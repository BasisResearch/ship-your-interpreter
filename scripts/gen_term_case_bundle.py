#!/usr/bin/env python3
"""Generate the 50-premise term-simulation bundle from its kernel-checked API.

The authoritative premise types remain on `term_sim_of_cases`.  This script
extracts those binders and emits one proof-only record plus thin wrappers for
the EvalE root, ExecSeq root, and `termSimClosed`.
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys


ROOT = pathlib.Path(__file__).resolve().parents[1]
ASSEMBLY = ROOT / "Vsa/Sim/TermSimAssembly.lean"
CLOSE = ROOT / "Vsa/Sim/TermSimClose.lean"
OUTPUT = ROOT / "Vsa/Sim/TermCaseBundle.lean"


def matching_paren(source: str, start: int) -> int:
    depth = 0
    for index in range(start, len(source)):
        char = source[index]
        if char == "(":
            depth += 1
        elif char == ")":
            depth -= 1
            if depth == 0:
                return index
    raise ValueError(f"unclosed binder at byte {start}")


def theorem_parts(source: str, theorem: str) -> tuple[list[tuple[str, str]], str]:
    marker = f"theorem {theorem}"
    start = source.index(marker) + len(marker)
    binders: list[tuple[str, str]] = []
    cursor = start
    while True:
        while cursor < len(source) and source[cursor].isspace():
            cursor += 1
        if cursor >= len(source) or source[cursor] != "(":
            break
        end = matching_paren(source, cursor)
        binder = source[cursor + 1 : end]
        match = re.match(r"([A-Za-z][A-Za-z0-9_]*)\s*:\s*([\s\S]*)", binder)
        if match is None:
            raise ValueError(f"unsupported binder in {theorem}: {binder[:80]!r}")
        binders.append((match.group(1), match.group(2).rstrip()))
        cursor = end + 1
    proof = source.index(":=", cursor)
    result = source[cursor:proof].strip()
    if result.startswith(":"):
        result = result[1:].strip()
    return binders, result


def indent_type(type_source: str, spaces: int = 4) -> str:
    prefix = " " * spaces
    return ("\n" + prefix).join(line.rstrip() for line in type_source.splitlines())


def render() -> str:
    assembly_source = ASSEMBLY.read_text()
    close_source = CLOSE.read_text()
    premise_binders, term_result = theorem_parts(assembly_source, "term_sim_of_cases")
    premises = [(name, ty) for name, ty in premise_binders if name.startswith("h")]
    if len(premises) != 50:
        raise ValueError(f"expected 50 term premises, found {len(premises)}")

    exec_binders, exec_result = theorem_parts(close_source, "execSeq_sim_of_cases")
    exec_names = [name for name, _ in exec_binders if name.startswith("h")]
    premise_names = [name for name, _ in premises]
    if exec_names != premise_names:
        raise ValueError("EvalE-root and ExecSeq-root premise orders differ")

    closed_binders, closed_result = theorem_parts(close_source, "termSimClosed")
    closed_names = [name for name, _ in closed_binders if name.startswith("h")]
    if closed_names[:-1] != premise_names or closed_names[-1] != "hEntryHalts":
        raise ValueError("termSimClosed premise order differs from the assembly API")
    entry_type = dict(closed_binders)["hEntryHalts"]

    lines = [
        "import Vsa.Sim.TermSimClose",
        "",
        "/-!",
        "# Generated term-case residual bundle",
        "",
        "Generated by `scripts/gen_term_case_bundle.py` from the authoritative",
        "`term_sim_of_cases`/`execSeq_sim_of_cases` signatures. Do not hand-edit.",
        "",
        "This proof-only record turns the 50 positional mutual-recursion premises",
        "into one named interface. Case-row generators can fill fields independently;",
        "the three wrappers below perform the positional assembly once.",
        "-/",
        "",
        "namespace Vsa.Sim.TermCaseBundle",
        "",
        "open LeanRV64DExecutable Sail",
        "open Register",
        "open Vsa.Machine (MState Config Halts)",
        "open Vsa.Logic",
        "open Vsa.RuntimeRepr",
        "open Vsa.MemRepr",
        "open Vsa.While",
        "open Vsa.Alloc",
        "open Vsa.Refine (Layout Loaded InterpSim)",
        "open Vsa.Sim",
        "open Vsa.Sim.Scaffold",
        "open Vsa.Sim.TermSimAssembly",
        "",
        "local notation \"SpecSt\" => Vsa.While.St",
        "",
        "/-- All mutual-recursion constructor simulations, named once. -/",
        "structure TermCases : Prop where",
    ]
    for name, type_source in premises:
        lines.append(f"  {name} :")
        lines.append(f"    {indent_type(type_source)}")

    projection_args = "\n      ".join(
        " ".join(f"B.{name}" for name in premise_names[index : index + 8])
        for index in range(0, len(premise_names), 8)
    )
    lines.extend(
        [
            "",
            "/-- EvalE-rooted mutual recursion from the named bundle. -/",
            "theorem term_sim_of_bundle (B : TermCases)",
            f"    {term_result} :=",
            "  Vsa.Sim.TermSimAssembly.term_sim_of_cases",
            f"      {projection_args}",
            "      t",
            "",
            "/-- ExecSeq-rooted mutual recursion from the same named bundle. -/",
            "theorem execSeq_sim_of_bundle (B : TermCases)",
            f"    {exec_result} :=",
            "  Vsa.Sim.TermSimClose.execSeq_sim_of_cases",
            f"      {projection_args}",
            "      t",
            "",
            "/-- `InterpSim.term_sim` from the case bundle and the sole entry bridge. -/",
            "theorem termSimClosed_of_bundle (L : Layout) (B : TermCases)",
            "    (hEntryHalts :",
            f"      {indent_type(entry_type, 6)}) :",
            f"    {closed_result} :=",
            "  Vsa.Sim.TermSimClose.termSimClosed L",
            f"      {projection_args}",
            "      hEntryHalts",
            "",
            "#print axioms term_sim_of_bundle",
            "#print axioms execSeq_sim_of_bundle",
            "#print axioms termSimClosed_of_bundle",
            "",
            "end Vsa.Sim.TermCaseBundle",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != generated:
            print(f"{OUTPUT.relative_to(ROOT)} is stale", file=sys.stderr)
            return 1
        print(f"{OUTPUT.relative_to(ROOT)}: up to date")
        return 0
    OUTPUT.write_text(generated)
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
