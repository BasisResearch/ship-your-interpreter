#!/usr/bin/env python3
"""Generate a Lean per-site StepObs battery from a TSV site list.

Emits site theorems in the house style of Vsa/Sim/SsputsSites.lean and the
sites section of Vsa/Sim/SnprintfSpec18.lean (the proven exemplars): one
`site_<addr><suffix>` theorem per line, each dispatching a single instruction
at a pinned code address through `stepObs_*` + the decode-table lemma + the
matching exec/execute helper.

TSV input (one site per line; blank lines and `#` comments ignored):

    <addr-hex>  <word-hex>  <class>  <operand fields...>

Classes (registers are decimal x-register numbers, immediates hex):

    alu_addi rd rs1 imm12          # addi/mv/li/sext-w-free moves
    addiw    rd rs1 imm12          # addiw / sext.w
    alu_add  rd rs1 rs2            # RTYPE ADD
    sub      rd rs1 rs2            # RTYPE SUB (64-bit)
    subw     rd rs1 rs2            # RTYPEW SUBW
    branch_taken    bop rs1 rs2 imm13   # bop in BEQ/BNE/BLT/BGE/BLTU/BGEU
    branch_nottaken bop rs1 rs2 imm13
    ld  rd rs1 imm12               # 8-byte load  (exec_ld)
    lw  rd rs1 imm12               # 4-byte load  (exec_lw)
    lbu rd rs1 imm12               # 1-byte load  (exec_lbu_gen)
    sd  rs2 rs1 imm12              # 8-byte store (exec_sd_val / writeMap8)
    sw  rs2 rs1 imm12              # 4-byte store (exec_sw / writeMap4)
    sb  rs2 rs1 imm12              # 1-byte store (exec_sb / insert)
    jal rd imm21                   # call (stepObs_jal)
    j   imm21                      # jal x0 (stepObs_j)
    jr  rs1                        # ret / jr (stepObs_jr, imm 0)

Example (selftest against the proven memmove sites in SnprintfSpec18):

    python3 scripts/gen_sites.py scripts/selftest_sites.tsv \
        --code-loaded Vsa.Sim.Code.MemmoveLoaded \
        --suffix _gen -o /tmp/selftest_sites.lean
    lake env lean /tmp/selftest_sites.lean

The `--code-loaded` predicate must come from a Vsa/Sim/Code/*.lean byte-pin
file (generated by experiments/gen_code_lemmas.py). The accessor prefix and
code module are derived from it (`Vsa.Sim.Code.MemmoveLoaded` ->
`Vsa.Sim.Code.memmove_at_<addr>` / `import Vsa.Sim.Code.Memmove`); override
with --code-accessor / --code-import when the derivation is wrong.

Decode-table imports are looked up per instruction word in
scripts/decode_index.tsv (regenerate with scripts/gen_decode_index.py).
"""

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_INDEX = ROOT / "scripts" / "decode_index.tsv"

BRANCH_OPS = {
    # bop -> (execute-lemma op fragment, guard format string)
    "BEQ":  ("beq",  "({v1} == {v2})"),
    "BNE":  ("bne",  "({v1} != {v2})"),
    "BLT":  ("blt",  "zopz0zI_s {v1} {v2}"),
    "BGE":  ("bge",  "zopz0zKzJ_s {v1} {v2}"),
    "BLTU": ("bltu", "zopz0zI_u {v1} {v2}"),
    "BGEU": ("bgeu", "zopz0zKzJ_u {v1} {v2}"),
}


def load_index(path: Path) -> dict[str, str]:
    index = {}
    for line in path.read_text().splitlines():
        if not line.strip():
            continue
        word, module = line.split("\t")
        index[word] = module
    return index


def word_bytes(word: int) -> list[str]:
    """Little-endian bytes b0..b3 of the 32-bit word, as Lean literals."""
    return [f"(0x{(word >> (8 * k)) & 0xff:02x}#8)" for k in range(4)]


def sext(value: int, bits: int) -> int:
    if value & (1 << (bits - 1)):
        value -= 1 << bits
    return value


def regidx(n: int) -> str:
    return f"regidx.Regidx 0x{n:02x}#5"


def vname(n: int) -> str:
    return f"(0#64)" if n == 0 else f"v{n}"


def rx_read(n: int, addr: int) -> str:
    """`hrsN` argument for an execute helper: register read on afterNextPC."""
    if n == 0:
        return "(rX_bits_zero _)"
    return (f"(rX_bits_x{n} _ v{n}\n"
            f"        (by rw [get?_afterNextPC σ (0x{addr:08x}#64) _ (by decide) "
            f"(by decide)]; exact hx{n}))")


def reg_hyp(n: int) -> str:
    return f"    (hx{n} : σ.regs.get? Register.x{n} = some v{n})\n"


def decode_block(word: int) -> str:
    return (f"    (Vsa.Sim.DecodeTable.decode_{word:08x} (afterPrelude σ)\n"
            "      (by rw [get?_afterPrelude σ _ (by decide)]; exact hG.misa)\n"
            "      (by rw [get?_afterPrelude σ _ (by decide)]; exact hG.cur_privilege)\n"
            "      (by rw [get?_afterPrelude σ _ (by decide)]; exact hG.mseccfg))")


def append_expr(nbytes: int) -> str:
    """Little-endian byte reassembly, e.g. ((((b3.append b2).append b1).append b0))."""
    expr = f"b{nbytes - 1}"
    first = True
    for k in range(nbytes - 2, -1, -1):
        expr = f"{expr}.append b{k}" if first else f"({expr}).append b{k}"
        first = False
    return f"(({expr}) : BitVec (8 * {nbytes}))"


class Site:
    def __init__(self, addr: int, word: int, cls: str, fields: list[str], lineno: int):
        self.addr = addr
        self.word = word
        self.cls = cls
        self.fields = fields
        self.lineno = lineno


class Emitter:
    def __init__(self, pred: str, accessor: str, suffix: str):
        self.pred = pred           # fully-qualified predicate, e.g. Vsa.Sim.Code.MemmoveLoaded
        self.accessor = accessor   # fully-qualified prefix, e.g. Vsa.Sim.Code.memmove_at_
        self.suffix = suffix

    # -- shared scaffolding ---------------------------------------------------

    def head(self, name: str, addr: int, doc: str, vregs: list[int],
             extra_params: str, reg_hyps: str, extra_hyps: str,
             mem_clause: str, post: str) -> str:
        vparams = " ".join(["vminstret"] + [f"v{n}" for n in vregs])
        return (
            f"/-- 0x{addr:08x}: {doc} -/\n"
            f"theorem {name} (σ : MState) (i u : Nat) (pc : BitVec 64) "
            f"({vparams} : BitVec 64){extra_params}\n"
            "    (hG : GoodState σ) (hpc : σ.regs.get? Register.PC = some pc)\n"
            "    (hminstret : σ.regs.get? Register.minstret = some vminstret)\n"
            f"{reg_hyps}"
            f"    (hmem : {self.pred} σ.mem)\n"
            f"    (hpcv : pc = (0x{addr:08x}#64 : BitVec 64))"
            f"{extra_hyps} (hi : i < 2) :\n"
            "    ∃ (σ' : MState) (i' : Nat),\n"
            "      Vsa.Machine.Step ⟨σ, i, u⟩ ⟨σ', i', u + 1⟩ ∧ i' < 2 ∧ GoodState σ' ∧\n"
            f"      {mem_clause} ∧\n"
            f"      ReadsLikePost σ' ({post}) := by\n"
            "  subst hpcv\n"
            f"  obtain ⟨hb0, hb1, hb2, hb3⟩ := {self.accessor}{self.addr_key(addr)} hmem\n"
        )

    @staticmethod
    def addr_key(addr: int) -> str:
        return f"{addr:08x}"

    def site_name(self, addr: int, variant: str = "") -> str:
        return f"site_{addr:08x}{variant}{self.suffix}"

    # -- ALU-shaped stepObs_alu call -----------------------------------------

    def alu_body(self, s: Site, instr: str, rd: int, value: str, exec_proof: str) -> str:
        b = word_bytes(s.word)
        return (
            f"  exact stepObs_alu σ i u (0x{s.addr:08x}#64) vminstret (0x{s.word:08x}#32)\n"
            f"    ({instr})\n"
            f"    Register.x{rd} {value}\n"
            f"    {b[0]} {b[1]} {b[2]} {b[3]}\n"
            "    hG hpc hminstret (by apply BitVec.eq_of_toNat_eq; decide)\n"
            "    (by apply BitVec.eq_of_toNat_eq; decide)\n"
            f"{decode_block(s.word)}\n"
            f"{exec_proof}\n"
            "    (by decide) (by decide) (by decide) (by decide) (by decide)\n"
            "    hb0 hb1 hb2 hb3 (by decide) (by decide) (by decide) hi\n"
        )

    # -- classes --------------------------------------------------------------

    def emit_alu_addi(self, s: Site) -> str:
        rd, rs1, imm = int(s.fields[0]), int(s.fields[1]), int(s.fields[2], 16)
        if rd == 0:
            raise ValueError(f"line {s.lineno}: alu_addi with rd=x0 unsupported")
        value = f"({vname(rs1)} + sign_extend (m := 64) (0x{imm:03x}#12))"
        instr = (f"instruction.ITYPE (0x{imm:03x}#12, {regidx(rs1)}, "
                 f"{regidx(rd)}, iop.ADDI)")
        exec_proof = (
            f"    (execute_itype_addi_char (0x{imm:03x}#12) ({regidx(rs1)}) "
            f"({regidx(rd)}) {vname(rs1)}\n"
            f"      (afterNextPC (afterPrelude σ) (0x{s.addr:08x}#64))\n"
            f"      (sigma3_alu σ (0x{s.addr:08x}#64) Register.x{rd} {value})\n"
            f"      {rx_read(rs1, s.addr)}\n"
            f"      (wX_bits_x{rd} _ {value}))")
        vregs = [rs1] if rs1 != 0 else []
        head = self.head(
            self.site_name(s.addr), s.addr,
            f"`addi x{rd},x{rs1},0x{imm:x}`.", vregs, "",
            reg_hyp(rs1) if rs1 != 0 else "", "",
            "σ'.mem = σ.mem",
            f"sigmaPost_alu σ pc vminstret Register.x{rd}\n        {value}")
        return head + self.alu_body(s, instr, rd, value, exec_proof)

    def emit_addiw(self, s: Site) -> str:
        rd, rs1, imm = int(s.fields[0]), int(s.fields[1]), int(s.fields[2], 16)
        if rd == 0:
            raise ValueError(f"line {s.lineno}: addiw with rd=x0 unsupported")
        value = (f"(sign_extend (m := 64)\n"
                 f"          (Sail.BitVec.extractLsb ({vname(rs1)} + "
                 f"sign_extend (m := 64) (0x{imm:03x}#12)) 31 0))")
        value_flat = (f"(sign_extend (m := 64) (Sail.BitVec.extractLsb "
                      f"({vname(rs1)} + sign_extend (m := 64) (0x{imm:03x}#12)) 31 0))")
        instr = f"instruction.ADDIW (0x{imm:03x}#12, {regidx(rs1)}, {regidx(rd)})"
        exec_proof = (
            f"    (execute_addiw_char (0x{imm:03x}#12) ({regidx(rs1)}) "
            f"({regidx(rd)}) {vname(rs1)}\n"
            f"      (afterNextPC (afterPrelude σ) (0x{s.addr:08x}#64))\n"
            f"      (sigma3_alu σ (0x{s.addr:08x}#64) Register.x{rd} {value_flat})\n"
            f"      {rx_read(rs1, s.addr)}\n"
            f"      (wX_bits_x{rd} _ {value_flat}))")
        vregs = [rs1] if rs1 != 0 else []
        head = self.head(
            self.site_name(s.addr), s.addr,
            f"`addiw x{rd},x{rs1},0x{imm:x}`.", vregs, "",
            reg_hyp(rs1) if rs1 != 0 else "", "",
            "σ'.mem = σ.mem",
            f"sigmaPost_alu σ pc vminstret Register.x{rd}\n        {value}")
        return head + self.alu_body(s, instr, rd, value_flat, exec_proof)

    def _rtype(self, s: Site, kind: str) -> str:
        rd, rs1, rs2 = int(s.fields[0]), int(s.fields[1]), int(s.fields[2])
        if rd == 0:
            raise ValueError(f"line {s.lineno}: {kind} with rd=x0 unsupported")
        v1, v2 = vname(rs1), vname(rs2)
        if kind == "alu_add":
            value = f"({v1} + {v2})"
            instr = (f"instruction.RTYPE ({regidx(rs2)}, {regidx(rs1)}, "
                     f"{regidx(rd)}, rop.ADD)")
            helper = "execute_rtype_add_char"
            asm = f"`add x{rd},x{rs1},x{rs2}`."
        elif kind == "sub":
            value = f"({v1} - {v2})"
            instr = (f"instruction.RTYPE ({regidx(rs2)}, {regidx(rs1)}, "
                     f"{regidx(rd)}, rop.SUB)")
            helper = "execute_rtype_sub_char"
            asm = f"`sub x{rd},x{rs1},x{rs2}`."
        else:  # subw
            value = (f"(sign_extend (m := 64)\n"
                     f"          ((Sail.BitVec.extractLsb {v1} 31 0) - "
                     f"(Sail.BitVec.extractLsb {v2} 31 0)))")
            instr = (f"instruction.RTYPEW ({regidx(rs2)}, {regidx(rs1)}, "
                     f"{regidx(rd)}, ropw.SUBW)")
            helper = "execute_rtypew_subw_char"
            asm = f"`subw x{rd},x{rs1},x{rs2}`."
        value_flat = " ".join(value.split())
        exec_proof = (
            f"    ({helper} ({regidx(rs2)}) ({regidx(rs1)}) ({regidx(rd)})\n"
            f"      {v1} {v2} (afterNextPC (afterPrelude σ) (0x{s.addr:08x}#64))\n"
            f"      (sigma3_alu σ (0x{s.addr:08x}#64) Register.x{rd} {value_flat})\n"
            f"      {rx_read(rs1, s.addr)}\n"
            f"      {rx_read(rs2, s.addr)}\n"
            f"      (wX_bits_x{rd} _ {value_flat}))")
        vregs = [n for n in dict.fromkeys([rs1, rs2]) if n != 0]
        head = self.head(
            self.site_name(s.addr), s.addr, asm, vregs, "",
            "".join(reg_hyp(n) for n in vregs), "",
            "σ'.mem = σ.mem",
            f"sigmaPost_alu σ pc vminstret Register.x{rd} {value}")
        return head + self.alu_body(s, instr, rd, value_flat, exec_proof)

    def emit_alu_add(self, s: Site) -> str:
        return self._rtype(s, "alu_add")

    def emit_sub(self, s: Site) -> str:
        return self._rtype(s, "sub")

    def emit_subw(self, s: Site) -> str:
        return self._rtype(s, "subw")

    def _branch(self, s: Site, taken: bool) -> str:
        bop, rs1, rs2 = s.fields[0], int(s.fields[1]), int(s.fields[2])
        imm = int(s.fields[3], 16)
        if bop not in BRANCH_OPS:
            raise ValueError(f"line {s.lineno}: unknown bop {bop}")
        opfrag, guard_fmt = BRANCH_OPS[bop]
        v1, v2 = vname(rs1), vname(rs2)
        guard = guard_fmt.format(v1=v1, v2=v2)
        variant = "_taken" if taken else "_nottaken"
        name = self.site_name(s.addr, variant)
        vregs = [n for n in dict.fromkeys([rs1, rs2]) if n != 0]
        b = word_bytes(s.word)
        hv = f"\n    (hv : {guard} = {'true' if taken else 'false'})"
        tgt = (s.addr + sext(imm, 13)) % (1 << 64)
        pre = ""
        if taken:
            post = f"sigmaPost_branch_taken σ pc vminstret (0x{imm:04x}#13)"
            asm = (f"`{bop.lower()} x{rs1},x{rs2} → 0x{tgt:x}` (TAKEN).")
            # Per-site target-collapse lemma (mirrors `bne_target_mv`).
            pre = (
                f"/-- Branch target of the taken site at 0x{s.addr:08x}. -/\n"
                f"theorem {name}_tgt :\n"
                f"    (0x{s.addr:08x}#64 + sign_extend (m := 64) (0x{imm:04x}#13)) "
                f"= (0x{tgt:08x}#64 : BitVec 64) := by\n"
                "  apply BitVec.eq_of_toNat_eq; decide\n\n")
            exec_proof = (
                f"    (execute_btype_{opfrag}_taken (0x{imm:04x}#13) ({regidx(rs1)}) "
                f"({regidx(rs2)})\n"
                f"      {v1} {v2} (0x{s.addr:08x}#64) initMisa "
                f"(afterNextPC (afterPrelude σ) (0x{s.addr:08x}#64))\n"
                f"      {rx_read(rs1, s.addr)}\n"
                f"      {rx_read(rs2, s.addr)}\n"
                f"      (by rw [get?_afterNextPC σ (0x{s.addr:08x}#64) _ (by decide) "
                "(by decide)]; exact hpc)\n"
                f"      (by rw [get?_afterNextPC σ (0x{s.addr:08x}#64) _ (by decide) "
                "(by decide)]; exact hG.misa)\n"
                f"      (by rw [{name}_tgt]; decide) hv)")
        else:
            post = "sigmaPost_branch_nottaken σ pc vminstret"
            asm = f"`{bop.lower()} x{rs1},x{rs2}` (NOT taken)."
            exec_proof = (
                f"    (execute_btype_{opfrag}_nottaken (0x{imm:04x}#13) ({regidx(rs1)}) "
                f"({regidx(rs2)})\n"
                f"      {v1} {v2} (afterNextPC (afterPrelude σ) (0x{s.addr:08x}#64))\n"
                f"      {rx_read(rs1, s.addr)}\n"
                f"      {rx_read(rs2, s.addr)}\n"
                "      hv)")
        head = self.head(
            name, s.addr, asm, vregs, "",
            "".join(reg_hyp(n) for n in vregs), hv,
            "σ'.mem = σ.mem", post)
        body = (
            f"  exact stepObs_branch{variant} σ i u (0x{s.addr:08x}#64) vminstret "
            f"(0x{imm:04x}#13)\n"
            f"    ({regidx(rs1)}) ({regidx(rs2)}) bop.{bop} (0x{s.word:08x}#32)\n"
            f"    {b[0]} {b[1]} {b[2]} {b[3]}\n"
            "    hG hpc hminstret (by apply BitVec.eq_of_toNat_eq; decide)\n"
            "    (by apply BitVec.eq_of_toNat_eq; decide)\n"
            f"{decode_block(s.word)}\n"
            f"{exec_proof}\n"
            "    hb0 hb1 hb2 hb3 (by decide) (by decide) (by decide) hi\n"
        )
        return pre + head + body

    def emit_branch_taken(self, s: Site) -> str:
        return self._branch(s, True)

    def emit_branch_nottaken(self, s: Site) -> str:
        return self._branch(s, False)

    def _load_wide(self, s: Site, nbytes: int) -> str:
        rd, rs1, imm = int(s.fields[0]), int(s.fields[1]), int(s.fields[2], 16)
        if rd == 0 or rs1 == 0:
            raise ValueError(f"line {s.lineno}: load with x0 operand unsupported")
        mn = {8: "ld", 4: "lw"}[nbytes]
        ea = f"(v{rs1} + sign_extend (m := 64) (0x{imm:03x}#12))"
        app = append_expr(nbytes)
        value = f"(sign_extend (m := 64) {app})"
        bparams = " ".join(f"b{k}" for k in range(nbytes))
        extra_params = f"\n    ({bparams} : BitVec 8)"
        byte_hyps = "".join(
            f"    (h{k} : σ.mem[{ea}.toNat{f' + {k}' if k else ''}]? = some b{k})\n"
            for k in range(nbytes))
        extra_hyps = (
            f"\n    (hlo : 0x80000000 ≤ {ea}.toNat)\n"
            f"    (hhiram : {ea}.toNat + {nbytes} ≤ 0x100000000)\n"
            f"    (hhtif : {ea}.toNat + {nbytes} ≤ tohostAddr\n"
            f"      ∨ tohostAddr + 8 ≤ {ea}.toNat)\n"
            f"    (halign : {ea}.toNat % {nbytes} = 0)\n"
            f"{byte_hyps}   "  # trailing spaces so ` (hi : i < 2)` lines up
        )
        instr = (f"instruction.LOAD (0x{imm:03x}#12, {regidx(rs1)}, "
                 f"{regidx(rd)}, false, {nbytes})")
        hs = " ".join(f"h{k}" for k in range(nbytes))
        bs = " ".join(f"b{k}" for k in range(nbytes))
        exec_proof = (
            f"    (exec_{mn} σ (0x{s.addr:08x}#64) (0x{imm:03x}#12) ({regidx(rs1)}) "
            f"({regidx(rd)})\n"
            f"      (sigma3_alu σ (0x{s.addr:08x}#64) Register.x{rd} {value})\n"
            f"      v{rs1} {bs} hG\n"
            f"      {rx_read(rs1, s.addr)}\n"
            f"      (wX_bits_x{rd} _ {value})\n"
            f"      hlo hhiram hhtif halign {hs})")
        head = self.head(
            self.site_name(s.addr), s.addr,
            f"`{mn} x{rd},0x{imm:x}(x{rs1})`.", [rs1], extra_params,
            reg_hyp(rs1), extra_hyps,
            "σ'.mem = σ.mem",
            f"sigmaPost_alu σ pc vminstret Register.x{rd}\n"
            f"        (sign_extend (m := 64)\n          {app})")
        return head + self.alu_body(s, instr, rd, value, exec_proof)

    def emit_ld(self, s: Site) -> str:
        return self._load_wide(s, 8)

    def emit_lw(self, s: Site) -> str:
        return self._load_wide(s, 4)

    def emit_lbu(self, s: Site) -> str:
        rd, rs1, imm = int(s.fields[0]), int(s.fields[1]), int(s.fields[2], 16)
        if rd == 0 or rs1 == 0:
            raise ValueError(f"line {s.lineno}: lbu with x0 operand unsupported")
        ea = f"(v{rs1} + sign_extend (m := 64) (0x{imm:03x}#12))"
        value = "(zero_extend (m := 64) b)"
        extra_params = "\n    (b : BitVec 8)"
        extra_hyps = (
            f"\n    (hlo : 0x80000000 ≤ {ea}.toNat)\n"
            f"    (hhiram : {ea}.toNat + 1 ≤ 0x100000000)\n"
            f"    (hhtif : {ea}.toNat + 1 ≤ tohostAddr\n"
            f"      ∨ tohostAddr + 8 ≤ {ea}.toNat)\n"
            f"    (hb : σ.mem[{ea}.toNat]? = some b)\n   ")
        instr = (f"instruction.LOAD (0x{imm:03x}#12, {regidx(rs1)}, "
                 f"{regidx(rd)}, true, 1)")
        exec_proof = (
            f"    (exec_lbu_gen σ (0x{s.addr:08x}#64) (0x{imm:03x}#12) ({regidx(rs1)}) "
            f"({regidx(rd)})\n"
            f"      v{rs1} b (sigma3_alu σ (0x{s.addr:08x}#64) Register.x{rd} {value}) hG\n"
            f"      {rx_read(rs1, s.addr)}\n"
            f"      (wX_bits_x{rd} _ {value})\n"
            "      hlo hhiram hhtif hb)")
        head = self.head(
            self.site_name(s.addr), s.addr,
            f"`lbu x{rd},0x{imm:x}(x{rs1})`.", [rs1], extra_params,
            reg_hyp(rs1), extra_hyps,
            "σ'.mem = σ.mem",
            f"sigmaPost_alu σ pc vminstret Register.x{rd} {value}")
        return head + self.alu_body(s, instr, rd, value, exec_proof)

    def _store(self, s: Site, nbytes: int) -> str:
        rs2, rs1, imm = int(s.fields[0]), int(s.fields[1]), int(s.fields[2], 16)
        if rs1 == 0:
            raise ValueError(f"line {s.lineno}: store with rs1=x0 unsupported")
        mn = {8: "sd", 4: "sw", 1: "sb"}[nbytes]
        ea = f"(v{rs1} + sign_extend (m := 64) (0x{imm:03x}#12))"
        v2 = vname(rs2)
        if nbytes == 8:
            mem_val = (f"writeMap8 (afterNextPC (afterPrelude σ) "
                       f"(0x{s.addr:08x}#64)).mem\n"
                       f"        {ea}.toNat (sdData_val {v2})")
            helper, hkind = "exec_sd_val", "map"
        elif nbytes == 4:
            mem_val = (f"writeMap4 (afterNextPC (afterPrelude σ) "
                       f"(0x{s.addr:08x}#64)).mem\n"
                       f"        {ea}.toNat (swData {v2})")
            helper, hkind = "exec_sw", "map"
        else:
            mem_val = (f"((afterNextPC (afterPrelude σ) (0x{s.addr:08x}#64)).mem.insert\n"
                       f"        {ea}.toNat (stData 1 {v2}))")
            helper, hkind = "exec_sb", "insert"
        mem_val_flat = " ".join(mem_val.split())
        if hkind == "map":
            extra_hyps = (
                f"\n    (halo : 0x80000000 ≤ {ea}.toNat)\n"
                f"    (hahiram : {ea}.toNat + {nbytes} ≤ 0x100000000)\n"
                f"    (hahiwin : tohostAddr + 16 ≤ {ea}.toNat)\n"
                f"    (haalign : {ea}.toNat % {nbytes} = 0)")
            side_hyps = "halo hahiram hahiwin haalign"
        else:
            extra_hyps = (
                f"\n    (hlo : 0x80000000 ≤ {ea}.toNat)\n"
                f"    (hhiram : {ea}.toNat + 1 ≤ 0x100000000)\n"
                f"    (hhiwin : tohostAddr + 16 ≤ {ea}.toNat)")
            side_hyps = "hlo hhiram hhiwin"
        instr = (f"instruction.STORE (0x{imm:03x}#12, {regidx(rs2)}, "
                 f"{regidx(rs1)}, {nbytes})")
        b = word_bytes(s.word)
        vregs = [n for n in dict.fromkeys([rs1, rs2]) if n != 0]
        head = self.head(
            self.site_name(s.addr), s.addr,
            f"`{mn} x{rs2},0x{imm:x}(x{rs1})`.", vregs, "",
            "".join(reg_hyp(n) for n in vregs), extra_hyps,
            f"σ'.mem = {mem_val}",
            f"sigmaPost_store σ pc vminstret\n        ({mem_val_flat})")
        body = (
            f"  exact stepObs_store σ i u (0x{s.addr:08x}#64) vminstret "
            f"(0x{s.word:08x}#32)\n"
            f"    ({instr})\n"
            f"    ({mem_val_flat})\n"
            f"    {b[0]} {b[1]} {b[2]} {b[3]}\n"
            "    hG hpc hminstret (by apply BitVec.eq_of_toNat_eq; decide)\n"
            "    (by apply BitVec.eq_of_toNat_eq; decide)\n"
            f"{decode_block(s.word)}\n"
            f"    ({helper} σ (0x{s.addr:08x}#64) (0x{imm:03x}#12) ({regidx(rs2)}) "
            f"({regidx(rs1)})\n"
            f"      v{rs1} {v2} hG\n"
            f"      {rx_read(rs1, s.addr)}\n"
            f"      {rx_read(rs2, s.addr)}\n"
            f"      {side_hyps})\n"
            "    hb0 hb1 hb2 hb3 (by decide) (by decide) (by decide) hi\n"
        )
        return head + body

    def emit_sd(self, s: Site) -> str:
        return self._store(s, 8)

    def emit_sw(self, s: Site) -> str:
        return self._store(s, 4)

    def emit_sb(self, s: Site) -> str:
        return self._store(s, 1)

    def emit_jal(self, s: Site) -> str:
        rd, imm = int(s.fields[0]), int(s.fields[1], 16)
        if rd == 0:
            raise ValueError(f"line {s.lineno}: jal with rd=x0 is class `j`")
        tgt = (s.addr + sext(imm, 21)) % (1 << 64)
        b = word_bytes(s.word)
        head = self.head(
            self.site_name(s.addr), s.addr,
            f"`jal x{rd},0x{tgt:x}` (link `x{rd} := 0x{(s.addr + 4):x}`).", [], "",
            "", "",
            "σ'.mem = σ.mem",
            f"sigmaPost_jal σ pc vminstret (0x{imm:06x}#21) Register.x{rd} "
            "(BitVec.addInt pc 4)")
        body = (
            f"  refine stepObs_jal σ i u (0x{s.addr:08x}#64) vminstret "
            f"(0x{s.word:08x}#32) (0x{imm:06x}#21)\n"
            f"    ({regidx(rd)}) Register.x{rd} (BitVec.addInt (0x{s.addr:08x}#64) 4)\n"
            f"    {b[0]} {b[1]} {b[2]} {b[3]}\n"
            "    hG hpc hminstret hb0 hb1 hb2 hb3 (by decide) (by decide) (by decide)\n"
            "    (by apply BitVec.eq_of_toNat_eq; decide) "
            "(by apply BitVec.eq_of_toNat_eq; decide)\n"
            f"{decode_block(s.word)}\n"
            "    (by decide)\n"
            "    (by decide) (by decide) (by decide) (by decide) (by decide) ?_ hi\n"
            f"  exact wX_bits_x{rd} _ (BitVec.addInt (0x{s.addr:08x}#64) 4)\n"
        )
        return head + body

    def emit_j(self, s: Site) -> str:
        imm = int(s.fields[0], 16)
        tgt = (s.addr + sext(imm, 21)) % (1 << 64)
        b = word_bytes(s.word)
        extra_hyps = (
            f"\n    (htgt : (pc + sign_extend (m := 64) (0x{imm:06x}#21)).toNat % 4 = 0)")
        head = self.head(
            self.site_name(s.addr), s.addr,
            f"`j 0x{tgt:x}`.", [], "", "", extra_hyps,
            "σ'.mem = σ.mem",
            f"sigmaPost_jump_x0 σ pc vminstret "
            f"(pc + sign_extend (m := 64) (0x{imm:06x}#21))")
        body = (
            f"  exact stepObs_j σ i u (0x{s.addr:08x}#64) vminstret "
            f"(0x{s.word:08x}#32) (0x{imm:06x}#21)\n"
            f"    {b[0]} {b[1]} {b[2]} {b[3]}\n"
            "    hG hpc hminstret hb0 hb1 hb2 hb3 (by decide) (by decide) (by decide) "
            "(by decide)\n"
            "    (by apply BitVec.eq_of_toNat_eq; decide)\n"
            f"{decode_block(s.word)}\n"
            "    htgt hi\n"
        )
        return head + body

    def emit_jr(self, s: Site) -> str:
        rs1 = int(s.fields[0])
        if rs1 == 0:
            raise ValueError(f"line {s.lineno}: jr with rs1=x0 unsupported")
        b = word_bytes(s.word)
        upd = (f"(BitVec.update (v{rs1} + sign_extend (m := 64) (0x000#12)) 0 0#1)")
        extra_hyps = f"\n    (htgt : {upd}.toNat % 4 = 0)\n   "
        head = self.head(
            self.site_name(s.addr), s.addr,
            f"`jr x{rs1}`{' (`ret`)' if rs1 == 1 else ''}.", [rs1], "",
            reg_hyp(rs1), extra_hyps,
            "σ'.mem = σ.mem",
            f"sigmaPost_jump_x0 σ pc vminstret\n          {upd}")
        body = (
            f"  exact stepObs_jr σ i u (0x{s.addr:08x}#64) vminstret v{rs1} "
            f"(0x{s.word:08x}#32) (0x000#12)\n"
            f"    ({regidx(rs1)}) {b[0]} {b[1]} {b[2]} {b[3]}\n"
            "    hG hpc hminstret hb0 hb1 hb2 hb3 (by decide) (by decide) (by decide)\n"
            "    (by apply BitVec.eq_of_toNat_eq; decide) "
            "(by apply BitVec.eq_of_toNat_eq; decide)\n"
            f"{decode_block(s.word)}\n"
            f"    (rX_bits_x{rs1} _ v{rs1}\n"
            f"      (by rw [get?_afterNextPC σ (0x{s.addr:08x}#64) _ (by decide) "
            f"(by decide)]; exact hx{rs1}))\n"
            "    htgt hi\n"
        )
        return head + body


CLASS_EMITTERS = {
    "alu_addi": "emit_alu_addi",
    "addiw": "emit_addiw",
    "alu_add": "emit_alu_add",
    "sub": "emit_sub",
    "subw": "emit_subw",
    "branch_taken": "emit_branch_taken",
    "branch_nottaken": "emit_branch_nottaken",
    "ld": "emit_ld",
    "lw": "emit_lw",
    "lbu": "emit_lbu",
    "sd": "emit_sd",
    "sw": "emit_sw",
    "sb": "emit_sb",
    "jal": "emit_jal",
    "j": "emit_j",
    "jr": "emit_jr",
}

NEEDS_STRCPY_SITES = {"lbu", "sb"}


def parse_sites(path: Path) -> list[Site]:
    sites = []
    for lineno, raw in enumerate(path.read_text().splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split()
        if len(parts) < 3:
            raise ValueError(f"line {lineno}: expected addr word class ...")
        addr, word, cls = int(parts[0], 16), int(parts[1], 16), parts[2]
        if cls not in CLASS_EMITTERS:
            raise ValueError(f"line {lineno}: unknown class {cls}")
        sites.append(Site(addr, word, cls, parts[3:], lineno))
    return sites


def derive_code_names(pred: str, accessor: str | None, code_import: str | None):
    """Vsa.Sim.Code.MemmoveLoaded -> (Vsa.Sim.Code.memmove_at_, Vsa.Sim.Code.Memmove)."""
    prefix, _, last = pred.rpartition(".")
    if last.endswith("Loaded"):
        stem = last[: -len("Loaded")]
    else:
        stem = last
    if accessor is None:
        acc_stem = stem if stem.startswith("_") else stem[0].lower() + stem[1:]
        accessor = f"{prefix}.{acc_stem}_at_" if prefix else f"{acc_stem}_at_"
    if code_import is None:
        code_import = f"{prefix}.{stem}" if prefix else stem
    return accessor, code_import


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("sites_tsv", type=Path)
    ap.add_argument("-o", "--output", type=Path, required=True)
    ap.add_argument("--code-loaded", required=True,
                    help="fully-qualified byte-pin predicate, "
                         "e.g. Vsa.Sim.Code.MemmoveLoaded")
    ap.add_argument("--code-accessor", default=None,
                    help="fully-qualified accessor prefix "
                         "(default derived: Vsa.Sim.Code.memmove_at_)")
    ap.add_argument("--code-import", default=None,
                    help="Lean module of the Code file "
                         "(default derived: Vsa.Sim.Code.Memmove)")
    ap.add_argument("--suffix", default="",
                    help="suffix appended to every site theorem name, e.g. _gen")
    ap.add_argument("--namespace", default="Vsa.Sim")
    ap.add_argument("--index", type=Path, default=DEFAULT_INDEX,
                    help="decode_index.tsv (word -> DecodeTable module)")
    args = ap.parse_args()

    sites = parse_sites(args.sites_tsv)
    if not sites:
        print("error: no sites in input", file=sys.stderr)
        return 1
    index = load_index(args.index)
    accessor, code_import = derive_code_names(
        args.code_loaded, args.code_accessor, args.code_import)

    decode_imports = set()
    for s in sites:
        key = f"{s.word:08x}"
        if key not in index:
            print(f"error: no decode lemma for word {key} "
                  f"(line {s.lineno}); regenerate {args.index}?", file=sys.stderr)
            return 1
        decode_imports.add(index[key])

    imports = ["Vsa.Sim.ValueSites"]
    if any(s.cls in NEEDS_STRCPY_SITES for s in sites):
        imports.append("Vsa.Sim.StrcpySites")
    imports.append(code_import)
    imports.extend(sorted(decode_imports))

    em = Emitter(args.code_loaded, accessor, args.suffix)
    theorems = []
    for s in sites:
        theorems.append(getattr(em, CLASS_EMITTERS[s.cls])(s))

    out = []
    out.append("\n".join(f"import {m}" for m in imports))
    out.append(f"""
/-!
Per-site `StepObs` battery generated by scripts/gen_sites.py from
{args.sites_tsv.name} against `{args.code_loaded}`.
Do not hand-edit; regenerate instead.
-/

open LeanRV64DExecutable LeanRV64DExecutable.Functions Sail ConcurrencyInterfaceV1 Vsa
open Register
open Sail.ConcurrencyInterfaceV1.PreSail
open Vsa.Machine (MState Config Step Steps)

set_option maxHeartbeats 8000000
set_option maxRecDepth 1000000

namespace {args.namespace}
""")
    out.append("\n".join(theorems))
    out.append(f"end {args.namespace}\n")

    args.output.write_text("\n".join(out))
    print(f"wrote {args.output} ({len(theorems)} site theorems, "
          f"{len(decode_imports)} decode imports)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
