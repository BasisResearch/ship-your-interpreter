#!/usr/bin/env python3
"""gen_iris_cases.py — the Iris case generator (lane G, INTERP_DESIGN.md §6).

Reads `scripts/iris_arms/arms.tsv` (one row per machine arm of `eval_expr` /
`exec_stmt`) and the disassembly `experiments/disasm.txt`, and writes one
total case `VsaIris/Interp/Case/<Arm>T.lean` and one partial case
`VsaIris/Interp/Case/<Arm>P.lean` per row. The row format and the step
language are documented in LANE.md ("Row format"); this module's interface is:

    rows = load_rows()                 # list[Arm], validated against the disassembly
    text = emit(arm, "T" | "P")        # the generated Lean source of one case
    write_all(check=False)             # (re)write every case; check=True: fail on drift

Usage:
    python3 -B scripts/gen_iris_cases.py            # regenerate every case
    python3 -B scripts/gen_iris_cases.py --check    # drift gate (check_all.sh stage a3)
    python3 -B scripts/gen_iris_cases.py --list     # print the parsed rows
"""
from __future__ import annotations

import argparse
import dataclasses
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
ARMS = ROOT / "scripts/iris_arms/arms.tsv"
DISASM = ROOT / "experiments/disasm.txt"
OUT = ROOT / "VsaIris/Interp/Case"

EVAL_ENTRY = 0x80003164
EXEC_ENTRY = 0x80003FE0
ENTRY = {"eval": EVAL_ENTRY, "exec": EXEC_ENTRY}
HEADER = "-- GENERATED by scripts/gen_iris_cases.py from scripts/iris_arms/arms.tsv. Do not edit.\n"


# ------------------------------------------------------------------ disassembly
def load_disasm() -> dict[int, tuple[int, str, str]]:
    """pc -> (word, mnemonic, operands)."""
    code = {}
    for line in DISASM.read_text().splitlines():
        m = re.match(r"^\s+([0-9a-f]+):\t([0-9a-f]{8})\s+\t(\S+)\s*(.*)$", line)
        if m:
            code[int(m.group(1), 16)] = (int(m.group(2), 16), m.group(3), m.group(4))
    return code


def jal_target(word: int, pc: int) -> int | None:
    """Target of a `jal ra, tgt` word at `pc` (None if not a linking jal)."""
    if word & 0x7F != 0x6F or (word >> 7) & 31 != 1:
        return None
    imm = (((word >> 31) & 1) << 20 | ((word >> 12) & 0xFF) << 12
           | ((word >> 20) & 1) << 11 | ((word >> 21) & 0x3FF) << 1)
    if imm >> 20:
        imm -= 1 << 21
    return (pc + imm) & ((1 << 64) - 1)


# ------------------------------------------------------------------ rows
@dataclasses.dataclass
class Child:
    var: str          # the ctor variable naming the child (`l`, `r`, `e`, `s`)
    kind: str         # "E" (eval_expr child) or "S" (exec_stmt child)
    value: str        # the child's outcome pattern (value for E, status for S)
    slot: int         # sret/ret slot offset in the arm's frame


@dataclasses.dataclass
class Step:
    op: str           # run | child | helper | ret
    args: list[str]


@dataclasses.dataclass
class Divert:
    kind: str         # kind | zero | arity | depth | ... (the error family)
    at: int           # branch PC whose other polarity leaves the row
    to: int           # where that polarity goes


@dataclasses.dataclass
class Arm:
    name: str
    fn: str
    tag: int
    ctor: str
    children: list[Child]
    result: str
    steps: list[Step]
    errors: list[Divert]


def parse_row(cols: list[str]) -> Arm:
    name, fn, tag, ctor, children, result, steps, errors = cols
    ch = []
    for c in filter(None, (x.strip() for x in children.split(";"))):
        var, kind, value, slot = c.split(":")
        ch.append(Child(var, kind, value, int(slot, 0)))
    st = []
    for s in filter(None, (x.strip() for x in steps.split(";"))):
        op, *args = s.split()
        st.append(Step(op, args))
    er = []
    for e in filter(None, (x.strip() for x in errors.split(";"))):
        kind, at, to = e.split(":")
        er.append(Divert(kind, int(at, 0), int(to, 0)))
    return Arm(name, fn, int(tag), ctor, ch, result, st, er)


def validate(arm: Arm, code: dict[int, tuple[int, str, str]]) -> None:
    """Structural checks against the binary: runs start/stop at instructions,
    child calls are `jal` into the recursive entry, the first run starts at the
    function entry and the last ends in `ret`."""
    def err(msg: str) -> None:
        raise SystemExit(f"arms.tsv: {arm.name}: {msg}")
    if arm.fn not in ENTRY:
        err(f"fn must be eval|exec, got {arm.fn}")
    runs = [s for s in arm.steps if s.op == "run"]
    if not runs or int(runs[0].args[0], 0) != ENTRY[arm.fn]:
        err("the first step must be a run from the function entry")
    if arm.steps[-1].op != "run" or arm.steps[-1].args[1] != "ret":
        err("the last step must be a run ending in ret")
    names = {c.var for c in arm.children}
    for s in arm.steps:
        if s.op == "run":
            a = int(s.args[0], 0)
            if a not in code:
                err(f"run start {a:#x} is not an instruction")
            if s.args[1] != "ret" and int(s.args[1], 0) not in code:
                err(f"run stop {s.args[1]} is not an instruction")
        elif s.op == "child":
            var, pc = s.args[0], int(s.args[1], 0)
            if var not in names:
                err(f"child {var} not declared in the children column")
            tgt = jal_target(code[pc][0], pc) if pc in code else None
            kind = next(c.kind for c in arm.children if c.var == var)
            want = EVAL_ENTRY if kind == "E" else EXEC_ENTRY
            if tgt != want:
                err(f"child call at {pc:#x} is not `jal {want:#x}`")
        elif s.op == "helper":
            pc = int(s.args[1], 0)
            if pc not in code or jal_target(code[pc][0], pc) is None:
                err(f"helper call at {pc:#x} is not a linking jal")
        else:
            err(f"unknown step {s.op}")
    for d in arm.errors:
        if d.at not in code:
            err(f"error divert {d.at:#x} is not an instruction")


def load_rows() -> list[Arm]:
    code = load_disasm()
    rows = []
    for line in ARMS.read_text().splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        arm = parse_row(line.split("\t"))
        validate(arm, code)
        rows.append(arm)
    return rows


# ------------------------------------------------------------------ emitters
def emit(arm: Arm, mode: str) -> str:
    """The Lean source of one generated case. Filled in by the case emitters
    (`emit_total` / `emit_partial`) once the arm layer is in place."""
    raise NotImplementedError(f"emitter for mode {mode}")


def write_all(check: bool = False) -> int:
    rows = load_rows()
    stale = []
    for arm in rows:
        for mode in ("T", "P"):
            try:
                text = HEADER + emit(arm, mode)
            except NotImplementedError:
                continue
            path = OUT / f"{arm.name}{mode}.lean"
            if check:
                if not path.exists() or path.read_text() != text:
                    stale.append(path)
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text)
    for p in stale:
        print(f"stale: {p.relative_to(ROOT)}", file=sys.stderr)
    return 1 if stale else 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--list", action="store_true")
    a = ap.parse_args()
    if a.list:
        for arm in load_rows():
            print(arm)
        return 0
    return write_all(check=a.check)


if __name__ == "__main__":
    sys.exit(main())
