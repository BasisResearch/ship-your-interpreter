#!/usr/bin/env python3
"""gen_iris_cases.py — the Iris case generator (lane G, INTERP_DESIGN.md §6).

Reads `scripts/iris_arms/arms.tsv` (one row per machine arm of `eval_expr` /
`exec_stmt`) and the disassembly `experiments/disasm.txt`, and writes one
total case `VsaIris/Interp/Case/<Arm>T.lean` and one partial case
`VsaIris/Interp/Case/<Arm>P.lean` per row. The row format and the step
language are documented in LANE.md ("Row format"); this module's interface is:

    rows = load_rows()                 # list[Arm], validated against the disassembly
    text = emit(arm, "T" | "P")        # the generated Lean source of one case
    write_all(check=False)             # (re)write every case; check=True: fail on drift

Usage:
    python3 -B scripts/gen_iris_cases.py            # regenerate every case
    python3 -B scripts/gen_iris_cases.py --check    # drift gate (check_all.sh stage a3)
    python3 -B scripts/gen_iris_cases.py --list     # print the parsed rows
"""
from __future__ import annotations

import argparse
import dataclasses
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
ARMS = ROOT / "scripts/iris_arms/arms.tsv"
DISASM = ROOT / "experiments/disasm.txt"
OUT = ROOT / "VsaIris/Interp/Case"
TEMPLATES = ROOT / "scripts/iris_arms/templates"

EVAL_ENTRY = 0x80003164
EXEC_ENTRY = 0x80003FE0
ENTRY = {"eval": EVAL_ENTRY, "exec": EXEC_ENTRY}
HEADER = "-- GENERATED by scripts/gen_iris_cases.py from scripts/iris_arms/arms.tsv. Do not edit.\n"


# ------------------------------------------------------------------ disassembly
def load_disasm() -> dict[int, tuple[int, str, str]]:
    """pc -> (word, mnemonic, operands)."""
    code = {}
    for line in DISASM.read_text().splitlines():
        m = re.match(r"^\s+([0-9a-f]+):\t([0-9a-f]{8})\s+\t(\S+)\s*(.*)$", line)
        if m:
            code[int(m.group(1), 16)] = (int(m.group(2), 16), m.group(3), m.group(4))
    return code


def jal_target(word: int, pc: int) -> int | None:
    """Target of a `jal ra, tgt` word at `pc` (None if not a linking jal)."""
    if word & 0x7F != 0x6F or (word >> 7) & 31 != 1:
        return None
    imm = (((word >> 31) & 1) << 20 | ((word >> 12) & 0xFF) << 12
           | ((word >> 20) & 1) << 11 | ((word >> 21) & 0x3FF) << 1)
    if imm >> 20:
        imm -= 1 << 21
    return (pc + imm) & ((1 << 64) - 1)


# ------------------------------------------------------------------ rows
@dataclasses.dataclass
class Child:
    var: str          # the ctor variable naming the child (`l`, `r`, `e`, `s`)
    kind: str         # "E" (eval_expr child) or "S" (exec_stmt child)
    value: str        # the child's outcome pattern (value for E, status for S)
    slot: int         # sret/ret slot offset in the arm's frame


@dataclasses.dataclass
class Step:
    op: str           # run | child | helper | ret
    args: list[str]


@dataclasses.dataclass
class Divert:
    kind: str         # kind | zero | arity | depth | ... (the error family)
    at: int           # branch PC whose other polarity leaves the row
    to: int           # where that polarity goes


@dataclasses.dataclass
class Arm:
    name: str
    fn: str
    tag: int
    ctor: str
    children: list[Child]
    result: str
    steps: list[Step]
    errors: list[Divert]
    family: str = ""                  # the case template (`templates/<family>_<mode>.lean`)
    params: dict[str, str] = dataclasses.field(default_factory=dict)


def parse_row(cols: list[str]) -> Arm:
    name, fn, tag, ctor, children, result, steps, errors = cols[:8]
    family, params = "", {}
    if len(cols) > 8 and cols[8].strip():
        family, *kvs = cols[8].split()
        params = dict(kv.split("=", 1) for kv in kvs)
    ch = []
    for c in filter(None, (x.strip() for x in children.split(";"))):
        var, kind, value, slot = c.split(":")
        ch.append(Child(var, kind, value, int(slot, 0)))
    st = []
    for s in filter(None, (x.strip() for x in steps.split(";"))):
        op, *args = s.split()
        st.append(Step(op, args))
    er = []
    for e in filter(None, (x.strip() for x in errors.split(";"))):
        kind, at, to = e.split(":")
        er.append(Divert(kind, int(at, 0), int(to, 0)))
    return Arm(name, fn, int(tag), ctor, ch, result, st, er, family, params)


def validate(arm: Arm, code: dict[int, tuple[int, str, str]]) -> None:
    """Structural checks against the binary: runs start/stop at instructions,
    child calls are `jal` into the recursive entry, the first run starts at the
    function entry and the last ends in `ret`."""
    def err(msg: str) -> None:
        raise SystemExit(f"arms.tsv: {arm.name}: {msg}")
    if arm.fn not in ENTRY:
        err(f"fn must be eval|exec, got {arm.fn}")
    runs = [s for s in arm.steps if s.op == "run"]
    if not runs or int(runs[0].args[0], 0) != ENTRY[arm.fn]:
        err("the first step must be a run from the function entry")
    if arm.steps[-1].op != "run" or arm.steps[-1].args[1] != "ret":
        err("the last step must be a run ending in ret")
    names = {c.var for c in arm.children}
    for s in arm.steps:
        if s.op == "run":
            a = int(s.args[0], 0)
            if a not in code:
                err(f"run start {a:#x} is not an instruction")
            if s.args[1] != "ret" and int(s.args[1], 0) not in code:
                err(f"run stop {s.args[1]} is not an instruction")
        elif s.op == "child":
            var, pc = s.args[0], int(s.args[1], 0)
            if var not in names:
                err(f"child {var} not declared in the children column")
            tgt = jal_target(code[pc][0], pc) if pc in code else None
            kind = next(c.kind for c in arm.children if c.var == var)
            want = EVAL_ENTRY if kind == "E" else EXEC_ENTRY
            if tgt != want:
                err(f"child call at {pc:#x} is not `jal {want:#x}`")
        elif s.op == "helper":
            pc = int(s.args[1], 0)
            if pc not in code or jal_target(code[pc][0], pc) is None:
                err(f"helper call at {pc:#x} is not a linking jal")
        else:
            err(f"unknown step {s.op}")
    for d in arm.errors:
        if d.at not in code:
            err(f"error divert {d.at:#x} is not an instruction")


def load_rows() -> list[Arm]:
    code = load_disasm()
    rows = []
    # arms.tsv plus one table per case family in arms.d/ (so parallel lanes do not
    # edit the same file); rows are read in file order, arms.d sorted by name.
    tables = [ARMS] + sorted((ARMS.parent / "arms.d").glob("*.tsv"))
    for line in (l for t in tables for l in t.read_text().splitlines()):
        if not line.strip() or line.startswith("#"):
            continue
        arm = parse_row(line.split("\t"))
        validate(arm, code)
        rows.append(arm)
    return rows


# ------------------------------------------------------------------ emitters
def run_steps(arm: Arm) -> list[Step]:
    return [s for s in arm.steps if s.op == "run"]


def fill(template: str, subst: dict[str, str]) -> str:
    """Replace every `{KEY}` of the template; fail on a placeholder left over."""
    for k, v in subst.items():
        template = template.replace("{" + k + "}", v)
    left = re.findall(r"\{[A-Z0-9]+\}", template)
    if left:
        raise SystemExit(f"template placeholders left unfilled: {sorted(set(left))}")
    return template


def subst_binInt(arm: Arm, mode: str) -> dict[str, str]:
    """Family `binInt`: `eval_expr`'s binary arm on two ints whose tail is one
    `value_int` call (`+`, `-`). Params: `op` (the `BinOp`), `mop` (the machine
    operator of the tail), `wrap` (the `toInt` lemma of that operator), `tok`
    (the operator token the dispatch reads)."""
    runs = run_steps(arm)
    helpers = [s for s in arm.steps if s.op == "helper"]
    if len(runs) != 4 or len(helpers) != 1 or [c.slot for c in arm.children] != [120, 144]:
        raise SystemExit(f"{arm.name}: family binInt needs 4 runs, 1 helper, child slots 120/144")
    j3 = int(helpers[0].args[1], 0)
    r4 = int(runs[3].args[0], 0)
    if r4 != j3 + 4 or int(runs[2].args[1], 0) != j3:
        raise SystemExit(f"{arm.name}: the last two runs must meet the helper call at {j3:#x}")
    p = arm.params
    return {"ARM": arm.name, "OP": p["op"], "MOP": p["mop"], "WRAP": p["wrap"], "TOK": p["tok"],
            "RES": "(" + arm.result.removeprefix(".int ").strip() + ")",
            "J3": f"{j3:08x}", "R4": f"{r4:08x}"}


FAMILIES = {"binInt": subst_binInt}


# ------------------------------------------------------------------ lane E3 families
# The logical (`EX_LOGICAL`, tag 7) and unary (`EX_UNARY`, tag 8) arms. The
# shared code (prologue and dispatch, the `value_truthy`/`value_bool` tail at
# 0x800035cc-0x800035dc, the epilogue) is literal in the templates; the
# functions below read the row-specific PCs off the steps and check the rest.
def _pcs(arm: Arm, op: str) -> list[int]:
    return [int(s.args[1], 0) for s in arm.steps if s.op == op]


def _starts(arm: Arm) -> list[int]:
    return [int(s.args[0], 0) for s in run_steps(arm)]


def _need(arm: Arm, ok: bool, what: str) -> None:
    if not ok:
        raise SystemExit(f"{arm.name}: family {arm.family}: {what}")


def _meet(arm: Arm) -> None:
    """Each run after a call starts right after that call's `jal`."""
    calls = [int(s.args[1], 0) for s in arm.steps if s.op in ("child", "helper")]
    starts = _starts(arm)[1:]
    _need(arm, [c + 4 for c in calls] == starts, "each run must start after the previous call")


def subst_unNot(arm: Arm, mode: str) -> dict[str, str]:
    """Family `unNot`: `!e` (operand; `value_truthy` on its copy; `seqz`;
    `value_bool`)."""
    _meet(arm)
    _need(arm, _pcs(arm, "child") == [0x800035E8] and _pcs(arm, "helper") == [0x80003614, 0x80003620],
          "the operand at 0x800035e8, value_truthy at 0x80003614, value_bool at 0x80003620")
    return {"ARM": arm.name}


def subst_unNeg(arm: Arm, mode: str) -> dict[str, str]:
    """Family `unNeg`: `-e` on an int (operand; kind test; `neg`; `value_int`).
    Partial mode exports the non-int operand (the type-error row)."""
    _meet(arm)
    _need(arm, _pcs(arm, "child") == [0x800035E8] and _pcs(arm, "helper") == [0x800039D8],
          "the operand at 0x800035e8, value_int at 0x800039d8")
    return {"ARM": arm.name}


def _logCommon(arm: Arm) -> dict[str, str]:
    p = arm.params
    _meet(arm)
    _need(arm, _pcs(arm, "child")[0] == 0x80003568 and arm.children[0].slot == 120,
          "the left operand at 0x80003568 into sp+120")
    h = _pcs(arm, "helper")
    return {"ARM": arm.name, "LOP": p["lop"], "TRU": p["tru"], "TOK": p["tok"], "CTOR": p["ctor"],
            "BIT": "1" if p["tru"] == "true" else "0", "J2": f"{h[0]:08x}",
            "R3": f"{_starts(arm)[2]:08x}"}


def subst_logLong(arm: Arm, mode: str) -> dict[str, str]:
    """Family `logLong`: `l && r` with `l` truthy, `l || r` with `l` falsy
    (both operands, `value_truthy` on each copy, `value_bool`). Partial mode
    exports the other truthiness (the `logShort` row)."""
    d = _logCommon(arm)
    h, c = _pcs(arm, "helper"), _pcs(arm, "child")
    _need(arm, len(c) == 2 and h[1:] == [0x800035CC, 0x800035D8],
          "two operands; the shared tail value_truthy 0x800035cc, value_bool 0x800035d8")
    d.update({"J3": f"{c[1]:08x}", "SR": str(arm.children[1].slot), "R4": f"{_starts(arm)[3]:08x}"})
    return d


def subst_logShort(arm: Arm, mode: str) -> dict[str, str]:
    """Family `logShort`: `l && r` with `l` falsy, `l || r` with `l` truthy
    (left operand, `value_truthy`, `value_bool` of the constant). Params
    `from` (the `logLong` row whose export this row continues) and `opn` (the
    name of the operator's closed partial case)."""
    d = _logCommon(arm)
    h = _pcs(arm, "helper")
    _need(arm, len(_pcs(arm, "child")) == 1 and len(h) == 2, "one operand, two helpers")
    res = arm.result.removeprefix(".bool ").strip()
    _need(arm, res in ("true", "false"), "the result is a constant bool")
    d.update({"J3": f"{h[1]:08x}", "R4": f"{_starts(arm)[3]:08x}", "RES": res,
              "RB": "1" if res == "true" else "0", "LONG": arm.params["from"],
              "OPN": arm.params["opn"]})
    return d


FAMILIES.update({"unNot": subst_unNot, "unNeg": subst_unNeg, "logLong": subst_logLong,
                 "logShort": subst_logShort})


def emit(arm: Arm, mode: str) -> str:
    """The Lean source of one generated case: the row's family template
    (`templates/<family>_<mode>.lean`) filled from the row."""
    tmpl = TEMPLATES / f"{arm.family}_{mode}.lean"
    if arm.family not in FAMILIES or not tmpl.exists():
        raise NotImplementedError(f"{arm.name}: no template {tmpl.name}")
    return fill(tmpl.read_text(), FAMILIES[arm.family](arm, mode))


def write_all(check: bool = False) -> int:
    rows = load_rows()
    stale = []
    for arm in rows:
        for mode in ("T", "P"):
            try:
                text = HEADER + emit(arm, mode)
            except NotImplementedError:
                continue
            path = OUT / f"{arm.name}{mode}.lean"
            if check:
                if not path.exists() or path.read_text() != text:
                    stale.append(path)
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text)
    for p in stale:
        print(f"stale: {p.relative_to(ROOT)}", file=sys.stderr)
    return 1 if stale else 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--list", action="store_true")
    a = ap.parse_args()
    if a.list:
        for arm in load_rows():
            print(arm)
        return 0
    return write_all(check=a.check)


if __name__ == "__main__":
    sys.exit(main())
