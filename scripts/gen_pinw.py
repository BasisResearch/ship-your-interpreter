#!/usr/bin/env python3
"""Generate Vsa/Sim/PinW.lean — the width-indexed byte-window pin family.

One template, four instantiations (widths 1/2/4/8).  Regenerate with:

    python3 scripts/gen_pinw.py

The generated file collapses the per-width near-copies of the memory-pin
machinery (SlotHolds/slotHolds_* in SnprintfSpec5, Pin8/Pin4 in SnprintfSpec19)
into a uniform API:

  PinW<w> mem a v                 — w conjuncts of byte extracts at [a, a+w)
  pinw<w>_of_writeMap             — store image => pin
  pinw<w>_survives_insert         — disjoint byte insert transport
  pinw<w>_survives_writeMap{1,2,4,8}
  pinw<w>_survives_frame          — pointwise outside-[lo,hi) frame transport
  pinw<w>_bytes                   — unpack to the h0..h(w-1) load-site shapes
  pinw<w>_reassemble (+ sext bridges at 4/8)
  pin8_iff_Pin8 / pin4_iff_Pin4 / pinW8_iff_slotHolds

No dependent-width BitVec algebra: every lemma is emitted at a concrete width,
so the proofs are exactly the battle-tested Pin8/Pin4/SlotHolds proof shapes.
"""

import os

MEM = "Std.ExtHashMap Nat (BitVec 8)"
WIDTHS = [1, 2, 4, 8]

OUT = os.path.join(os.path.dirname(__file__), "..", "Vsa", "Sim", "PinW.lean")


def addr(k: int) -> str:
    return "a" if k == 0 else f"a + {k}"


def conj(w: int, indent: str, mem: str = "mem", v: str = "v") -> str:
    """The w byte-pin conjuncts, one per line, joined by ∧."""
    lines = [f"{indent}{mem}[{addr(k)}]? = some ({v}.extractLsb' {8 * k} 8)"
             for k in range(w)]
    return " ∧\n".join(lines)


def chain(w: int, v: str = "v") -> str:
    """The little-endian append chain (b_{w-1} ++ … ++ b0) of v's byte extracts."""
    offs = list(range(8 * (w - 1), -1, -8))
    expr = f"({v}.extractLsb' {offs[0]} 8)"
    for off in offs[1:]:
        expr = f"({expr}.append ({v}.extractLsb' {off} 8))"
    return expr


def obtain_pat(w: int) -> str:
    return ", ".join(f"h{k}" for k in range(w))


def holes(w: int) -> str:
    return ", ".join("?_" for _ in range(w))


def per_conjunct_transport(w: int, name: str, rw: str) -> str:
    """A survive lemma body: destruct, refine, rewrite each byte, close."""
    if w == 1:
        return (f"  show (?m)[a]? = some (v.extractLsb' 0 8)\n"  # placeholder, unused
                )
    return (f"  obtain ⟨{obtain_pat(w)}⟩ := h\n"
            f"  refine ⟨{holes(w)}⟩ <;>\n"
            f"    rw [{rw}] <;> assumption")


HEADER = f"""import Vsa.Sim.ValueSites
import Vsa.Sim.ValueSpec
import Vsa.Sim.ValueTruthySpec
import Vsa.Sim.SnprintfSpec5
import Vsa.Sim.SnprintfSpec19

/-!
# `PinW` — width-indexed byte-window memory pins (widths 1/2/4/8)

GENERATED by `scripts/gen_pinw.py` — edit the generator, not this file.

`PinW<w> mem a v` pins the `w` little-endian bytes of `v : BitVec (8*<w>)` at
`[a, a+<w>)`.  This is the single shape behind the per-width near-copies
`SlotHolds` (`SnprintfSpec5`), `Pin8`/`Pin4` (`SnprintfSpec19`), and the widths
2/1 about to be needed.  Per width the API is uniform:

* `pinw<w>_of_writeMap`      — a `writeMap<w>` store image establishes the pin;
* `pinw<w>_survives_insert` / `pinw<w>_survives_writeMap{{1,2,4,8}}`
                             — transport across disjoint stores;
* `pinw<w>_survives_frame`   — transport across a pointwise "outside `[lo,hi)`
                             unchanged" frame (verified sub-call postconditions);
* `pinw<w>_bytes`            — unpack to the `h0…h(w-1)` byte facts load sites want;
* `pinw<w>_reassemble`       — the LE append chain of the extracts is `v`
                             (plus the `sext` `lw`/`ld` shapes at widths 4/8).

Conversion is free: `pin8_iff_Pin8`, `pin4_iff_Pin4`, `pinW8_iff_slotHolds` are
all `Iff.rfl` — the existing definitions are literally `PinW` instances (`Pin8`
at the `sdData_val` byte image, `SlotHolds` at the `base + sext (ofNat12 off)`
address shape).

`writeMap2`/`writeMap1` (the `sh`/`sb` store images) are introduced here,
mirroring `writeMap4`/`writeMap8` (`ValueSites`).
-/

open LeanRV64DExecutable LeanRV64DExecutable.Functions Sail ConcurrencyInterfaceV1 Vsa

set_option maxHeartbeats 4000000
set_option maxRecDepth 1000000

namespace Vsa.Sim

/-! ## Width-2 / width-1 write-maps (missing analogues of `writeMap4`/`writeMap8`) -/

/-- The width-2 write-map: `mem` updated with 2 little-endian bytes at `a`. -/
abbrev writeMap2 (mem : {MEM}) (a : Nat) (d : BitVec (8 * 2)) :
    {MEM} :=
  (mem.insert a (d.extractLsb' 0 8)).insert (a + 1) (d.extractLsb' 8 8)

/-- The width-1 write-map: `mem` updated with 1 byte at `a` (the `sb` image). -/
abbrev writeMap1 (mem : {MEM}) (a : Nat) (d : BitVec (8 * 1)) :
    {MEM} :=
  mem.insert a (d.extractLsb' 0 8)

/-! ## Small recon helpers -/

/-- LE reconstruction at width 2: `(b1 ++ b0).toNat = b0 + 256*b1`
(the width-2 analogue of `word_toNat_recon` / `word8_toNat_recon`). -/
theorem word2_toNat_recon (b0 b1 : BitVec 8) :
    ((b1.append b0) : BitVec (8 * 2)).toNat = b0.toNat + 256 * b1.toNat := by
  simp only [BitVec.append_eq, BitVec.toNat_append]
  have h0 := b0.isLt
  have h1 := b1.isLt
  rw [← Nat.shiftLeft_add_eq_or_of_lt (by omega)]
  simp only [Nat.shiftLeft_eq, Nat.reducePow]
  omega

/-- The width-8 store-data slice is the identity: `sdData_val v = v`. -/
theorem sdData_val_id (v : BitVec 64) : sdData_val v = v :=
  BitVec.eq_of_toNat_eq (sdData_toNat v)
"""


def block(w: int) -> str:
    p = f"pinw{w}"
    P = f"PinW{w}"
    bv = f"BitVec (8 * {w})"
    out = []

    # ---- definition ----
    plural = "byte" if w == 1 else "bytes"
    out.append(f"""/-! ## Width {w} -/

/-- The {w} little-endian {plural} of `v` pinned at `[a, a+{w})`. -/
def {P} (mem : {MEM}) (a : Nat) (v : {bv}) : Prop :=
{conj(w, "  ")}""")

    # ---- of_writeMap ----
    if w in (4, 8):
        fields = ",\n   ".join(f"getElem_writeMap{w}_{k} _ _ _" for k in range(w))
        out.append(f"""/-- **store ⇒ pin**: a `writeMap{w}` store image establishes the pin. -/
theorem {p}_of_writeMap (mem : {MEM}) (a : Nat) (v : {bv}) :
    {P} (writeMap{w} mem a v) a v :=
  ⟨{fields}⟩""")
    elif w == 2:
        out.append(f"""/-- **store ⇒ pin**: a `writeMap2` store image establishes the pin. -/
theorem {p}_of_writeMap (mem : {MEM}) (a : Nat) (v : {bv}) :
    {P} (writeMap2 mem a v) a v := by
  refine ⟨?_, ?_⟩
  · simp only [writeMap2]
    rw [getElem_insert_ne _ _ _ _ (by simp only [beq_eq_false_iff_ne, ne_eq]; omega),
      getElem_insert_self]
  · simp only [writeMap2]
    rw [getElem_insert_self]""")
    else:  # w == 1
        out.append(f"""/-- **store ⇒ pin**: a `writeMap1` store image establishes the pin. -/
theorem {p}_of_writeMap (mem : {MEM}) (a : Nat) (v : {bv}) :
    {P} (writeMap1 mem a v) a v :=
  getElem_insert_self _ _ _""")

    # ---- survives_insert ----
    ins_rw = ("Std.ExtHashMap.getElem?_insert, "
              "if_neg (by simp only [beq_iff_eq]; omega)")
    if w == 1:
        body = (f"  show (mem.insert k b)[a]? = some (v.extractLsb' 0 8)\n"
                f"  rw [{ins_rw}]\n"
                f"  exact h")
    else:
        body = (f"  obtain ⟨{obtain_pat(w)}⟩ := h\n"
                f"  refine ⟨{holes(w)}⟩ <;>\n"
                f"    rw [{ins_rw}] <;> assumption")
    out.append(f"""/-- **survive** a disjoint single byte insert. -/
theorem {p}_survives_insert {{mem : {MEM}}} {{a : Nat}}
    {{v : {bv}}} (k : Nat) (b : BitVec 8)
    (hdis : k < a ∨ a + {w} ≤ k) (h : {P} mem a v) : {P} (mem.insert k b) a v := by
{body}""")

    # ---- survives_writeMap1 / writeMap2 (via inserts) ----
    out.append(f"""/-- **survive** a disjoint 1-byte store (`sb`). -/
theorem {p}_survives_writeMap1 {{mem : {MEM}}} {{a : Nat}}
    {{v : {bv}}} (k : Nat) (d : BitVec (8 * 1))
    (hdis : k + 1 ≤ a ∨ a + {w} ≤ k) (h : {P} mem a v) :
    {P} (writeMap1 mem k d) a v :=
  {p}_survives_insert k _ (by omega) h""")

    out.append(f"""/-- **survive** a disjoint 2-byte store (`sh`). -/
theorem {p}_survives_writeMap2 {{mem : {MEM}}} {{a : Nat}}
    {{v : {bv}}} (k : Nat) (d : BitVec (8 * 2))
    (hdis : k + 2 ≤ a ∨ a + {w} ≤ k) (h : {P} mem a v) :
    {P} (writeMap2 mem k d) a v :=
  {p}_survives_insert (k + 1) _ (by omega)
    ({p}_survives_insert k _ (by omega) h)""")

    # ---- survives_writeMap4 / writeMap8 (via disjoint read-through) ----
    for K, ins in ((4, "sw"), (8, "sd")):
        rw = f"getElem_writeMap{K}_disjoint _ _ _ _ (by omega)"
        if w == 1:
            body = (f"  show (writeMap{K} mem k d)[a]? = some (v.extractLsb' 0 8)\n"
                    f"  rw [{rw}]\n"
                    f"  exact h")
        else:
            body = (f"  obtain ⟨{obtain_pat(w)}⟩ := h\n"
                    f"  refine ⟨{holes(w)}⟩ <;>\n"
                    f"    rw [{rw}] <;> assumption")
        out.append(f"""/-- **survive** a disjoint {K}-byte store (`{ins}`). -/
theorem {p}_survives_writeMap{K} {{mem : {MEM}}} {{a : Nat}}
    {{v : {bv}}} (k : Nat) (d : BitVec (8 * {K}))
    (hdis : k + {K} ≤ a ∨ a + {w} ≤ k) (h : {P} mem a v) :
    {P} (writeMap{K} mem k d) a v := by
{body}""")

    # ---- survives_frame ----
    if w == 1:
        body = (f"  show mem'[a]? = some (v.extractLsb' 0 8)\n"
                f"  rw [hframe _ (by omega)]\n"
                f"  exact h")
    else:
        body = (f"  obtain ⟨{obtain_pat(w)}⟩ := h\n"
                f"  refine ⟨{holes(w)}⟩ <;>\n"
                f"    rw [hframe _ (by omega)] <;> assumption")
    out.append(f"""/-- **survive** a whole verified sub-call: any memory transition with a
pointwise frame "outside `[lo, hi)` unchanged" preserves a pin whose window
lies entirely below `lo` or entirely at/above `hi`
(mirrors `slot_survives_frame`, `SlotFrame`). -/
theorem {p}_survives_frame {{mem mem' : {MEM}}} {{a : Nat}}
    {{v : {bv}}} (lo hi : Nat)
    (hframe : ∀ j, (j < lo ∨ hi ≤ j) → mem'[j]? = mem[j]?)
    (hwin : a + {w} ≤ lo ∨ hi ≤ a) (h : {P} mem a v) : {P} mem' a v := by
{body}""")

    # ---- bytes ----
    out.append(f"""/-- **unpack**: the individual byte facts, in exactly the `mem[a + k]? = some bk`
shape a load site's `h0…h{w - 1}` hypotheses want. -/
theorem {p}_bytes (mem : {MEM}) (a : Nat) (v : {bv})
    (h : {P} mem a v) :
{conj(w, "    ")} := h""")

    # ---- reassemble ----
    if w == 1:
        out.append(f"""/-- **reassemble**: the single byte extract is `v`. -/
theorem {p}_reassemble (v : {bv}) : v.extractLsb' 0 8 = v := by
  apply BitVec.eq_of_toNat_eq
  simp only [BitVec.extractLsb', BitVec.toNat_ofNat, Nat.shiftRight_eq_div_pow]
  have hv : v.toNat < 2 ^ 8 := v.isLt
  omega""")
    elif w == 2:
        out.append(f"""/-- **reassemble**: the LE append chain of the byte extracts is `v`. -/
theorem {p}_reassemble (v : {bv}) :
    ({chain(2)} : BitVec (8 * 2)) = v := by
  apply BitVec.eq_of_toNat_eq
  rw [word2_toNat_recon]
  simp only [BitVec.extractLsb', BitVec.toNat_ofNat, Nat.shiftRight_eq_div_pow]
  have hv : v.toNat < 2 ^ 16 := v.isLt
  omega""")
    elif w == 4:
        out.append(f"""/-- **reassemble**: the LE append chain of the byte extracts is `v`
(wraps `word4_eq_sp`, `SnprintfSpec19` — `word_toNat_recon`-based). -/
theorem {p}_reassemble (v : {bv}) :
    ({chain(4)} : BitVec (8 * 4)) = v :=
  word4_eq_sp v

/-- **reassemble (`lw` shape)**: the sign-extended 4-byte reassembly is `sext v`
(wraps `lw_cap_reassemble_sp`, `SnprintfSpec19`). -/
theorem {p}_sext_reassemble (v : {bv}) :
    (sign_extend (m := 64)
      ({chain(4)} : BitVec (8 * 4)) : BitVec 64) = sign_extend (m := 64) v :=
  lw_cap_reassemble_sp v""")
    else:  # w == 8
        out.append(f"""/-- **reassemble**: the LE append chain of the byte extracts is `v`
(`word8_toNat_recon`-based). -/
theorem {p}_reassemble (v : {bv}) :
    ({chain(8)} : BitVec (8 * 8)) = v := by
  apply BitVec.eq_of_toNat_eq
  rw [word8_toNat_recon]
  simp only [BitVec.extractLsb', BitVec.toNat_ofNat, Nat.shiftRight_eq_div_pow]
  have hv : v.toNat < 2 ^ 64 := v.isLt
  omega

/-- **reassemble (`ld` shape)**: the sign-extended 8-byte reassembly is `v`
(`ve_sext_reassemble` generalized from `sdData_val` images to any `v`). -/
theorem {p}_sext_reassemble (v : {bv}) :
    (sign_extend (m := 64)
      ({chain(8)} : BitVec (8 * 8)) : BitVec 64) = v := by
  rw [sext_full]
  exact {p}_reassemble v""")

    return "\n\n".join(out)


BRIDGES = """/-! ## Bridges to the existing per-width pins (all definitional) -/

/-- `Pin8` (`SnprintfSpec19`) *is* `PinW8` at the `sdData_val` byte image. -/
theorem pin8_iff_Pin8 (mem : Std.ExtHashMap Nat (BitVec 8)) (a : Nat) (v : BitVec 64) :
    PinW8 mem a (sdData_val v) ↔ Pin8 mem a v := Iff.rfl

/-- `Pin4` (`SnprintfSpec19`) *is* `PinW4` (`BitVec 32 = BitVec (8*4)` definitionally). -/
theorem pin4_iff_Pin4 (mem : Std.ExtHashMap Nat (BitVec 8)) (a : Nat) (w : BitVec 32) :
    PinW4 mem a w ↔ Pin4 mem a w := Iff.rfl

/-- `SlotHolds` (`SnprintfSpec5`) *is* `PinW8` at the `base + sext (ofNat12 off)`
effective address and the `sdData_val` byte image. -/
theorem pinW8_iff_slotHolds (base : BitVec 64) (off : Nat) (v : BitVec 64)
    (mem : Std.ExtHashMap Nat (BitVec 8)) :
    PinW8 mem ((base + sign_extend (m := 64) (BitVec.ofNat 12 off)).toNat) (sdData_val v)
      ↔ SlotHolds base off v mem := Iff.rfl

end Vsa.Sim
"""


def main() -> None:
    parts = [HEADER]
    parts.extend(block(w) for w in WIDTHS)
    parts.append(BRIDGES)
    text = "\n".join(parts)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()
