#!/usr/bin/env python3
"""gen_trace.py — trace-harness generator (ANALYSIS ONLY, stage 1 of the
invariant-gen pipeline; see experiments/invariant-gen-plan.md).

Input: a case id (from experiments/corpus/INDEX.md, which gives the arm/loop
entry PC) + a probe spec (which x-registers to dump, plus optional 8-byte mem
windows relative to a probed register).  Emits the `tracedLoop` patch into a
COPY of the emulator (NEVER the real riscv-lean, NEVER the proof ELF), builds
once per probe-set, runs a `.wl` test program, and writes structured JSONL.

Nothing here enters a proof.  This is the same category as the ELF emulator
harness and the statement fuzzer: design-time mining input.

The `tracedLoop` template is the validated one from /tmp/rl-trace: a
`while (not htif_done)` step loop that, at each trace PC, dumps the chosen
registers via `print_effect` in the exact proof model.  We only rewrite the
PROBE portion (trace PCs + the register/mem dump), never the stepping harness.

Usage:
  python3 scripts/gen_trace.py --case hSBrk \
      --pc 0x80004014 --regs a0,a1,a2,sp \
      --mem a1:0:32 \
      --wl /tmp/wl-test/tests/while.wl \
      --out /tmp/rl-trace/hSBrk_trace.jsonl

  # PC/regs default from a small built-in case table when omitted.
  python3 scripts/gen_trace.py --case hSBrk --wl ... --out ...

Emulator copy defaults to /tmp/rl-trace (the warm COW copy); pass --emulator to
point elsewhere.  --no-build reuses the last-built binary (probe unchanged).
"""
import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile

# x-register name -> Sail register (x0..x31).  ABI names accepted.
ABI = {
    "zero": 0, "ra": 1, "sp": 2, "gp": 3, "tp": 4, "t0": 5, "t1": 6, "t2": 7,
    "s0": 8, "fp": 8, "s1": 9, "a0": 10, "a1": 11, "a2": 12, "a3": 13,
    "a4": 14, "a5": 15, "a6": 16, "a7": 17, "s2": 18, "s3": 19, "s4": 20,
    "s5": 21, "s6": 22, "s7": 23, "s8": 24, "s9": 25, "s10": 26, "s11": 27,
    "t3": 28, "t4": 29, "t5": 30, "t6": 31,
}

# Built-in case → (probe PC, default register list).  PC is the ARM-ENTRY or
# dispatch PC where the arg regs + slot window are live (from corpus INDEX).
# For the relational-lite exec arms we probe the dispatch PC 0x80004014, where
# the represented Stmt pointer is in s0/x8 (aStmt) and the kind is resolvable.
CASES = {
    # exec dispatch point: x8=aStmt (stmt node), x14=table base, a0=status set later
    "hSBrk":  (0x80004014, ["s0", "a0", "a1", "a2", "sp"]),
    "hSCont": (0x80004014, ["s0", "a0", "a1", "a2", "sp"]),
    "hSExpr": (0x80004014, ["s0", "a0", "a1", "a2", "sp"]),
    # io write loop head (stage-1 pure-machine case)
    "io_write": (0x8000004c, ["a1", "a2", "a3", "a4", "a6"]),
    # eval_expr entry (stack-ladder case)
    "hCallClosure": (0x80003164, ["sp", "ra", "a0", "a2"]),
}

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def build_probe(trace_pcs, regs, mems):
    """Emit the Lean `tracedLoop` body for the given probe set.

    regs: list of x-register indices.  mems: list of (regidx, off, nbytes)
    windows dumped as words relative to that register's value."""
    pc_list = ", ".join(f"0x{pc:x}#64" for pc in trace_pcs)
    reg_lets = []
    dump_parts = ["pc={pc}"]  # pc always first
    for r in regs:
        reg_lets.append(f"      let r{r} ← readReg x{r}")
        dump_parts.append(f"x{r}={{r{r}}}")
    # memory windows: dump nbytes bytes at (reg + off) as one little-endian
    # word per 4 bytes.  The proof model exposes byte reads through the memory
    # map via Sail's `readByte : Nat → SailM (BitVec 8)`; we assemble words from
    # bytes so a mined constant matches the read32/read64 the proof pins.
    mem_lets = []
    for i, (rr, off, nb) in enumerate(mems):
        # dump each byte raw; the miner assembles the little-endian word.  We
        # read via `Sail.readByte : Nat → SailM (BitVec 8)` off the memory map.
        for b in range(nb):
            mem_lets.append(
                f"      let mb{i}_{b} ← Sail.ConcurrencyInterfaceV1.PreSail.readByte "
                f"(r{rr} + {off + b}#64).toNat")
            dump_parts.append(f"m{i}b{b}={{mb{i}_{b}}}")
    dump_fmt = " ".join(dump_parts)
    body = f"""/-- Traced loop (GENERATED by scripts/gen_trace.py) — probe dump. -/
def tracedLoop (_ : Unit) : SailM Nat := do
  let tracePCs : List (BitVec 64) := [{pc_list}]
  let mut steps : Nat := 0
  while (not (← readReg htif_done)) do
    let _ ← LeanRV64DExecutable.Functions.try_step steps true
    steps := steps + 1
    let pc ← readReg PC
    if tracePCs.contains pc then do
{chr(10).join(reg_lets)}
{chr(10).join(mem_lets)}
      print_effect s!"TRACE {dump_fmt}\\n"
    if steps > 4000000 then do
      print_effect "TRACE-FUEL-OUT\\n"
      writeReg htif_done true
  pure 0"""
    return body


def patch_main(main_path, probe_body):
    src = open(main_path).read()
    # Replace the existing `def tracedLoop ... pure 0` block.
    pat = re.compile(r"/-- Traced loop.*?\n  pure 0", re.S)
    if not pat.search(src):
        # fall back: match a bare `def tracedLoop` block up to `pure 0`.
        pat = re.compile(r"def tracedLoop.*?\n  pure 0", re.S)
    if not pat.search(src):
        sys.exit("gen_trace: could not find tracedLoop block to patch")
    new = pat.sub(lambda _: probe_body, src)
    if new == src:
        # identical probe already in place — no rebuild needed, not an error.
        print("[gen_trace] probe unchanged (reusing built emulator)")
        return False
    open(main_path, "w").write(new)
    return True


def parse_trace_line(line):
    """Parse one `TRACE k=0x..#64 ...` line into a dict of int values."""
    m = re.match(r"TRACE (.*)", line)
    if not m:
        return None
    d = {}
    for kv in re.finditer(r"(\w+)=0x0*([0-9a-fA-F]+)#\d+", m.group(1)):
        d[kv.group(1)] = int(kv.group(2), 16)
    return d if d else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--case", required=True)
    ap.add_argument("--pc", help="probe PC (hex); default from case table")
    ap.add_argument("--regs", help="comma reg list (abi names); default from case table")
    ap.add_argument("--mem", action="append", default=[],
                    help="mem window reg:off:nbytes (word-dumped), repeatable")
    ap.add_argument("--wl", help=".wl program to trace (baked into a fresh ELF)")
    ap.add_argument("--elf", help="use a PREBUILT ELF (skip the make step); "
                    "for reusing one ELF across probe-sets / cases sharing a path")
    ap.add_argument("--out", required=True, help="output JSONL path")
    ap.add_argument("--emulator", default="/tmp/rl-trace/lean_emulator")
    ap.add_argument("--wl-test", default="/tmp/wl-test")
    ap.add_argument("--no-build", action="store_true")
    args = ap.parse_args()

    # resolve probe from flags or the case table.  --pc accepts a comma list.
    if args.pc and args.regs:
        pcs = [int(p, 16) for p in args.pc.split(",")]
        regnames = args.regs.split(",")
    elif args.case in CASES:
        pc0, regnames = CASES[args.case]
        pcs = [pc0]
    else:
        sys.exit(f"gen_trace: no built-in probe for {args.case}; pass --pc/--regs")
    regs = [ABI[r] if r in ABI else int(r.lstrip("x")) for r in regnames]
    mems = []
    for m in args.mem:
        rr, off, nb = m.split(":")
        mems.append((ABI[rr] if rr in ABI else int(rr.lstrip("x")),
                     int(off), int(nb)))

    # 1. patch the emulator copy's probe.  The `tracedLoop` template lives in
    # LeanRiscv.lean (the library), not Main.lean (the entry point).
    main_path = os.path.join(args.emulator, "LeanRiscv.lean")
    if not os.path.exists(main_path):
        sys.exit(f"gen_trace: emulator copy not found: {main_path}")
    probe = build_probe(pcs, regs, mems)
    changed = patch_main(main_path, probe)
    if changed:
        print(f"[gen_trace] patched probe: pcs={[hex(p) for p in pcs]} "
              f"regs={regnames} mems={args.mem}")
    # a probe that did not change the source needs no rebuild.
    if not changed:
        args.no_build = True

    # 2. obtain the test ELF.  --elf reuses a PREBUILT scratch ELF (probe-set
    # sharing / no cross-gcc needed); otherwise build one from the .wl program.
    # NEVER clobber the tracked c/while-riscv-htif.elf: builds go to the wl-test
    # scratch name and the caller (invgen.py) restores the tracked copy.
    if args.elf:
        elf = os.path.abspath(args.elf)
        if not os.path.exists(elf):
            sys.exit(f"gen_trace: prebuilt ELF not found: {elf}")
        print(f"[gen_trace] using prebuilt ELF {os.path.basename(elf)}")
    else:
        if not args.wl:
            sys.exit("gen_trace: need --wl (build) or --elf (prebuilt)")
        wl = os.path.abspath(args.wl)
        elf = os.path.join(args.wl_test, "while-riscv-htif.elf")
        subprocess.run(["make", "-C", args.wl_test, "clean"],
                       capture_output=True)
        r = subprocess.run(
            ["make", "-C", args.wl_test, "riscv-htif", f"HTIF_SCRIPT={wl}"],
            capture_output=True, text=True)
        if not os.path.exists(elf):
            sys.exit(f"gen_trace: ELF build failed:\n{r.stdout}\n{r.stderr}")
        print(f"[gen_trace] built test ELF from {os.path.basename(wl)}")

    # 3. build the emulator (once per probe-set).  Retry once — a transient
    # lake lock / racing build (the ≤2-lean-process rule) can spuriously fail.
    binp = os.path.join(args.emulator, ".lake/build/bin/lean_riscv_emulator")
    if not args.no_build:
        print("[gen_trace] building emulator (lake build)...")
        for attempt in range(2):
            r = subprocess.run(["lake", "build"], cwd=args.emulator,
                               capture_output=True, text=True)
            if r.returncode == 0:
                break
            if attempt == 0:
                print("[gen_trace] build hiccup, retrying once...")
                subprocess.run(["sleep", "2"])
        if r.returncode != 0:
            sys.exit(f"gen_trace: emulator build failed:\n{r.stdout[-2000:]}\n"
                     f"{r.stderr[-2000:]}")
    if not os.path.exists(binp):
        sys.exit(f"gen_trace: emulator binary missing: {binp}")

    # 4. run + capture, emit JSONL
    print("[gen_trace] running trace...")
    r = subprocess.run([binp, elf], capture_output=True, text=True, timeout=600)
    rows = []
    for line in (r.stdout + r.stderr).splitlines():
        d = parse_trace_line(line)
        if d is not None:
            rows.append(d)
    with open(args.out, "w") as f:
        for i, d in enumerate(rows):
            f.write(json.dumps(dict(idx=i, case=args.case, **d)) + "\n")
    print(f"[gen_trace] wrote {len(rows)} trace events → {args.out}")


if __name__ == "__main__":
    main()
