"""Tests for the abstraction-discovery gate (scripts/abstraction_gate.py)."""

import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import abstraction_gate as gate  # noqa: E402


def unit(name, cost):
    body = "\n".join(f"  step{i}" for i in range(cost - 1))
    return f"theorem {name} : True := by\n{body}\n"


class GateTests(unittest.TestCase):
    def repo(self, files, baseline=None):
        d = Path(tempfile.mkdtemp())
        (d / "scripts").mkdir()
        (d / "Vsa").mkdir()
        for rel, text in files.items():
            p = d / rel
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text)
        if baseline:
            (d / "scripts" / "abstraction_gate_baseline.tsv").write_text(baseline)
        subprocess.run(["git", "init", "-q", str(d)], check=True)
        return d

    def test_stem_drops_addresses_digits_and_variants(self):
        self.assertEqual(gate.stem("site_80003254_totb"), "site totb")
        self.assertEqual(gate.stem("BinaryAddP_eL_run_1"), "Binary Add run")
        self.assertEqual(gate.stem("S.facts"), "")

    def test_flat_cluster_fires(self):
        d = self.repo({"Vsa/A.lean": "".join(unit(f"site_{0x80000000 + i:x}_ld", 10)
                                             for i in range(8))})
        found, _ = gate.check(d, "Vsa/**/*.lean")
        self.assertEqual(len(found), 1)
        self.assertIn("site ld", found[0])

    def test_falling_cluster_passes(self):
        costs = [30, 30, 20, 15, 10, 8, 6, 5]
        d = self.repo({"Vsa/A.lean": "".join(unit(f"row_{i}", c)
                                             for i, c in enumerate(costs))})
        found, firing = gate.check(d, "Vsa/**/*.lean")
        self.assertEqual(found, [])
        self.assertEqual(firing, [])

    def test_small_cluster_passes(self):
        d = self.repo({"Vsa/A.lean": "".join(unit(f"row_{i}", 10) for i in range(7))})
        self.assertEqual(gate.check(d, "Vsa/**/*.lean")[0], [])

    def test_baseline_holds_until_growth(self):
        text = "".join(unit(f"row_{i}", 10) for i in range(8))
        d = self.repo({"Vsa/A.lean": text}, baseline="row\t8\tround 1\n")
        self.assertEqual(gate.check(d, "Vsa/**/*.lean")[0], [])
        (d / "Vsa" / "A.lean").write_text(text + unit("row_9", 10))
        self.assertEqual(len(gate.check(d, "Vsa/**/*.lean")[0]), 1)

    def test_generated_files_are_ignored(self):
        text = "-- Generated by scripts/gen_x.py\n" + "".join(
            unit(f"row_{i}", 10) for i in range(8))
        d = self.repo({"Vsa/A.lean": text})
        self.assertEqual(gate.check(d, "Vsa/**/*.lean")[0], [])


if __name__ == "__main__":
    unittest.main()
