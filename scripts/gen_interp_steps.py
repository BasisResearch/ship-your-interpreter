def gen_steps():
    unsupported, parts = [], []
    cur = ([], [], set(), [])
    for pc in PCS:
        segs, thms = emit(pc)
        if segs is None:
            unsupported.append(pc)
            continue
        cur[0].extend(segs)
        cur[1].extend(thms)
        cur[2].add(DEC[W[pc]])
        cur[3].append(pc)
        if len(cur[3]) >= PER_FILE:
            parts.append(cur)
            cur = ([], [], set(), [])
    if cur[3]:
        parts.append(cur)
    files = {}
    uns = ', '.join(f'`0x{pc:x}` {MN[pc]}' for pc in unsupported)
    for k, (segs, thms, mods, pcs) in enumerate(parts):
        L = [HEADER, 'import VsaIris.Interp.IRun', 'import VsaIris.Vsa.SymObs', 'import Vsa.Sim.EnvNewSites', 'import Vsa.Sim.ExecuteAlu'] + \
            [f'import {m}' for m in sorted(mods)] + ['',
             f'/-! The interpreter\'s step table, `0x{pcs[0]:x}` to `0x{pcs[-1]:x}` (see',
             '`scripts/gen_interp_steps.py`). -/', '',
             'open LeanRV64DExecutable LeanRV64DExecutable.Functions Sail', '',
             'namespace Vsa.Sim', ''] + segs + ['', 'end Vsa.Sim', '',
             'namespace VsaIris.Sym', '', 'open Vsa.Sim Vsa.MemRepr VsaIris.Inst VsaIris.MallocFast', ''] + \
            [t + '\n' for t in thms] + ['end VsaIris.Sym', '']
        files[f'VsaIris/Interp/Steps/Part{k:02d}.lean'] = '\n'.join(L)
    files['VsaIris/Interp/Steps.lean'] = '\n'.join(
        [HEADER, f'-- No step lemma (outside the reflected block model): {uns}.'] +
        [f'import VsaIris.Interp.Steps.Part{k:02d}' for k in range(len(parts))] + [''])
    return files, unsupported


def main():
    check = '--check' in sys.argv
    files, unsupported = gen_steps()
    files['VsaIris/Interp/Code.lean'] = gen_code()
    stale = []
    for rel, text in files.items():
        p = ROOT / rel
        if check:
            if not p.exists() or p.read_text() != text:
                stale.append(rel)
        else:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text)
    if check:
        for rel in stale:
            print(f'stale: {rel}', file=sys.stderr)
        return 1 if stale else 0
    print(f'{len(PCS)} instructions, {len(code)} code bytes, {len(ro)} table bytes, '
          f'{len(files) - 2} parts; no step lemma: ' + ', '.join(f'0x{pc:x} {MN[pc]}' for pc in unsupported))
    return 0


if __name__ == '__main__':
    sys.exit(main())
