#!/usr/bin/env python3
"""Emit Vsa/Sim/SnprintfSpec55.lean — **`snprintf_lld_total_spec`**: the
∀-v `snprintf("%lld")` capstone.  Statement = Spec42's WITHOUT any value
hypothesis; proof = the 2-way sign split on `zopz0zKzJ_s v 0` (the machine's
`bgez` guard at `0x800080e8`):

  * `false` (negative)  → `snprintf_lld_spec`     (Spec42);
  * `true`  (nonneg)    → `snprintf_lld_nn_spec`  (Spec54).

Generated from Spec42's statement text.
"""
import pathlib
import re

SRC = pathlib.Path("Vsa/Sim/SnprintfSpec42.lean").read_text()

i = SRC.index("theorem snprintf_lld_spec")
j = SRC.index(":= by", i)
stmt = SRC[i:j]

GHOST = ("    -- the argument-value ghosts: negative, magnitude > 9\n"
         "    (hneg : zopz0zKzJ_s v (0#64) = false)\n")
if GHOST not in stmt:
    raise SystemExit("ghost hyp block not found")
stmt = stmt.replace(GHOST, "")
stmt = stmt.replace("theorem snprintf_lld_spec", "theorem snprintf_lld_total_spec", 1)

# ordered hypothesis-name list (parse the binders; hypotheses only — stop at
# the conclusion, which begins after the `htick` binder)
hyp_region = stmt[:stmt.index("(htick : c.tick < 2)")] + "(htick : c.tick < 2)"
hyps = re.findall(r"\(\s*(h[A-Za-z0-9_']*)\s*:", hyp_region)
PARAMS = ("vsp wra0 d sz v va4o va5o va6o va7o "
          "vS0o vS1o vS2o vS3o vS4o vS5o vS6o vS7o vS8o vS9o vS10o vS11o c")

# args with the ghost inserted after hszhi
def arglist(ghost):
    out = []
    for h in hyps:
        out.append(h)
        if h == "hszhi":
            out.append(ghost)
    return out

def wrap(items, indent="      "):
    lines, cur = [], indent
    for it in items:
        if len(cur) + len(it) + 1 > 96:
            lines.append(cur.rstrip())
            cur = indent
        cur += it + " "
    lines.append(cur.rstrip())
    return "\n".join(lines)

proof = f""":= by
  rcases Bool.eq_false_or_eq_true (zopz0zKzJ_s v (0#64)) with hnn | hneg
  · -- v nonneg (incl. 0): the 1-iovec arm (Spec54)
    exact snprintf_lld_nn_spec {PARAMS}
{wrap(arglist('hnn'))}
  · -- v negative: the sign-byte arm (Spec42)
    exact snprintf_lld_spec {PARAMS}
{wrap(arglist('hneg'))}
"""

HDR = """import Vsa.Sim.SnprintfSpec42
import Vsa.Sim.SnprintfSpec54

/-!
# M3 Layer-3 — `SnprintfSpec55` : **`snprintf_lld_total_spec`** — ∀ v

THE M3 total capstone: for **every** `v : BitVec 64`,
`snprintf(d, sz, "%lld", v)` runs from the ABI entry `0x80005c44` to `ret`
with the caller buffer holding `(intToString v.toInt).toUTF8` byte-for-byte
**plus the NUL terminator**, `a0` = the byte length, callee-saves/`sp`
restored, and a pointwise frame outside the stack frames and the written
buffer.  Statement = `snprintf_lld_spec`'s (Spec42) with NO value
hypothesis; proof = the 2-way sign split mirroring the machine's `bgez`
guard at `0x800080e8`:

  * `zopz0zKzJ_s v 0 = false` (negative, any magnitude) → Spec42's
    `snprintf_lld_spec` (sign-byte 2-iovec flush);
  * `zopz0zKzJ_s v 0 = true` (nonneg, incl. `v = 0` → the digit `'0'`) →
    Spec54's `snprintf_lld_nn_spec` (1-iovec flush).

Residual hypotheses: the static-image pins + code `*Loaded` predicates and
the layout/size facts only — the honest ledger of Spec42, minus every value
ghost.

Generated by `scripts/pro_emitter/gen_spec55.py` from Spec42's statement.
-/

open Vsa Vsa.Sim Vsa.While
open LeanRV64DExecutable LeanRV64DExecutable.Functions Sail ConcurrencyInterfaceV1
open Register
open Vsa.Machine (MState Config Step Steps)
open Vsa.Sim.Code (SvfprintfSliceLoaded SvfprintfSlice2Loaded FlushPinsLoaded MemmoveLoaded
  __ssprint_rLoaded __locale_mb_cur_maxLoaded __ascii_mbtowcLoaded __hidden___udivdi3Loaded)

set_option maxHeartbeats 8000000
set_option maxRecDepth 1000000

namespace Vsa.Sim

/-- **The `snprintf("%lld")` TOTAL capstone — every `v : BitVec 64`.**
The caller buffer gets `(intToString v.toInt).toUTF8 ++ [0]`, `a0` = the
byte length; see the module docstring. -/
"""

out = HDR + stmt + proof + "\nend Vsa.Sim\n"
p = pathlib.Path("Vsa/Sim/SnprintfSpec55.lean")
p.write_text(out)
print(f"wrote {p} ({out.count(chr(10))} lines); {len(hyps)} hyps")
