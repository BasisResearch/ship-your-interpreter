#!/usr/bin/env python3
"""Driver: generate Vsa/Sim/Code/ArmPins.lean — byte pins for the two
`%lld` value-arm ranges outside every existing pinned window (arm traces,
experiments/pctrace.md session g):

  [0x80008ea4, 0x80008ebc)  single-digit fast-path tail (lbu sign/li/li/li/addi/j)
  [0x80007ce4, 0x80007cec)  nonneg PRINT hop (subw s4,s4,s6; blez → 78bc)

Predicate `ArmPinsLoaded`, accessors `armPins_at_<addr>`.
"""
import sys, pathlib
sys.path.insert(0, "experiments")
import gen_code_lemmas as g

RANGES = [
    (0x80007ce4, 0x80007cec),
    (0x80008ea4, 0x80008ebc),
]

def in_ranges(a):
    return any(lo <= a < hi for lo, hi in RANGES)

def emit(insts):
    f = "armPins"
    F = "ArmPins"
    CHUNK = g.CHUNK
    chunks = [insts[i:i + CHUNK] for i in range(0, len(insts), CHUNK)]
    L = []
    L.append("import Vsa.Sim.Regions\n")
    L.append(f"/-! Code byte pins for the `%lld` value-arm hop ranges "
             f"(`ArmPinsLoaded`)\n(generated by scripts/pro_emitter/gen_armpins.py driving "
             f"experiments/gen_code_lemmas.py — do not hand-edit).\n"
             f"{len(insts)} instructions across "
             f"{[(hex(lo),hex(hi)) for lo,hi in RANGES]}: the single-digit\n"
             f"fast-path tail block and the nonneg PRINT hop. -/\n")
    L.append("namespace Vsa.Sim.Code\n")
    L.append("open Std\n")

    for ci, ch in enumerate(chunks):
        conj = " ∧\n  ".join(
            f"mem[(0x{a:x} : Nat)]? = some (0x{b:02x} : BitVec 8)"
            for addr, word in ch for a, b in [(addr + k, (word >> (8 * k)) & 0xFF) for k in range(4)])
        L.append(f"def {f}Chunk{ci} (mem : ExtHashMap Nat (BitVec 8)) : Prop :=\n  {conj}\n")

    top = " ∧ ".join(f"{f}Chunk{ci} mem" for ci in range(len(chunks)))
    L.append(f"/-- The `%lld` value-arm hop ranges are loaded. -/\n"
             f"def {F}Loaded (mem : ExtHashMap Nat (BitVec 8)) : Prop :=\n  {top}\n")

    for ci in range(len(chunks)):
        proj = "h" if len(chunks) == 1 else (
            "h." + ".".join(["2"] * ci + (["1"] if ci < len(chunks) - 1 else [])))
        proj = proj.rstrip(".")
        L.append(f"theorem {f}_chunk{ci} {{mem : ExtHashMap Nat (BitVec 8)}}\n"
                 f"    (h : {F}Loaded mem) : {f}Chunk{ci} mem := {proj}\n")

    for ci, ch in enumerate(chunks):
        nconj = 4 * len(ch)
        for ii, (addr, word) in enumerate(ch):
            bs = [(addr + k, (word >> (8 * k)) & 0xFF) for k in range(4)]
            concl = " ∧\n      ".join(
                f"mem[(0x{a:x} : Nat)]? = some (0x{b:02x} : BitVec 8)" for a, b in bs)

            def proj(k):
                i = 4 * ii + k
                if i == nconj - 1:
                    return "hc" + "".join(".2" for _ in range(i))
                return "hc" + "".join(".2" for _ in range(i)) + ".1"

            parts = ", ".join(proj(k) for k in range(4))
            L.append(f"theorem {f}_at_{addr:x} {{mem : ExtHashMap Nat (BitVec 8)}}\n"
                     f"    (h : {F}Loaded mem) :\n      {concl} :=\n"
                     f"  have hc := {f}_chunk{ci} h\n  ⟨{parts}⟩\n")

    L.append("end Vsa.Sim.Code\n")
    out = pathlib.Path("Vsa/Sim/Code/ArmPins.lean")
    out.write_text("\n".join(L))
    print(f"wrote {out} ({len(insts)} sites, {len(chunks)} chunks)")

funcs = g.parse()
sv = funcs["_svfprintf_r"]
insts = sorted((a, w) for a, w in sv if in_ranges(a))
assert len(insts) == 8, insts
emit(insts)
