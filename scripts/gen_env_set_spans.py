#!/usr/bin/env python3
"""Generate `VsaIris/Interp/EnvSetSpans.lean` from `EnvGetSpans.lean`.

`env_set` (`0x80002cdc`) is `env_get` (`0x80002c10`) shifted by 0xcc up to
the hit arm: the same prologue, scan, compare branch, parent walk and
epilogue (`experiments/disasm.txt`). Its scan spans are `env_get`'s with every
PC literal in `env_get`'s range shifted and `get_` renamed `set_`. The hit
arms differ and are hand-written (`EnvGetHit.lean`, `EnvSetHit.lean`).

Usage: python3 scripts/gen_env_set_spans.py [--check]
"""
import re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / 'VsaIris/Interp/EnvGetSpans.lean'
DST = ROOT / 'VsaIris/Interp/EnvSetSpans.lean'
LO, HI, DELTA = 0x80002c10, 0x80002cdc, 0xcc


def shift(m):
    v = int(m.group(1), 16)
    return f'0x{v + DELTA:x}' if LO <= v < HI else m.group(0)


src = SRC.read_text()
# the template's module doc
src = src.replace("# `env_get`'s scan spans, first-order", "# `env_set`'s scan spans, first-order (generated)")
src = src.replace('**This\nfile is the template of `EnvSetSpans.lean`** (`scripts/gen_env_set_spans.py`\nshifts every PC by `0xcc` and renames `get_` to `set_`).',
                  '**Generated\nfrom `EnvGetSpans.lean` by `scripts/gen_env_set_spans.py`; do not edit.**')
out = re.sub(r'0x([0-9a-f]{8})', shift, src)
out = re.sub(r'\bget_(entry|head|load|cmp|parent|epi)\b', r'set_\1', out)
out = out.replace("`env_get` (`0x80002cdc`)", "`env_set` (`0x80002cdc`)")
out = out.replace("Each call-free span of `env_get`", "Each call-free span of `env_set`")
out = out.replace("common to `env_set`", "common to `env_get`")
out = '-- Generated by scripts/gen_env_set_spans.py from EnvGetSpans.lean; do not edit.\n' + out
if '--check' in sys.argv:
    sys.exit(0 if DST.exists() and DST.read_text() == out else 1)
DST.write_text(out)
print(f'wrote {DST.relative_to(ROOT)}')
