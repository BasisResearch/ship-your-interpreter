#!/usr/bin/env python3
"""Generate VsaIris/Vsa/MallocFastJal.lean: one `JalExec` theorem per `jal`
site of malloc's fast paths (`jal_exec_<pc>`), each an instance of
`jalExec_of_site` + `stepObs_jal` + `jalStep_of_obs` with the site's decode
lemma. Sites are read from experiments/disasm.txt.

Usage: python3 scripts/gen_malloc_jal_sites.py
"""
import re, pathlib, subprocess
SITES = [0x800047cc, 0x80004874, 0x80004c10]
W = {}
for l in open('experiments/disasm.txt'):
    m = re.match(r'^\s+([0-9a-f]+):\t([0-9a-f]{8})\s+\t', l)
    if m: W[int(m.group(1), 16)] = int(m.group(2), 16)

def jimm(w):
    return ((w >> 31) & 1) << 20 | ((w >> 12) & 0xff) << 12 | ((w >> 20) & 1) << 11 | ((w >> 21) & 0x3ff) << 1

def sext21(v): return v - (1 << 21) if v >> 20 else v

mods = set()
body = []
for pc in SITES:
    w = W[pc]
    assert w & 0xfff == 0x0ef, hex(w)
    imm = jimm(w)
    tgt = (pc + sext21(imm)) % (1 << 64)
    bs = [(w >> (8 * i)) & 0xff for i in range(4)]
    out = subprocess.run(['grep', '-rl', f'theorem decode_{w:08x}$', 'Vsa/Sim/DecodeTable'],
                         capture_output=True, text=True).stdout.split()
    assert out, f'no decode lemma for {w:08x}'
    mods.add(out[0][:-5].replace('/', '.'))
    code = ', '.join(f'0x{b:02x}#8' for b in bs)
    hb = '\n'.join(f'  have hb{i} := hb (0x{pc + i:x}, .discard, 0x{bs[i]:02x}#8) (by simp [codeFoot])'
                   for i in range(4))
    body.append(f'''open LeanRV64DExecutable LeanRV64DExecutable.Functions Sail in
/-- `jal` at `0x{pc:x}` to `0x{tgt:x}`. -/
theorem jal_exec_{pc:08x} (live : Nat → Prop)
    (hlive : ∀ p ∈ codeFoot 0x{pc:x} [{code}], live p.1) :
    JalExec (vsaModel live) 0x{pc:x} [{code}] 0x{tgt:x}#64 := by
  refine jalExec_of_site live _ _ _ hlive fun c hG hi hpc hb => ?_
  obtain ⟨vm, hmi⟩ := hG.minstret
{hb}
  obtain ⟨σ', i', hs, hi', hG', hmem, hobs⟩ :=
    stepObs_jal c.σ c.tick c.steps (0x{pc:x}#64) vm (0x{w:08x}#32) (0x{imm:06x}#21)
      (regidx.Regidx 0x01#5) Register.x1 (BitVec.addInt (0x{pc:x}#64) 4)
      {' '.join(f'(0x{b:02x}#8)' for b in bs)}
      hG hpc hmi hb0 hb1 hb2 hb3 (by decide) (by decide) (by decide)
      (by apply BitVec.eq_of_toNat_eq; decide) (by apply BitVec.eq_of_toNat_eq; decide)
      (Vsa.Sim.DecodeTable.decode_{w:08x} (afterPrelude c.σ)
        (by rw [get?_afterPrelude c.σ _ (by decide)]; exact hG.misa)
        (by rw [get?_afterPrelude c.σ _ (by decide)]; exact hG.cur_privilege)
        (by rw [get?_afterPrelude c.σ _ (by decide)]; exact hG.mseccfg))
      (by decide)
      (by decide) (by decide) (by decide) (by decide) (by decide)
      (wX_bits_x1 _ (BitVec.addInt (0x{pc:x}#64) 4)) hi
  have h := jalStep_of_obs (calleeEntry := 0x{tgt:x}#64) hs hi' hG' hmem hobs
    (by apply BitVec.eq_of_toNat_eq; decide)
  rwa [show BitVec.addInt (0x{pc:x}#64 : BitVec 64) 4 = BitVec.ofNat 64 (0x{pc:x} + 4) from by
    apply BitVec.eq_of_toNat_eq; decide] at h
''')

hdr = ['-- Generated by scripts/gen_malloc_jal_sites.py; do not edit.',
       'import VsaIris.Vsa.Tools', 'import Vsa.Sim.EnvNewSites'] + \
      [f'import {m}' for m in sorted(mods)] + ['', '''/-!
# The `jal` sites of malloc's fast paths

One `JalExec` per site: the lock calls at `0x800047cc` (requests ≤ 23) and
`0x80004874` (larger requests), and the unlock call at `0x80004c10`.
-/

namespace VsaIris.MallocFast

open Vsa.Sim VsaIris.Inst

''']
pathlib.Path('VsaIris/Vsa/MallocFastJal.lean').write_text('\n'.join(hdr) + '\n'.join(body) + '\nend VsaIris.MallocFast\n')
print(len(SITES), 'sites')
