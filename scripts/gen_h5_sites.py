#!/usr/bin/env python3
"""Generate VsaIris/Vsa/H5Sites.lean from scripts/h5_sites.tsv and
experiments/disasm.txt: the code byte lists H5's proofs run (each with its
decided `TextAt` fact against the fixed image) and the `jal ra` sites (each a
`JalSite` with its decided `Cert`). `--check` fails on drift."""
import re, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
dis = (root / 'experiments/disasm.txt').read_text()
words = {int(a, 16): int(w, 16) for a, w in re.findall(r'^\s*([0-9a-f]{8}):\s+([0-9a-f]{8})\s', dis, re.M)}

def le(w): return [(w >> (8 * k)) & 0xff for k in range(4)]

out = ['-- Generated by scripts/gen_h5_sites.py from scripts/h5_sites.tsv; do not hand-edit.',
       'import VsaIris.Vsa.BinImg', 'import VsaIris.Vsa.JalSite', 'import Vsa.Sim.OutputAliasDecode', '',
       'namespace VsaIris.Newlib.Sites', '', 'open VsaIris.Inst', '']
# decode aliases go first so later sites may use them
for line in (root / 'scripts/h5_sites.tsv').read_text().splitlines():
    if not line.strip() or line.startswith('#'): continue
    f = line.split('\t')
    kind, name = f[0], f[1]
    if kind == 'code':
        lo, hi = int(f[2], 16), int(f[3], 16)
        bs = [b for a in range(lo, hi, 4) for b in le(words[a])]
        body = ', '.join(f'0x{b:02x}#8' for b in bs)
        n = hi - lo
        out += [f'/-- `.text` [{lo:#x}, {hi:#x}). -/', f'abbrev {name}Base : Nat := {lo:#x}',
                f'def {name} : List (BitVec 8) :=', f'  [{body}]', '',
                f'theorem {name}_text : TextAt {name}Base {name} := by decide +kernel', '',
                f'/-- The bytes of `{name}` are present, by index. -/',
                f'def {name}Loaded (m : Std.ExtHashMap Nat (BitVec 8)) : Prop :=',
                f'  ∀ k, k < {n} → m[{name}Base + k]? = some ({name}.getD k 0)', '',
                f'theorem {name}_len : {name}.length = {n} := by decide +kernel', '',
                f'theorem {name}Loaded_of {{m : Std.ExtHashMap Nat (BitVec 8)}}',
                f'    (h : ∀ p ∈ codeFoot {name}Base {name}, m[p.1]? = some p.2.2) : {name}Loaded m :=',
                f'  fun k hk => loaded_of_foot h k (by rw [{name}_len]; exact hk)', '']
        for a in range(lo, hi, 4):
            k = a - lo; w = le(words[a])
            pins = ' ∧\n    '.join(f'm[({a + j:#x} : Nat)]? = some ({w[j]:#04x} : BitVec 8)' for j in range(4))
            proofs = ', '.join(f'h {k + j} (by decide)' for j in range(4))
            out += [f'theorem {name}_at_{a:08x} {{m : Std.ExtHashMap Nat (BitVec 8)}} (h : {name}Loaded m) :',
                    f'    {pins} :=', f'  ⟨{proofs}⟩', '']
    elif kind == 'decode_alias':
        w, src = f[1], f[2]
        out += ['end VsaIris.Newlib.Sites', '', 'namespace Vsa.Sim.DecodeTable', '',
                f'/-- `{w}`, decoded in `{src}`; here under the `DecodeTable` name `chain_facts` uses. -/',
                f'alias decode_{w} := {src}.decode_{w}', '', 'end Vsa.Sim.DecodeTable', '',
                'namespace VsaIris.Newlib.Sites', '', 'open VsaIris.Inst', '']
# decode aliases go first so later sites may use them
    elif kind == 'jal':
        pc = int(f[2], 16); w = words[pc]
        assert w & 0x7f == 0x6f and (w >> 7) & 0x1f == 1, f'{name}: not jal ra at {pc:#x}'
        imm = (((w >> 31) & 1) << 20) | (((w >> 12) & 0xff) << 12) | (((w >> 20) & 1) << 11) | (((w >> 21) & 0x3ff) << 1)
        tgt = (pc + (imm - (1 << 21) if imm >> 20 else imm)) % (1 << 64)
        b = le(w)
        out += [f'/-- `{pc:#x}: jal {tgt:#x}`. -/', f'def {name} : JalSite where',
                f'  pc := {pc:#x}', *[f'  b{k} := 0x{b[k]:02x}#8' for k in range(4)],
                f'  w := 0x{w:08x}#32', f'  imm := 0x{imm:x}#21', f'  tgt := 0x{tgt:x}#64', '',
                f'theorem {name}_cert : {name}.Cert where',
                '  word := by decide', '  notrvc := by decide',
                f'  dec := fun σ h1 h2 h3 => Vsa.Sim.DecodeTable.decode_{w:08x} σ h1 h2 h3',
                '  tgt := by decide', '  tgt_align := by decide', '  lo := by decide',
                '  hi := by decide', '  align := by decide', '']
out += ['end VsaIris.Newlib.Sites', '']
text = '\n'.join(out)
dst = root / 'VsaIris/Vsa/H5Sites.lean'
if '--check' in sys.argv:
    sys.exit(0 if dst.exists() and dst.read_text() == text else 1)
dst.write_text(text)
