#!/usr/bin/env python3
"""Generate the kind-indexed error judgment `Vsa/AbsInt/ErrK.lean`.

The source is the mutual error judgment of `Vsa/While/ErrorSem.lean`. Each
relation `R` gains a leading `Kind` index as `RK`. Leaf rules conclude with
the kind of their error (table `LEAF`); propagation rules carry the kind of
the sub-error. Run with ``--check`` to detect drift without rewriting.
"""

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "Vsa/While/ErrorSem.lean"
OUTPUT = ROOT / "Vsa/AbsInt/ErrK.lean"

LEAF = {
    "varUndef": ".unbound",
    "assignUnbound": ".unbound",
    "binaryOp": "(binFailKind op lv rv)",
    "negType": ".type",
    "callTooMany": ".call",
    "notCallable": ".call",
    "badClosure": ".call",
    "arity": ".call",
    "depth": ".call",
    "escape": ".call",
    "assertFail": ".assert",
    "assertArity": ".assert",
}

RELS = re.compile(r"\b(EvalArgsErr|EvalErr|CallErr|ExecErr|ForLoopErr|ExecSeqErr)\b")

HEADER = '''-- Generated by scripts/gen_errk.py from Vsa/While/ErrorSem.lean. Do not edit.
import Vsa.While.ErrorSem
import Vsa.AbsInt.Domain

/-!
# The error judgment indexed by error kind

`EvalErrK k …` … `ExecSeqErrK k …` are the relations of
`Vsa/While/ErrorSem.lean` with a leading `Kind` index. A leaf rule concludes
with the kind of its error; `CallErrK.body` carries the kind of the error in
the closure body. `Vsa/AbsInt/ErrSound.lean` proves every `ExecSeqErr`
derivation has some kind.
-/

namespace Vsa.AbsInt

open Vsa.While

mutual

'''

FOOTER = '''
end
'''

END = '''
end Vsa.AbsInt
'''


def mutual_block(src: str) -> str:
    start = src.index("mutual\n\n/-- An expression evaluation reaches")
    end = src.index("\nend\n", start)
    blk = src[start + len("mutual\n"):end]
    blk = re.sub(r"/--.*?-/\n", "", blk, flags=re.S)
    return "\n".join(l for l in blk.split("\n") if not l.strip().startswith("--"))


def constructors(blk: str) -> list:
    """(relation, constructor, is_leaf) in declaration order."""
    rel, out = None, []
    for line in blk.split("\n"):
        if line.startswith("inductive "):
            rel = line.split()[1]
        elif line.startswith("  | "):
            name = line.split()[1]
            out.append((rel, name, name in LEAF))
    return out


MOTIVES = [
    ("EvalErr", "fun st d env e _ => HasKind fun k => EvalErrK k st d env e"),
    ("EvalArgsErr", "fun st d env es _ => HasKind fun k => EvalArgsErrK k st d env es"),
    ("CallErr", "fun st d fv vs _ => HasKind fun k => CallErrK k st d fv vs"),
    ("ExecErr", "fun st d env s _ => HasKind fun k => ExecErrK k st d env s"),
    ("ForLoopErr",
     "fun st d env cnd step b _ => HasKind fun k => ForLoopErrK k st d env cnd step b"),
    ("ExecSeqErr", "fun st d env ss _ => HasKind fun k => ExecSeqErrK k st d env ss"),
]


def bridge(blk: str) -> str:
    lines = [
        "",
        "/-- Some kind satisfies `P`. -/",
        "abbrev HasKind (P : Kind → Prop) : Prop := ∃ k, P k",
        "",
        "/-- Every runtime error of a statement sequence has a kind. -/",
        "theorem ExecSeqErr.hasKind {st : St} {d : Nat} {env : Addr} {ss : List Stmt}",
        "    (h : ExecSeqErr st d env ss) : HasKind fun k => ExecSeqErrK k st d env ss := by",
        "  refine ExecSeqErr.rec",
    ]
    for i, (_, m) in enumerate(MOTIVES, 1):
        lines.append(f"    (motive_{i} := {m})")
    ctors = constructors(blk)
    lines.append("    " + " ".join("?_" for _ in ctors) + " h")
    for rel, name, leaf in ctors:
        tgt = f"{rel}K.{name}"
        if leaf:
            lines.append(f"  · intros; exact ⟨_, by apply {tgt} <;> assumption⟩")
        else:
            lines.append(f"  · intros; rename_i ih; obtain ⟨k, _⟩ := ih")
            lines.append(f"    exact ⟨k, by apply {tgt} <;> assumption⟩")
    return "\n".join(lines) + "\n"


def transform(blk: str) -> str:
    chunks, cur = [], []
    for line in blk.split("\n"):
        if line.startswith("inductive ") or line.startswith("  | "):
            if cur:
                chunks.append(cur)
            cur = [line]
        else:
            cur.append(line)
    if cur:
        chunks.append(cur)
    out = []
    for c in chunks:
        if c[0].startswith("inductive "):
            c[0] = RELS.sub(lambda m: m.group(1) + "K", c[0]).replace(
                " : St →", " : Kind → St →")
            out += c
        elif c[0].startswith("  | "):
            name = c[0].split()[1]
            if name in LEAF:
                idx = max(i for i, l in enumerate(c) if l.strip())
                for l in c[:idx]:
                    if RELS.search(l):
                        sys.exit(f"gen_errk: leaf {name} has an error premise")
                c[idx] = RELS.sub(lambda m: m.group(1) + "K " + LEAF[name], c[idx])
            else:
                c = [RELS.sub(lambda m: m.group(1) + "K k", l) for l in c]
                c[0] = c[0].replace(f"  | {name} (", f"  | {name} (k : Kind) (", 1)
            out += c
        else:
            out += c
    return "\n".join(out).strip("\n") + "\n"


def render() -> str:
    blk = mutual_block(SOURCE.read_text())
    return HEADER + transform(blk) + FOOTER + bridge(blk) + END


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render()
    if args.check:
        if OUTPUT.read_text() != text:
            print(f"gen_errk: {OUTPUT.relative_to(ROOT)} is stale", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
