#!/usr/bin/env python3
"""gen_exec_row.py — emit the M4 statement-side case-routing file.

The `ExecS`/`ExecSeq` twin of `gen_m4_term_row.py`.  Each `mExecS`-motive minor
premise of `execSeq_sim_of_cases` (TermSimClose.lean) is `ExecIH …` by
definitional unfolding (`TermSimAssembly.mExecS = ExecBlock.ExecIH`); an
`exec_<case>_row` marshals the landed `*D` lemma (rows/ExecCaseGeom.lean) into
that slot.  This generator reads scripts/exec_rows.tsv and emits
Vsa/Sim/rows/ExecRouting.lean.

One shape:
  * leaf_reg — the register-only statement leaf (brk/cont): the landed sim's
    entry IS `ExecEntry` and its exit is `ExecExit`; the `*D` lemma
    (`execBrkSimD`/`execContSimD`) already bridges `out0 := c.σ.sailOutput` (rfl)
    and `ExecExit → ExecExitD` via the `ExecCaseGeom` bundle.  The row supplies
    that bundle ∀-closed over the ghosts as an `<Key>Resid`, and applies the
    `*D` lemma directly at the `ExecIH` motive shape.

The BLOCKED premises (retNull/varNull/expr/ret and every recursive/loop
statement case) are documented in the tsv header + the survey ledger and NOT
emitted; each has an honest per-row reason.

NO sorry/axiom/native_decide/bv_decide; no Mathlib.
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TSV = os.path.join(ROOT, "scripts/exec_rows.tsv")
OUT = os.path.join(ROOT, "Vsa/Sim/rows/ExecRouting.lean")

HEADER = """import Vsa.Sim.rows.ExecCaseGeom
import Vsa.Sim.TermSimClose

/-!
# `ExecRouting` — mechanical statement-side case rows (step-6, GENERATED)

Each `mExecS`-motive minor premise of `execSeq_sim_of_cases`
(`TermSimClose.lean`) is `ExecIH …` by definitional unfolding
(`TermSimAssembly.mExecS = ExecBlock.ExecIH`).  An `exec_<case>_row` adapter
marshals the corresponding landed `*D` lemma (`rows/ExecCaseGeom.lean`) into that
slot, threading the recursor-supplied `ExecCaseGeom` bundle (jump-table slot pin
+ its stack-disjointness + the `ExecLeafWiden` widener).

GENERATED by `scripts/gen_exec_row.py` from `scripts/exec_rows.tsv`.
DO NOT hand-edit.  NO `sorry`/`axiom`/`native_decide`/`bv_decide`.
-/

open LeanRV64DExecutable Sail Vsa
open Register
open Vsa.Machine (MState Config Halts Steps)
open Vsa.Logic (Triple)
open Vsa.RuntimeRepr Vsa.MemRepr Vsa.While Vsa.Alloc
open Vsa.Sim.Code
open Vsa.Sim.TermSimAssembly

namespace Vsa.Sim.Rows

local notation "SpecSt" => Vsa.While.St
"""

LEAF_REG_TMPL = """
/-- The {key}-case residual: the `ExecCaseGeom` bundle, ∀-closed over the ghosts. -/
def {Key}Resid (st : SpecSt) : Prop :=
  ∀ (g : (R : Register) → Option (RegisterType R))
    (N : NativeAddrs) (A : Arena) (SL : StackLayout) (φf φc : Addr → Nat)
    (sp r aRet : BitVec 64) (m0 : Mem),
    Vsa.Sim.ExecCaseGeom g N A SL φf φc st {statusPat} {k} Vsa.Sim.{armpc} sp r aRet m0

/-- Route `{name}` → `{simD}`. -/
theorem exec_{key}_row (hR : ∀ st, {Key}Resid st) :
    ∀ (st : SpecSt) (d : Nat) (env : Addr),
      mExecS st d env {stmt} st {status} ({ctor}) := by
  intro st d env
  show Vsa.Sim.ExecIH st d env {stmtShow} st {statusShow}
  intro g N A SL φf φc sp r aInterp aStmt aEnv aRet m0
  exact Vsa.Sim.{simD} g N A SL φf φc st d env sp r aInterp aStmt aEnv aRet m0
    ({ctor}) (hR st g N A SL φf φc sp r aRet m0)
"""


def status_pat(status):
    # `Status.brk` → `.brk` for the ExecCaseGeom / show arguments
    return "." + status.split(".")[-1]


def stmt_show(stmt):
    return "." + stmt.split(".")[-1]


def main():
    rows = []
    with open(TSV) as f:
        for line in f:
            line = line.rstrip("\n")
            if not line or line.startswith("#"):
                continue
            cols = line.split("\t")
            if cols[0] == "name":  # the column-header line
                continue
            (name, key, shape, simD, stmt, status, ctor, k, armpc, notes) = cols
            rows.append(dict(name=name, key=key, shape=shape, simD=simD,
                             stmt=stmt, status=status, ctor=ctor, k=k,
                             armpc=armpc, notes=notes))

    body = [HEADER]
    for r in rows:
        if r["shape"] != "leaf_reg":
            raise SystemExit(f"unknown shape {r['shape']} for {r['name']}")
        body.append(LEAF_REG_TMPL.format(
            key=r["key"], Key=r["key"].capitalize(), name=r["name"],
            simD=r["simD"], stmt=r["stmt"], status=r["status"], ctor=r["ctor"],
            k=r["k"], armpc=r["armpc"],
            statusPat=status_pat(r["status"]),
            stmtShow=stmt_show(r["stmt"]),
            statusShow=status_pat(r["status"]),
        ))
    body.append("\nend Vsa.Sim.Rows\n")

    with open(OUT, "w") as f:
        f.write("".join(body))
    print(f"wrote {OUT} ({len(rows)} rows)")


if __name__ == "__main__":
    main()
