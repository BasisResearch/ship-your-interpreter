#!/usr/bin/env python3
"""Abstraction-discovery gate (the `GATE:` rule of discipline_rules.tsv).

Fires when one obligation cluster reaches MIN hand-written proof units without
its per-case cost falling by at least a third between the first and the last
quarter of its history. The only allowed next task is a round of
`/abstraction-discovery` (record it in abstractions/ROUND-<n>.md).

Hand-written proof unit: a `theorem`/`lemma`, or a `#ix_seg`/`#ix_piece`/
`#sym_seg`-style proof command, in a file that is not generated (no
`Generated by` header and no match in scripts/generated_paths.txt).

Cluster: units whose names share a stem. The stem drops namespaces, hex
addresses, digits and one-letter variant markers (`BinaryAddP_eL_run_1` and
`BinaryLtP_eR_run_3` share `Binary run`), so it groups re-proofs of one shape
over varying data. A one-word name without an index (`S.facts`, `run`)
is a per-structure API method and is not clustered. Cost: non-blank lines of the unit. History order: the time
git first added the unit's file (untracked files count as newest), then line.

Clusters already stalled when the gate was installed are listed in
scripts/abstraction_gate_baseline.tsv with their size; they fail only when they
grow. Add a cluster there only with a note naming the round that decided it.

  python3 scripts/abstraction_gate.py            # check (exit 1 on a firing cluster)
  python3 scripts/abstraction_gate.py --report   # all clusters with >= MIN units
  python3 scripts/abstraction_gate.py --baseline # print baseline lines for firing clusters
"""
import argparse
import fnmatch
import math
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GENERATED = ROOT / "scripts" / "generated_paths.txt"
BASELINE = ROOT / "scripts" / "abstraction_gate_baseline.tsv"
DEFAULT_SCOPE = "Vsa/**/*.lean;VsaIris/**/*.lean"

GEN_HEADER = re.compile(r"^\s*(--|/-!?)\s*`?[Gg]enerated by\b", re.M)
UNIT = re.compile(r"^(?:@\[[^\]]*\]\s*)?(?:private\s+|protected\s+)?"
                  r"(?:theorem|lemma)\s+([^\s({:]+)"
                  r"|^#(?:ix_seg|ix_piece|sym_seg|sym_piece)\s+([^\s({:]+)")
TOP = re.compile(r"^(?:@\[|private\s|protected\s|noncomputable\s|theorem\s|lemma\s|def\s|"
                 r"abbrev\s|instance\s|structure\s|inductive\s|class\s|namespace\s|section\b|"
                 r"end\b|open\s|variable\s|set_option\s|macro\s|syntax\s|elab\s|#|/-)")
HEX = re.compile(r"(?:0x)?[0-9a-fA-F]{4,}")
TOKEN = re.compile(r"[A-Z]+(?=[A-Z][a-z]|\b|_|\d)|[A-Z]?[a-z]+|[A-Z]+")


def matches(rel: str, glob: str) -> bool:
    """fnmatch where `dir/**/x` also matches `dir/x`."""
    return fnmatch.fnmatch(rel, glob) or ("/**/" in glob and
                                         fnmatch.fnmatch(rel, glob.replace("/**/", "/")))


def stem(name: str) -> str:
    base = name.split(".")[-1]
    indexed = bool(HEX.search(base) or re.search(r"\d", base))
    base = HEX.sub("_", base)
    base = re.sub(r"\d+", "_", base)
    toks = [t for part in base.split("_") for t in TOKEN.findall(part)]
    toks = [t for t in toks if len(t) > 1]
    # `S.facts`, `run`, `trans`: a one-word name is a per-structure API method,
    # not a re-proof of one shape, unless it carries an index (`line_80004790`).
    if len(toks) <= 1 and not indexed:
        return ""
    return " ".join(toks)


def load_generated(root: Path):
    f = root / "scripts" / "generated_paths.txt"
    if not f.exists():
        return []
    return [l.strip() for l in f.read_text().splitlines()
            if l.strip() and not l.startswith("#")]


def add_times(root: Path):
    """Seconds since epoch at which git first added each file."""
    try:
        out = subprocess.run(
            ["git", "-C", str(root), "log", "--diff-filter=A", "--format=@%at",
             "--name-only", "--reverse", "--", "*.lean"],
            capture_output=True, text=True, check=True).stdout
    except (OSError, subprocess.CalledProcessError):
        return {}
    times, t = {}, 0
    for line in out.splitlines():
        if line.startswith("@"):
            t = int(line[1:])
        elif line.strip() and line not in times:
            times[line] = t
    return times


def units_of(text: str):
    lines = text.splitlines()
    starts = []
    for i, line in enumerate(lines):
        m = UNIT.match(line)
        if m:
            starts.append((i, m.group(1) or m.group(2)))
    for k, (i, name) in enumerate(starts):
        j = i + 1
        stop = starts[k + 1][0] if k + 1 < len(starts) else len(lines)
        while j < stop and not TOP.match(lines[j]):
            j += 1
        cost = sum(1 for l in lines[i:j] if l.strip())
        yield i + 1, name, cost


def clusters(root: Path, scope: str):
    globs = [g for g in scope.split(";") if g]
    gen = load_generated(root)
    times = add_times(root)
    newest = max(times.values(), default=0) + 1
    out = {}
    for f in sorted(root.rglob("*.lean")):
        rel = str(f.relative_to(root))
        if ".lake" in f.parts or not any(matches(rel, g) for g in globs):
            continue
        if any(matches(rel, g) for g in gen):
            continue
        text = f.read_text(errors="replace")
        if GEN_HEADER.search(text[:2000]):
            continue
        t = times.get(rel, newest)
        for line, name, cost in units_of(text):
            key = stem(name)
            if key:
                out.setdefault(key, []).append((t, rel, line, name, cost))
    for key in out:
        out[key].sort()
    return out


def verdict(members, shrink: float):
    n = len(members)
    q = max(1, math.ceil(n / 4))
    first = sum(m[4] for m in members[:q]) / q
    last = sum(m[4] for m in members[-q:]) / q
    return first, last, last > shrink * first


def load_baseline(root: Path):
    f = root / "scripts" / "abstraction_gate_baseline.tsv"
    base = {}
    if f.exists():
        for l in f.read_text().splitlines():
            if l.strip() and not l.startswith("#"):
                parts = l.split("\t")
                base[parts[0]] = int(parts[1])
    return base


def check(root: Path = ROOT, scope: str = DEFAULT_SCOPE, minimum: int = 8,
          shrink: float = 2 / 3):
    """Return (violations, firing) for the discipline driver."""
    base = load_baseline(root)
    violations, firing = [], []
    for key, members in sorted(clusters(root, scope).items()):
        if len(members) < minimum:
            continue
        first, last, stalled = verdict(members, shrink)
        if not stalled:
            continue
        firing.append((key, members, first, last))
        if key in base and len(members) <= base[key]:
            continue
        ex = members[-1]
        violations.append(
            f"cluster '{key}': {len(members)} hand proofs, mean cost {first:.0f} → "
            f"{last:.0f} lines (first → last quarter; needs ≤ {shrink * first:.0f}); "
            f"latest {ex[1]}:{ex[2]} {ex[3]}")
    return violations, firing


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", type=Path, default=ROOT)
    ap.add_argument("--scope", default=DEFAULT_SCOPE)
    ap.add_argument("--min", type=int, default=8)
    ap.add_argument("--shrink", type=float, default=2 / 3)
    ap.add_argument("--report", action="store_true")
    ap.add_argument("--baseline", action="store_true")
    a = ap.parse_args()
    if a.report:
        for key, members in sorted(clusters(a.root, a.scope).items(),
                                   key=lambda kv: -sum(m[4] for m in kv[1])):
            if len(members) < a.min:
                continue
            first, last, stalled = verdict(members, a.shrink)
            tag = "STALLED" if stalled else "falling"
            print(f"{sum(m[4] for m in members):7d} lines {len(members):5d} units  "
                  f"{first:6.1f} → {last:6.1f}  {tag:8s} {key}   e.g. {members[0][3]} "
                  f"({members[0][1]})")
        return 0
    violations, firing = check(a.root, a.scope, a.min, a.shrink)
    if a.baseline:
        for key, members, _, _ in firing:
            print(f"{key}\t{len(members)}\tknown at gate install; decide in a round")
        return 0
    if violations:
        print("abstraction gate: FAIL — run /abstraction-discovery "
              "(record the round in abstractions/ROUND-<n>.md)")
        for v in violations:
            print("  " + v)
        return 1
    print(f"abstraction gate: OK ({len(firing)} stalled clusters, all in the baseline)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
