#!/usr/bin/env python3
"""Generate `VsaIris/Vsa/MemcpySteps.lean`: `memcpy`'s per-instruction step table
over `MW` (`VsaIris/Vsa/MemcpyRun.lean`).

The allocator's step table (`gen_alloc_steps.py`, `AllocSteps/Part09.lean`)
already reflects every `memcpy` instruction (`ax_<pc>` segments, `st_<pc>`
lemmas over `AW`). `AW` fixes the read-only register `gp` and the code
`allocText`, which a `memcpy` caller does not own. This script rewrites each
`st_<pc>` of `[0x80006bc8, 0x80006cf0)` into `mst_<pc>` over `MW`: the same
segment, `mw_step` for `swp_step`, fetch facts from `Code.MemcpyLoaded`, and
loads from the read-only source image `img` (`ldvf`, `srcRead`) instead of
owned bytes. The `sltiu` at `0x80006bd8` is `MemcpyRun.mst_80006bd8`.

Usage: python3 scripts/gen_memcpy_steps.py [--check]
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / 'VsaIris/Vsa/AllocSteps/Part09.lean'
OUT = ROOT / 'VsaIris/Vsa/MemcpySteps.lean'
LO, HI = 0x80006bc8, 0x80006cf0

text = SRC.read_text()
blocks = re.split(r'\n(?=theorem )', text)
out = []
for b in blocks:
    m = re.match(r'theorem st_([0-9a-f]{8}) ', b)
    if not m or not (LO <= int(m.group(1), 16) < HI):
        continue
    b = b.split('\n\n')[0].rstrip()
    b = b.replace('theorem st_', 'theorem mst_', 1)
    b = b.replace('{live : Nat → Prop} {S : Nat → Prop}',
                  '{live : Nat → Prop} {Xs ns : Nat} {img : Nat → BitVec 8} {S : Nat → Prop}')
    b = b.replace('(hlive : ∀ p ∈ allocText, live p.1)', '(hlive : ∀ p ∈ mText, live p.1)')
    b = b.replace('AW live S Q', 'MW live Xs ns img S Q')
    b = re.sub(r'ldv (\.\w+) Mt', r'ldvf \1 img', b)
    b = re.sub(r'\(hLDS : ∀ b ∈ (accAddrs .*?), S b\)',
               r'(hin : ∀ b ∈ \1, Xs ≤ b ∧ b < Xs + ns)', b)
    # the load's byte list and its (now empty) owned-load list
    b = re.sub(r'\[bytesAt \(imgM Mt\) (.*?)\] \(accAddrs .*?\) \[\]', r'[bytesAt img \1] [] []', b)
    b = b.replace('swp_step ', 'mw_step ')
    b = b.replace('(fun m hm hLD => by unfold',
                  '(fun m hm hD hLD => by have hm := memcpyLoaded_of_text hm; unfold')
    b = b.replace('chain_facts hm with "VsaIris.Sym.alloc_at_"',
                  'chain_facts hm with "Vsa.Sim.Code.memcpy_at_"')
    b = re.sub(r'lpins(\d)_img hLD', r'lpins\1_fn (fun b hb => srcRead hD (hin b hb))', b)
    # hPC hks hgp hgprs → hks
    b = re.sub(r'\(by decide\) \(by decide\) \((?:fun h => absurd h \(by decide\)|fun h => nomatch h)\) \(by decide\) ',
               '(by decide) ', b)
    b = b.replace(' hLDS\n', ' (fun a h => by cases h)\n')
    assert 'swp_step' not in b and 'allocText' not in b and 'AW ' not in b, b
    out.append(b)

HEAD = '''-- Generated by scripts/gen_memcpy_steps.py; do not edit.
import VsaIris.Vsa.MemcpyRun
import VsaIris.Vsa.AllocSteps.Part09

/-! `memcpy`'s step table over `MW`: one lemma `mst_<pc>` per instruction of
`[0x80006bc8, 0x80006cf0)` but the `sltiu` (`MemcpyRun.mst_80006bd8`), over the
allocator table's segments `ax_<pc>`. -/

namespace VsaIris.Memcpy

open Vsa.Sim Vsa.MemRepr VsaIris.Inst VsaIris.MallocFast VsaIris.Sym
open LeanRV64DExecutable LeanRV64DExecutable.Functions Sail

'''
res = HEAD + '\n\n'.join(out) + '\n\nend VsaIris.Memcpy\n'
if '--check' in sys.argv:
    sys.exit(0 if OUT.read_text() == res else 1)
OUT.write_text(res)
print(f'{len(out)} lemmas')
