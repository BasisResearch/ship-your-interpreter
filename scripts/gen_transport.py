#!/usr/bin/env python3
"""gen_transport.py — the per-byte code/pin TRANSPORT emitter.

    python3 scripts/gen_transport.py <fn-symbol>... [-o] [--check]

For each function symbol F (as named in `experiments/disasm.txt`, e.g.
`_write`, `_write_r`, `__swrite`), emits `Vsa/Sim/rows/Transport<Fn>.lean`
containing the `<fn>Loaded_of_agree_lo`-style transport lemma

    theorem <fn>Loaded_of_agree_lo {m1 m0 : Std.ExtHashMap Nat (BitVec 8)}
        (hlo : ∀ j : Nat, j < tohostAddr → m1[j]? = m0[j]?)
        (h : Vsa.Sim.Code.<Fn>Loaded m0) : Vsa.Sim.Code.<Fn>Loaded m1

built PER-BYTE exactly like the hand-landed models
(`rows/FnWriteRFold.lean`'s `writeLoaded_of_agree_lo` /
`write_rLoaded_of_agree_lo`, `rows/FnSwriteFold.lean`'s
`swriteLoaded_of_agree_lo`): destructure the chunked byte-conjunction, rebuild
each byte fact as `(hlo 0x<addr> (by decide)).trans h<i>`.  This is the P2/P3
`<Fn>Loaded m → <Fn>Loaded (writeLog m log)` transport every fn fold needs —
promoted from the ad-hoc python one-offs inside the fold files.

Preconditions checked here: the `Vsa.Sim.Code.<Fn>` code file must exist
(gen_code_lemmas.py) and every code byte must sit below `tohostAddr`
(0x8001ad00 — the HTIF window), else the `by decide` obligations are false.

Site addresses/bytes are parsed with `experiments/gen_code_lemmas.py`'s own
parser (imported), so the conjunct order ALWAYS matches the generated
`<Fn>Loaded` chunk layout.

Emitted lemmas live in `namespace Vsa.Sim.Code` (beside the predicates they
transport) so they cannot collide with the fold files' landed local copies in
`Vsa.Sim` (dedup of those is a later cleanup).

NO `sorry`/`axiom`/`native_decide`/`bv_decide` in the output; no Mathlib.

Options:
  -o / --stdout   print the Lean text to stdout instead of writing the file
  --check         self-verify: run `lake env lean` on each emitted file
"""

import argparse
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "experiments"))
import gen_code_lemmas  # the parser + chunking constants (CHUNK, lean_ident)

# `Vsa.Sim.tohostAddr` (Vsa/Sim/InitValues.lean) — every code byte must sit
# below it for the emitted `by decide` side conditions to hold.
TOHOST_ADDR = 0x8001AD00


def emit(name, insts):
    """Return (out_path, lean_text) for one function's transport lemma."""
    f = gen_code_lemmas.lean_ident(name)
    F = f[0].upper() + f[1:]
    pred = f"Vsa.Sim.Code.{F}Loaded"
    stripped = f.lstrip("_")
    lemma = f"{stripped}Loaded_of_agree_lo"
    Fn = stripped[0].upper() + stripped[1:]
    out_path = os.path.join(ROOT, "Vsa", "Sim", "rows", f"Transport{Fn}.lean")

    hi = insts[-1][0] + 4
    if hi > TOHOST_ADDR:
        raise SystemExit(
            f"{name}: code bytes reach 0x{hi:x} ≥ tohostAddr 0x{TOHOST_ADDR:x}"
            " — the per-byte `by decide` transports would be false")

    chunks = [insts[i:i + gen_code_lemmas.CHUNK]
              for i in range(0, len(insts), gen_code_lemmas.CHUNK)]

    # global byte index → (addr); values are irrelevant to the transport
    # (the `.trans` reuses the byte fact h<i> whole).
    chunk_addrs = [[addr + k for addr, _word in ch for k in range(4)]
                   for ch in chunks]
    nbytes = sum(len(ca) for ca in chunk_addrs)

    L = []
    L.append(f"import Vsa.Sim.Code.{f}")
    L.append("import Vsa.Sim.InitValues")
    L.append("")
    L.append("/-!")
    L.append(f"# `Transport{Fn}` — the `{name}` code-pin transport "
             "(scripts/gen_transport.py)")
    L.append("")
    L.append(f"`{pred} m → {pred} m'` across any memory that agrees below "
             "`tohostAddr`")
    L.append(f"(all `{name}` code bytes sit below the HTIF window: "
             f"[0x{insts[0][0]:x}, 0x{hi:x})).")
    L.append("Built per-byte exactly like the hand-landed "
             "`rows/FnWriteRFold.lean`")
    L.append("`writeLoaded_of_agree_lo` idiom.  The write-log instantiation "
             "is the caller's:")
    L.append("`hlo` is typically `<log>_agree_lo`-shaped "
             "(`wrM1_agree_lo`-style disjointness).")
    L.append("")
    L.append("GENERATED by `scripts/gen_transport.py`.  DO NOT hand-edit.")
    L.append("NO `sorry`/`axiom`/`native_decide`/`bv_decide`; no Mathlib.")
    L.append("-/")
    L.append("")
    L.append("namespace Vsa.Sim.Code")
    L.append("")
    # --- per-chunk transports (64-wide obtains; the monolithic whole-module
    # obtain explodes elaboration on big modules — observation
    # gen-transport-monolithic-obtain-explodes) ---
    for gi, ca in enumerate(chunk_addrs):
        L.append(f"theorem {stripped}Chunk{gi}_of_agree_lo "
                 "{m1 m0 : Std.ExtHashMap Nat (BitVec 8)}")
        L.append("    (hlo : ∀ j : Nat, j < tohostAddr → m1[j]? = m0[j]?)")
        L.append(f"    (h : Vsa.Sim.Code.{f}Chunk{gi} m0) : "
                 f"Vsa.Sim.Code.{f}Chunk{gi} m1 := by")
        L.append("  obtain ⟨" + ", ".join(f"h{k}" for k in range(len(ca)))
                 + "⟩ := h")
        lines = ["  exact ⟨(hlo 0x%08x (by decide)).trans h0," % ca[0]]
        for k, a in enumerate(ca[1:-1], start=1):
            lines.append(f"    (hlo 0x{a:08x} (by decide)).trans h{k},")
        lines.append(f"    (hlo 0x{ca[-1]:08x} (by decide)).trans "
                     f"h{len(ca) - 1}⟩")
        L += lines
        L.append("")
    L.append(f"/-- Transport `{F}Loaded` across a memory that agrees below "
             "`tohostAddr`")
    L.append(f"(all `{name}` code bytes sit below the HTIF window). -/")
    L.append(f"theorem {lemma} {{m1 m0 : Std.ExtHashMap Nat (BitVec 8)}}")
    L.append("    (hlo : ∀ j : Nat, j < tohostAddr → m1[j]? = m0[j]?)")
    L.append(f"    (h : {pred} m0) : {pred} m1 := by")
    if len(chunk_addrs) == 1:
        L.append(f"  exact {stripped}Chunk0_of_agree_lo hlo h")
    else:
        L.append("  obtain ⟨" + ", ".join(
            f"hc{gi}" for gi in range(len(chunk_addrs))) + "⟩ := h")
        L.append("  exact ⟨" + ", ".join(
            f"{stripped}Chunk{gi}_of_agree_lo hlo hc{gi}"
            for gi in range(len(chunk_addrs))) + "⟩")
    L.append("")
    L.append(f"#print axioms {lemma}")
    L.append("")
    L.append("end Vsa.Sim.Code")
    L.append("")
    return out_path, "\n".join(L), nbytes


def main():
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("fns", nargs="+", help="function symbols (disasm names)")
    ap.add_argument("-o", "--stdout", action="store_true",
                    help="print to stdout instead of writing the rows/ file")
    ap.add_argument("--check", action="store_true",
                    help="run `lake env lean` on each emitted file")
    args = ap.parse_args()

    funcs = gen_code_lemmas.parse(os.path.join(ROOT, "experiments/disasm.txt"))
    rc = 0
    for name in args.fns:
        if name not in funcs:
            sys.exit(f"function {name!r} not in disasm (have e.g. "
                     f"{list(funcs)[:5]})")
        out_path, text, nbytes = emit(name, funcs[name])
        if args.stdout:
            print(text)
            continue
        with open(out_path, "w") as fh:
            fh.write(text)
        print(f"wrote {out_path} ({nbytes} byte facts)")
        if args.check:
            r = subprocess.run(["lake", "env", "lean", out_path], cwd=ROOT)
            if r.returncode != 0:
                print(f"CHECK FAILED: {out_path}")
                rc = 1
            else:
                print(f"check OK: {out_path}")
    return rc


if __name__ == "__main__":
    sys.exit(main())
