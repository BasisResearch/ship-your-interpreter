#!/usr/bin/env python3
"""Generate `Vsa/Densify/Gen*.lean`: one `Resp` theorem per monadic model function
in `Vsa.stepOnce`'s call graph (P3, presence-insensitivity of the Sail model).

Input: the dependency-ordered closure `experiments/densify/closure.tsv`
(`name<TAB>arity<TAB>flag<TAB>callee,callee,...`), produced by
`experiments/densify/Closure.lean` (`lake env lean`). Every function whose
`Resp` is proved by hand is listed in HAND below; the generated files are split
around the hand-proved `pt_walk` (`Vsa/Densify/RecMutual.lean`, `Vsa/Densify/RecPt.lean`).

    python3 -B scripts/gen_resp.py          # write the files
    python3 -B scripts/gen_resp.py --check  # fail if the files would change
"""
import sys, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CLOSURE = os.path.join(ROOT, "experiments/densify/closure.tsv")
PS = "Sail.ConcurrencyInterfaceV1.PreSail."
MODEL = "LeanRV64DExecutable."

# hand-proved (Vsa/Densify/Resp.lean) or tactic-handled: constant -> lemma to pass (or None)
HAND = {
    PS + "readReg": "PS.readReg_resp", PS + "writeReg": "PS.writeReg_resp", PS + "assert": "PS.assert_resp",
    PS + "sailThrow": "PS.sailThrow_resp", PS + "readByte": "PS.readByte_resp", PS + "readBytes": "PS.readBytes_resp",
    PS + "writeByte": "PS.writeByte_resp", PS + "writeBytes": "PS.writeBytes_resp",
    PS + "sail_mem_read": "PS.sail_mem_read_resp", PS + "sail_mem_write": "PS.sail_mem_write_resp",
    PS + "sail_barrier": "PS.sail_barrier_resp", PS + "cycle_count": "PS.cycle_count_resp",
    PS + "print_effect": "PS.print_effect_resp", PS + "print_bits_effect": "PS.print_bits_effect_resp",
    PS + "PreSailME.run": None, PS + "PreSailME.throw": None,
    MODEL + "SailME.run": None, MODEL + "SailME.throw": None,
    PS + "readBytes._f": None,
    MODEL + "Functions.pt_walk._unary": None,  # RecPt.lean
    MODEL + "Functions.pt_walk": "RecPt.pt_walk_resp",  # RecPt.lean
    # the model's reducible wrappers of the primitives
    MODEL + "readReg": "PS.readReg_resp", MODEL + "writeReg": "PS.writeReg_resp", MODEL + "assert": "PS.assert_resp",
    MODEL + "cycle_count": "PS.cycle_count_resp",
    MODEL + "print_effect": "PS.print_effect_resp", MODEL + "print_bits_effect": "PS.print_bits_effect_resp",
    MODEL + "ConcurrencyInterfaceV1.sail_mem_read": "PS.sail_mem_read_resp",
    MODEL + "ConcurrencyInterfaceV1.sail_mem_write": "PS.sail_mem_write_resp",
    MODEL + "ConcurrencyInterfaceV1.sail_barrier": "PS.sail_barrier_resp",
}
MUTUAL = ["check_stateen_bit", "currentlyEnabled", "get_hstateen", "get_sstateen", "get_xLPE",
          "is_hstateen_accessible", "is_sstateen_accessible", "is_zfinx_enabled_by_stateen",
          "virtual_memory_supported"]   # PlatformConfig.lean `mutual` block: RecMutual.lean
for m in MUTUAL: HAND[MODEL + "Functions." + m] = "RecMutual." + m + "_resp"
PT = [MODEL + "Functions.pt_walk._unary", MODEL + "Functions.pt_walk"]
FINAL = "Vsa.stepOnce"

def mangle(name):
    n = name[len(MODEL):] if name.startswith(MODEL) else name   # root-level names (RiscvExtrasExecutable.lean)
    if n.startswith("Functions."): n = n[len("Functions."):]
    return n.replace(".", "_") + "_resp"

def lemma_of(name):
    if name in HAND: return HAND[name]
    if name == FINAL: return "stepOnce_resp"
    return mangle(name)

def theorem(name, arity, callees):
    args = " ".join(f"a{i}" for i in range(arity))
    binders = " ".join(f"(a{i} : _)" for i in range(arity))
    lname = "stepOnce_resp" if name == FINAL else mangle(name)
    ls = [l for l in (lemma_of(c) for c in callees) if l]
    lst = f" [{', '.join(ls)}]" if ls else ""
    stmt = f"theorem {lname} : Resp (@{name})" if arity == 0 else \
        f"theorem {lname} : ∀ {binders}, Resp (@{name} {args})"
    intro = f"  intro {args}\n" if arity else ""
    return f"{stmt} := by\n{intro}  unfold {name}\n  resp_auto{lst}\n"

HEADER = """import {imp}

/-!
# Generated by `scripts/gen_resp.py` — DO NOT EDIT

`Resp` for every monadic function of the executable Sail model in
`Vsa.stepOnce`'s call graph{part}. See `Vsa/Densify/Resp.lean`.
-/

namespace Vsa.Densify.Gen

open Sail ConcurrencyInterfaceV1 LeanRV64DExecutable LeanRV64DExecutable.Functions
open Sail.ConcurrencyInterfaceV1.PreSail

"""
FOOTER = "\nend Vsa.Densify.Gen\n"

def main():
    rows = [l.rstrip("\n").split("\t") for l in open(CLOSURE) if l.strip()]
    mutual = {MODEL + "Functions." + m for m in MUTUAL}
    # bucket by transitive dependence on the hand-proved groups (postorder keeps callees first)
    level = {}   # name -> 0 (needs nothing hand-recursive), 1 (needs the mutual block), 2 (needs pt_walk)
    files = {0: [], 1: [], 2: []}
    for name, ar, flag, cs in rows:
        callees = [c for c in cs.split(",") if c]
        lv = max([level.get(c, 0) for c in callees] + [0])
        if name in mutual: lv = max(lv, 1)
        if name in PT: lv = max(lv, 2)
        level[name] = lv
        if name in HAND: continue
        files[lv].append(theorem(name, int(ar), callees))
    outs = {
        "Vsa/Densify/GenA.lean": HEADER.format(imp="Vsa.Densify.Tactic", part=" (independent of the recursive functions)") + "\n".join(files[0]) + FOOTER,
        "Vsa/Densify/GenB.lean": HEADER.format(imp="Vsa.Densify.RecMutual", part=" (after the `currentlyEnabled` block)") + "\n".join(files[1]) + FOOTER,
        "Vsa/Densify/GenC.lean": HEADER.format(imp="Vsa.Densify.RecPt", part=" (after the page walk), ending with `stepOnce`") + "\n".join(files[2]) + FOOTER,
    }
    check = "--check" in sys.argv
    bad = 0
    for rel, text in outs.items():
        p = os.path.join(ROOT, rel)
        old = open(p).read() if os.path.exists(p) else None
        if check:
            if old != text:
                print(f"drift: {rel}"); bad += 1
        else:
            open(p, "w").write(text); print(f"wrote {rel} ({text.count('theorem ')} theorems)")
    sys.exit(1 if bad else 0)

if __name__ == "__main__":
    main()
