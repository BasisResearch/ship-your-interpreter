#!/usr/bin/env python3
"""Generate `VsaIris/Vsa/ExitH/Run{Idle,Written}.lean` (lane N4): `exit`'s
newlib interior (`0x80004778` to `0x80004788`) as a chain of symbolic-run
pieces over the stdio step table, one chain per `stderr` state (idle at the
boundary, or after one write).

Every piece but the first is `xh_step`: drop the previous piece's branch
hypotheses, forget the dead stack below `sp`, keep one update per register,
run `STEPS` steps (`nx_run`). The last piece hands the state at `0x80004788`
to the continuation `hk` (`ExitEnd`). The facts the run rewrites with are the
fields of `CloseMt` and `ErrIdleMt`/`ErrWrittenMt` (`ExitH/Facts.lean`).

Usage: python3 scripts/gen_exit_handlers.py [--check]
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
STEPS = {'Idle': 20, 'Written': 10}
# pieces per chain (the run reaches `0x80004788` within them)
PIECES = {'Idle': 22, 'Written': 45}
STOP = 0x80004788

SIN, SOUT, SERR = 0x8001ba68, 0x8001bb20, 0x8001bbd8

# The load facts the runs rewrite with: (field, load kind, address, value, source).
# The source is a field of `CloseCommon m` / `ExitIdleFile m stderr 0x12 2` /
# `ErrWrittenFile m stderr` at the canonical memory `m` of an image (`h`).


def file_idle(F, fl, fd):
    return [('flagsU', 'lhu', F + 16, fl, 'flags_read'), ('flags', 'lh', F + 16, fl, 'flags_read'),
            ('fd', 'lh', F + 18, fd, 'descriptor_read'), ('r', 'lw', F + 8, 0, 'readCount'),
            ('ur', 'lw', F + 112, 0, 'savedReadCount'), ('cookie', 'ld', F + 48, F, 'cookie'),
            ('close', 'ld', F + 80, 0x8000f0c0, 'closeCallback'), ('ub', 'ld', F + 88, 0, 'ungetcBuffer'),
            ('lb', 'ld', F + 120, 0, 'lineBuffer'), ('lock', 'ld', F + 160, 0, 'lock'),
            ('mode', 'lw', F + 176, 0, 'lockMode')]


CLOSE = ([('atexit', 'ld', 0x8001b9f8, 0, 'atexit'), ('handler', 'ld', 0x8001b9b0, 0x80005d18, 'stdioHandler'),
          ('glueNext', 'ld', 0x8001b520, 0, 'glueNext'), ('glueCount', 'lw', 0x8001b528, 3, 'glueCount'),
          ('glueFiles', 'ld', 0x8001b530, SIN, 'glueFiles'), ('sinit', 'ld', 0x8001b580, 0x80005d2c, 'console.sinit')] +
         [('in_' + f, k, a, v, 'stdin.' + s) for f, k, a, v, s in file_idle(SIN, 4, 0)] +
         [('out_flagsU', 'lhu', SOUT + 16, 0x200a, 'console.flags'), ('out_flags', 'lh', SOUT + 16, 0x200a, 'console.flags'),
          ('out_fd', 'lh', SOUT + 18, 1, 'console.fd'), ('out_base', 'ld', SOUT + 24, 0x8001bb97, 'console.base'),
          ('out_p', 'ld', SOUT, 0x8001bb97, 'console.cursor'), ('out_cookie', 'ld', SOUT + 48, SOUT, 'console.cookie'),
          ('out_close', 'ld', SOUT + 80, 0x8000f0c0, 'stdoutClose'), ('out_ub', 'ld', SOUT + 88, 0, 'stdoutUngetc'),
          ('out_lb', 'ld', SOUT + 120, 0, 'stdoutLine'), ('out_lock', 'ld', SOUT + 160, 0, 'console.lock'),
          ('out_mode', 'lw', SOUT + 176, 0, 'console.lockMode')])
ERRF = {'Idle': file_idle(SERR, 0x12, 2),
        'Written': [('flagsU', 'lhu', SERR + 16, 0x201a, 'flags_read'), ('flags', 'lh', SERR + 16, 0x201a, 'flags_read'),
                    ('fd', 'lh', SERR + 18, 2, 'descriptor_read'), ('base', 'ld', SERR + 24, SERR + 119, 'base'),
                    ('p', 'ld', SERR, SERR + 119, 'cursor'), ('cookie', 'ld', SERR + 48, SERR, 'cookie'),
                    ('close', 'ld', SERR + 80, 0x8000f0c0, 'closeCallback'), ('ub', 'ld', SERR + 88, 0, 'ungetcBuffer'),
                    ('lb', 'ld', SERR + 120, 0, 'lineBuffer'), ('lock', 'ld', SERR + 160, 0, 'lock'),
                    ('mode', 'lw', SERR + 176, 0, 'lockMode')]}
ERR = {k: [f[0] for f in v] for k, v in ERRF.items()}
WIDTH = {'ld': 8, 'lw': 4, 'lh': 2, 'lhu': 2}
DOC = {'CloseMt': 'The fields the close path reads besides `stderr`\'s `FILE`, as loads.',
       'ErrIdleMt': '`stderr` at the boundary (`ExitIdleFile … 0x12 2`), as loads.',
       'ErrWrittenMt': '`stderr` after one write (`ErrWrittenFile`), as loads.'}


def struct(name, rows):
    return (f'/-- {DOC[name]} -/\nstructure {name} (Mt : Mem) : Prop where\n' +
            '\n'.join(f'  {f} : ldv .{k} Mt {a:#x} = {v:#x}#64' for f, k, a, v, _ in rows) + '\n')


def conv(f, k, a, v, src):
    """The load fact from its `read*` source, through `hM`."""
    base = f'(stdio_imgLE (fun a ha _ => hM a ha) h.{src} (stdioFoot_rng {a:#x} {WIDTH[k]} (by decide)))'
    if k == 'ld':
        return f'ldv_ld_of_imgLE {base}'
    if k == 'lhu':
        return f'ldv_lhu_of_imgLE {base}'
    return f'(ldv_{k}_of_imgLE {base}).trans (by decide)'


def of_lemma(name, src_ty, rows, doc):
    return (f'/-- {doc} -/\ntheorem {name[0].lower() + name[1:]}_of {{img : Nat → BitVec 8}} {{Mt : Mem}}\n'
            f'    (h : {src_ty}) (hM : ∀ a, stdioFoot a → imgM Mt a = img a) : {name} Mt :=\n'
            + '  ⟨' + ',\n   '.join(conv(*r) for r in rows) + '⟩\n')


def gen_loads():
    L = ['''-- Generated by scripts/gen_exit_handlers.py; do not edit.
import VsaIris.Vsa.ExitH.Facts
import VsaIris.Vsa.Stdout.Console
import VsaIris.Vsa.StdioErr

/-!
# The fields `exit`'s close path reads, as loads (lane N4)

`CloseMt`, `ErrIdleMt`, `ErrWrittenMt`: each field a load value of the
tracking memory `Mt`, the form `nx_run` rewrites with. `closeMt_of`,
`errIdleMt_of`, `errWrittenMt_of` derive them from `CloseCommon` /
`ExitIdleFile` / `ErrWrittenFile` (`StdioErr.lean`) at an image's canonical
memory (`fillMem img dataList`), when `Mt` agrees with the image on
`stdioFoot` (N1's `stdio_imgLE`).
-/

namespace VsaIris.Sym

open Vsa.Sim Vsa.MemRepr VsaIris.Interp VsaIris.MallocFast VsaIris.Stdio
open LeanRV64DExecutable LeanRV64DExecutable.Functions

/-- A range of newlib's data off `_impure_ptr`, checked. -/
theorem stdioFoot_rng (a n : Nat)
    (h : (decide (0x8001b520 ≤ a ∧ a + n ≤ 0x8001b538) || decide (0x8001b53c ≤ a ∧ a + n ≤ 0x8001b960) ||
      decide (0x8001b978 ≤ a ∧ a + n ≤ 0x8001b990) || decide (0x8001b9b0 ≤ a ∧ a + n ≤ 0x8001ba08) ||
      decide (0x8001ba0c ≤ a ∧ a + n ≤ 0x8001ba18) || decide (0x8001ba68 ≤ a ∧ a + n ≤ 0x8001c168)) = true) :
    ∀ i, i < n → stdioFoot (a + i) ∧ ¬ impureW (a + i) := by
  intro i hi
  simp only [Bool.or_eq_true, decide_eq_true_eq] at h
  unfold stdioFoot InRange impureW
  omega

''']
    L.append(struct('CloseMt', CLOSE))
    L.append(struct('ErrIdleMt', ERRF['Idle']))
    L.append(struct('ErrWrittenMt', ERRF['Written']))
    M = 'fillMem img dataList'
    L.append(of_lemma('CloseMt', f'CloseCommon ({M})', CLOSE, '`CloseMt` from `CloseCommon`.'))
    L.append(of_lemma('ErrIdleMt', f'ExitIdleFile ({M}) exitStderr 0x12 2', ERRF['Idle'],
                      '`ErrIdleMt` from `stderr` idle.'))
    L.append(of_lemma('ErrWrittenMt', f'ErrWrittenFile ({M}) exitStderr', ERRF['Written'],
                      '`ErrWrittenMt` from `stderr` written.'))
    L.append('end VsaIris.Sym\n')
    return '\n'.join(L)


SIMPROCS = ['BitVec.add_assoc', 'BitVec.reduceAnd', 'BitVec.reduceOr', 'BitVec.reduceSub',
            'BitVec.reduceMul', 'BitVec.reduceShiftLeft', 'BitVec.reduceHShiftLeft',
            'Nat.reducePow', 'Nat.reduceMod', 'BitVec.reduceOfNat']


def using(err):
    return ', '.join(['h2', 'h8', 'h11'] + [f'hC.{r[0]}' for r in CLOSE] +
                     [f'hE.{f}' for f in ERR[err]] + SIMPROCS)


def gen(err):
    n = PIECES[err]
    P = f'exit{err}'
    u = using(err)
    L = [f'''-- Generated by scripts/gen_exit_handlers.py; do not edit.
import VsaIris.Vsa.ExitH.Tac

/-!
# `exit`'s newlib interior with `stderr` {'idle' if err == 'Idle' else 'written'} (lane N4)

`{P}_run`: from `jal __call_exitprocs` (`0x80004778`) with `a1 = 0`,
`sp = s`, `s0 = e`, the close path's fields (`CloseMt`) and `stderr`
{'at the boundary (`ErrIdleMt`)' if err == 'Idle' else 'after one write (`ErrWrittenMt`)'}, the run reaches `mv a0,s0`
(`0x80004788`) with `sp`, `s0` and `s1`–`s11` as at the entry (`ExitEnd`).
A chain of `{n}` pieces of at most {STEPS[err]} steps each (`scripts/gen_exit_handlers.py`).
-/

namespace VsaIris.Sym

open Vsa.Sim Vsa.MemRepr VsaIris.Interp VsaIris.MallocFast VsaIris.Stdio
open scoped VsaIris.Sym.Stdout VsaIris.Sym.XH

set_option hygiene false in
/-- One piece of the `{err}` run. -/
macro "xh_step{err}" : tactic => `(tactic| (intros; xh_clean; xh_forget_sp (s.toNat - 256); xh_compactR; nx_run [{STEPS[err]}] hlive using [{u}] at {STOP}))

#ix_piece {P}_01 {{live : Nat → Prop}} (hlive : ∀ p ∈ stdioText, live p.1)
    {{Q : (Nat → BitVec 64) → (Nat → BitVec 8) → Prop}} {{R : Nat → BitVec 64}} {{Mt : Mem}}
    {{s e : BitVec 64}} (hs : ExitSp s) (h2 : R 2 = s) (h8 : R 8 = e) (h11 : R 11 = 0#64)
    (hC : CloseMt Mt) (hE : Err{err}Mt Mt)
    (hk : ∀ R' Mt', ExitEnd R s e R' → NW live ∅ [] (exitS s) Q 0x80004788#64 R' Mt') :
    NW live ∅ [] (exitS s) Q 0x80004778#64 R Mt
  by
    have hs1 := hs.lo; have hs2 := hs.hi; have hs3 := hs.align; have hs4 := hs.place
    nx_run [{STEPS[err]}] hlive using [{u}] at {STOP}
''']
    for k in range(2, n + 1):
        L.append(f'#ix_piece {P}_{k:02d} from {P}_{k - 1:02d} by\n  xh_step{err}\n')
    L.append(f'#ix_piece {P}_end from {P}_{n:02d} by\n  xh_end\n')
    L.append(f'#ix_chain {P}_chain := [{", ".join([f"{P}_{k:02d}" for k in range(1, n + 1)] + [f"{P}_end"])}]\n')
    L.append('end VsaIris.Sym\n')
    return '\n'.join(L)


def main():
    stale = []
    outs = {ROOT / f'VsaIris/Vsa/ExitH/Run{err}.lean': gen(err) for err in PIECES}
    outs[ROOT / 'VsaIris/Vsa/ExitH/Loads.lean'] = gen_loads()
    for out, text in outs.items():
        if '--check' in sys.argv:
            if not out.exists() or out.read_text() != text:
                stale.append(out.relative_to(ROOT))
        else:
            out.write_text(text)
    for s in stale:
        print(f'stale: {s}', file=sys.stderr)
    return 1 if stale else 0


if __name__ == '__main__':
    sys.exit(main())
