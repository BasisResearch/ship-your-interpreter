#!/usr/bin/env python3
"""Generate the string leaves' per-instruction step table (`strlen`, `strcpy`).

The twin of `gen_interp_steps.py` over `SW` (`VsaIris/Interp/StrCode.lean`):
`SR` (`VsaIris/Interp/StrRun.lean`), a symbolic run with NO read-only
register (`strlenSpec`/`strcpySpec` hand over no `gp`), whose read-only list
is the two leaves' code `strCode` (live) followed by a string's bytes `D`
(persistent data, total reads).

Output (do not hand-edit): `VsaIris/Interp/StrSteps.lean`, per instruction
one single-instruction segment (two for a branch) and one step lemma:

* `sl_<pc>`: ALU, store (to OWNED bytes), branch, `ret`;
* `slH_<pc>`: a load. The value is `ldvf k f ea` for EVERY byte function `f`
  agreeing with `D` (`sr_havoc`): the word loops read past the NUL, into
  bytes nobody hands over;
* `slO_<pc>`: `sltu` (`snez`), outside the reflected block model, as an
  observed ALU step (`sr_alu`).

Usage: python3 scripts/gen_str_steps.py [--check]
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from rv_steps import classify_word, src as _src, sx12  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
FUNCS = ['strlen', 'strcpy']
OUT = 'VsaIris/Interp/StrSteps.lean'
HEADER = '-- Generated by scripts/gen_str_steps.py; do not edit.'
LOADED = {'strlen': ('strlenLoaded_of_str', 'Vsa.Sim.Code.strlen_at_'),
          'strcpy': ('strcpyLoaded_of_str', 'Vsa.Sim.Code.strcpy_at_')}


def src(r):
    return _src(r, None)


W, MN, FN = {}, {}, {}
fn = None
for l in open(ROOT / 'experiments/disasm.txt'):
    m = re.match(r'^([0-9a-f]+) <(.*)>:$', l)
    if m:
        fn = m.group(2)
        continue
    m = re.match(r'^\s+([0-9a-f]+):\t([0-9a-f]{8})\s+\t(\S+)', l)
    if m and fn in FUNCS:
        pc = int(m.group(1), 16)
        W[pc] = int(m.group(2), 16)
        MN[pc] = m.group(3)
        FN[pc] = fn
PCS = sorted(W)

DEC = {}
for l in open(ROOT / 'scripts/decode_index.tsv'):
    w, mod = l.split()
    DEC[int(w, 16)] = mod


def classify(pc):
    w = W[pc]
    op, rd, f3, f7 = w & 0x7f, (w >> 7) & 31, (w >> 12) & 7, w >> 25
    rs1, rs2 = (w >> 15) & 31, (w >> 20) & 31
    if op == 0x33 and f3 == 3 and f7 == 0 and rd != 0:
        return ('obs', dict(rd=rd, rs1=rs1, rs2=rs2))
    return classify_word(pc, w, None)


def ks_of(regs):
    return sorted({r for r in regs if r != 0})


def lst(xs):
    return '[' + ', '.join(str(x) for x in xs) + ']'


def hR(ks):
    alts = ' | '.join(['rfl'] * len(ks))
    return ('(by intro x hx; simp only [List.mem_cons, List.not_mem_nil, or_false] at hx; '
            f'rcases hx with {alts} <;> rfl)')


def hRo(ks, rd=None):
    if rd is None:
        return '(fun _ _ _ _ => rfl)'
    return f'(fun x _ _ hx => upd_other _ _ (fun e => hx (e ▸ (by decide : {rd} ∈ {lst(ks)}))))'


def hdr(name, pc):
    return (f"theorem {name}_{pc:08x} {{live : Nat → Prop}} {{D : List (Nat × BitVec 8)}} {{S : Nat → Prop}}\n"
            f"    {{Q : (Nat → BitVec 64) → (Nat → BitVec 8) → Prop}} {{R : Nat → BitVec 64}} {{Mt : Mem}}\n"
            f"    (hlive : ∀ p ∈ strCode, live p.1)")


def cf(pc):
    lem, pfx = LOADED[FN[pc]]
    return f'chain_facts ({lem} hm) with "{pfx}"'


def step(seg, pc, ks, Wr, cover, tail, hpc, R, Ro, hk, ind='  '):
    t = f'; {tail}' if tail else ''
    wr = 'hS' if Wr != '[]' else '(fun a h => by cases h)'
    return (f'{ind}sr_step {seg} {lst(ks)} [] {Wr} 0 rfl (by decide) (by decide) (by decide)\n'
            f'{ind}  {cover} hlive\n'
            f'{ind}  (fun m hm => by unfold {seg} ChainFacts; {cf(pc)}{t})\n'
            f'{ind}  (by decide) {wr} {hpc}\n'
            f'{ind}  {R}\n'
            f'{ind}  {Ro} rfl {hk}')


def sw(pc_expr, R='R', Mt='Mt'):
    return f'SW live D S Q {pc_expr} {R} {Mt}'


def emit(pc):
    cls, d = classify(pc)
    w = W[pc]
    bs = [(w >> (8 * i)) & 0xff for i in range(4)]
    nxt = f'0x{pc + 4:x}#64'
    segs, thm = [], []
    if cls == 'unsupported':
        return None, None
    single = f'def stx_{pc:08x} : List BBlock := [{{ body := [mkLine 0x{pc:x}#64 0x{w:08x}#32], term := none }}]'
    tinstr = lambda kind, rs1, rs2, i13, i21: (
        f'⟨0x{pc:x}#64, 0x{w:08x}#32, 0x{bs[0]:02x}#8, 0x{bs[1]:02x}#8, 0x{bs[2]:02x}#8, '
        f'0x{bs[3]:02x}#8, {kind}, {rs1}, {rs2}, 0x{i13 & 0x1fff:x}#13, 0x{i21 & 0x1fffff:x}#21, 0#12⟩')
    tdef = lambda name, kind, rs1, rs2, i13, i21: (
        f'def {name} : List BBlock := [⟨[], some ({tinstr(kind, rs1, rs2, i13, i21)} : TInstr)⟩]')
    NIL = '(fun a _ => trivial)'
    if cls == 'alu':
        segs.append(single)
        ks = ks_of(d['srcs'] + [d['rd']])
        thm.append(hdr('sl', pc) + f"""
    (hk : {sw(nxt, f"(upd R {d['rd']} ({d['val']}))")}) :
    {sw(f'0x{pc:x}#64')} :=
""" + step(f'stx_{pc:08x}', pc, ks, '[]', NIL, '', 'rfl', hR(ks), hRo(ks, d['rd']), 'hk'))
    elif cls == 'load':
        segs.append(single)
        ea = f"({src(d['rs1'])} + {sx12(d['imm'])}).toNat"
        wd = d['width']
        ks = ks_of([d['rs1'], d['rd']])
        suf = {8: '8', 4: '4', 1: '1', 2: '2'}[wd]
        rd = d['rd']
        alts = ' | '.join(['rfl'] * len(ks))
        thm.append(hdr('slH', pc) + f"""
    (hea : LdOK {ea} {wd})
    (hk : ∀ f : Nat → BitVec 8, (∀ p ∈ D, f p.1 = p.2) →
      {sw(nxt, f"(upd R {rd} (ldvf .{d['kind']} f {ea}))")}) :
    {sw(f'0x{pc:x}#64')} :=
  sr_havoc stx_{pc:08x} {lst(ks)} {rd} (accAddrs {ea} {wd}) (fun f => [bytesAt f {ea} {wd}])
    (fun f => ldvf .{d['kind']} f {ea}) 0
    (fun f g h => congrArg (· :: []) (List.map_congr_left fun j hj => h _ (mem_accAddrs (List.mem_range.mp hj))))
    rfl (by decide) (by decide) (by decide) (fun _ _ => trivial) hlive
    (fun m hm => by unfold stx_{pc:08x} ChainFacts; {cf(pc)}; exact ⟨hea, lpins{suf}_img (fun b _ => rfl)⟩)
    (by decide) (by decide) (fun _ => rfl)
    (fun _ x hx hr => by simp only [List.mem_cons, List.not_mem_nil, or_false] at hx; rcases hx with {alts} <;> first | rfl | exact absurd rfl hr)
    (fun _ => rfl) hk""")
    elif cls == 'store':
        segs.append(single)
        ea = f"({src(d['rs1'])} + {sx12(d['imm'])}).toNat"
        wd = d['width']
        ks = ks_of([d['rs1'], d['rs2']])
        ok = f'StOKb {ea}' if d['kind'] == 'sb' else f'StOK {ea} {wd}'
        thm.append(hdr('sl', pc) + f"""
    (hea : {ok})
    (hS : ∀ b ∈ accAddrs {ea} {wd}, S b)
    (hk : {sw(nxt, 'R', f"(writeLog Mt [({ea}, {wd}, {src(d['rs2'])})])")}) :
    {sw(f'0x{pc:x}#64')} :=
""" + step(f'stx_{pc:08x}', pc, ks, f'(accAddrs {ea} {wd})', '(fun a ha => outL_single _ ha)',
           'exact hea', 'rfl', hR(ks), hRo(ks), 'hk'))
    elif cls == 'br':
        A, B = src(d['rs1']), src(d['rs2'])
        cond = {'BEQ': f'{A} = {B}', 'BNE': f'{A} ≠ {B}', 'BLT': f'{A}.toInt < {B}.toInt',
                'BGE': f'{B}.toInt ≤ {A}.toInt', 'BLTU': f'{A}.toNat < {B}.toNat',
                'BGEU': f'{B}.toNat ≤ {A}.toNat'}[d['op']]
        gl = {'BEQ': 'guard_beq', 'BNE': 'guard_bne', 'BLT': 'guard_blt', 'BGE': 'guard_bge',
              'BLTU': 'guard_bltu', 'BGEU': 'guard_bgeu'}[d['op']]
        ks = ks_of([d['rs1'], d['rs2']])
        segs.append(tdef(f'stxT_{pc:08x}', f'.br bop.{d["op"]} true', d['rs1'], d['rs2'], d['imm'], 0))
        segs.append(tdef(f'stxF_{pc:08x}', f'.br bop.{d["op"]} false', d['rs1'], d['rs2'], d['imm'], 0))
        tgt = f'0x{d["tgt"]:x}#64'
        thm.append(hdr('sl', pc) + f"""
    (hT : {cond} → {sw(tgt)}) (hF : ¬ ({cond}) → {sw(nxt)}) :
    {sw(f'0x{pc:x}#64')} := by
  by_cases hc : {cond}
  · exact
""" + step(f'stxT_{pc:08x}', pc, ks, '[]', NIL, f'exact ({gl} _ _).2 hc', 'rfl',
           hR(ks), hRo(ks), '(hT hc)', '    ') + """
  · exact
""" + step(f'stxF_{pc:08x}', pc, ks, '[]', NIL, f'exact (guard_false ({gl} _ _)).2 hc',
           'rfl', hR(ks), hRo(ks), '(hF hc)', '    '))
    elif cls == 'ret':
        r = 1
        segs.append(tdef(f'stx_{pc:08x}', '.jr', r, 0, 0, 0))
        thm.append(hdr('sl', pc) + f"""
    (hal : (R {r}).toNat % 4 = 0) (hk : {sw(f'(R {r})')}) :
    {sw(f'0x{pc:x}#64')} :=
""" + step(f'stx_{pc:08x}', pc, [r], '[]', NIL,
           f'show (Sail.BitVec.update (R {r} + sign_extend (m := 64) (0x000#12)) 0 0#1).toNat % 4 = 0; '
           'rw [ret_tgt _ hal]; exact hal', '(ret_tgt _ hal)', hR([r]), hRo([r]), 'hk'))
    elif cls == 'obs':
        rd, rs1, rs2 = d['rd'], d['rs1'], d['rs2']
        A, B = src(rs1), src(rs2)
        val = f'zero_extend (m := 64) (bool_to_bit (zopz0zI_u {A} {B}))'
        ks = ks_of([rs1, rs2])
        ast = (f'instruction.RTYPE (regidx.Regidx 0x{rs2:02x}#5, regidx.Regidx 0x{rs1:02x}#5, '
               f'regidx.Regidx 0x{rd:02x}#5, rop.SLTU)')
        npc = f'(afterNextPC (afterPrelude c.σ) (0x{pc:x}#64))'

        def rx(r):
            if r == 0:
                return 'rX_bits_zero _'
            return (f'rX_bits_x{r} _ (R {r}) (by rw [get?_afterNextPC c.σ (0x{pc:x}#64) _ (by decide) (by decide)]; '
                    f'exact hRR ({r}, Iris.DFrac.own 1, R {r}) (by simp))')
        post = f'(sigma3_alu c.σ (0x{pc:x}#64) Register.x{rd} ({val}))'
        ex = (f'execute_rtype_sltu_char (regidx.Regidx 0x{rs2:02x}#5) (regidx.Regidx 0x{rs1:02x}#5) '
              f'(regidx.Regidx 0x{rd:02x}#5) {A} {B} {npc} {post}\n'
              f'        ({rx(rs1)})\n        ({rx(rs2)})\n'
              f'        (wX_bits_x{rd} _ ({val}))')
        code_s = ', '.join(f'0x{b:02x}#8' for b in bs)
        hb = '\n'.join(f'      have hb{i} := hMR (0x{pc + i:x}, .discard, 0x{bs[i]:02x}#8) (by simp [codeFoot])'
                       for i in range(4))
        thm.append(f"""open LeanRV64DExecutable LeanRV64DExecutable.Functions Sail in
/-- `{MN[pc]}` at `0x{pc:x}` (outside the block model: an observed ALU step). -/
""" + hdr('slO', pc) + f"""
    (hk : {sw(nxt, f"(upd R {rd} ({val}))")}) :
    {sw(f'0x{pc:x}#64')} :=
  sr_alu 0x{pc:x} [{code_s}] {rd} {lst(ks)} ({val})
    (aluStep_of_obs (by decide) (by decide)
      (fun q hq => by
        obtain ⟨k, hk, rfl⟩ := List.mem_map.mp hq
        exact (show ∀ k ∈ {lst(ks)}, 1 ≤ k ∧ k ≤ 31 by decide) k hk)
      (fun p hp => hlive _ (str_code_{pc:08x} p hp))
      (fun c hG hi hpc hRR hMR => by
      obtain ⟨vm, hmi⟩ := hG.minstret
{hb}
      obtain ⟨σ', i', hs, hi', hG', hmem, hobs⟩ :=
        stepObs_alu c.σ c.tick c.steps (0x{pc:x}#64) vm (0x{w:08x}#32)
          ({ast})
          Register.x{rd} ({val})
          {' '.join(f'(0x{b:02x}#8)' for b in bs)}
          hG hpc hmi (by apply BitVec.eq_of_toNat_eq; decide) (by apply BitVec.eq_of_toNat_eq; decide)
          (Vsa.Sim.DecodeTable.decode_{w:08x} (afterPrelude c.σ)
            (by rw [get?_afterPrelude c.σ _ (by decide)]; exact hG.misa)
            (by rw [get?_afterPrelude c.σ _ (by decide)]; exact hG.cur_privilege)
            (by rw [get?_afterPrelude c.σ _ (by decide)]; exact hG.mseccfg))
          ({ex})
          (by decide) (by decide) (by decide) (by decide) (by decide)
          hb0 hb1 hb2 hb3 (by decide) (by decide) (by decide) hi
      exact ⟨σ', i', vm, hs, hi', hG', hmem, hobs⟩))
    (str_code_{pc:08x}) (by decide) (by decide) rfl hk""")
    else:
        return None, None
    return segs, thm


def gen():
    unsupported, segs_all, thms_all, mods = [], [], [], set()
    for pc in PCS:
        segs, thms = emit(pc)
        if segs is None:
            unsupported.append(pc)
            continue
        segs_all.extend(segs)
        thms_all.extend(thms)
        mods.add(DEC[W[pc]])
    uns = ', '.join(f'`0x{pc:x}` {MN[pc]}' for pc in unsupported) or 'none'
    L = [HEADER, 'import VsaIris.Interp.StrCode', 'import VsaIris.Vsa.SymObs',
         'import Vsa.Sim.EnvNewSites', 'import Vsa.Sim.ExecuteAlu'] + \
        [f'import {m}' for m in sorted(mods)] + ['',
         f'/-! The string leaves\' step table, `0x{PCS[0]:x}` to `0x{PCS[-1]:x}` (see',
         f'`scripts/gen_str_steps.py`). No step lemma: {uns}. -/', '',
         'open LeanRV64DExecutable LeanRV64DExecutable.Functions Sail', '',
         'namespace Vsa.Sim', ''] + segs_all + ['', 'end Vsa.Sim', '',
         'namespace VsaIris.Sym', '',
         'open Vsa.Sim Vsa.MemRepr VsaIris.Inst VsaIris.MallocFast', ''] + \
        [t + '\n' for t in thms_all] + ['end VsaIris.Sym', '']
    return '\n'.join(L), unsupported


def main():
    text, unsupported = gen()
    p = ROOT / OUT
    if '--check' in sys.argv:
        if not p.exists() or p.read_text() != text:
            print(f'stale: {OUT}', file=sys.stderr)
            return 1
        return 0
    p.write_text(text)
    print(f'{len(PCS)} instructions; no step lemma: ' +
          (', '.join(f'0x{pc:x} {MN[pc]}' for pc in unsupported) or 'none'))
    return 0


if __name__ == '__main__':
    sys.exit(main())
