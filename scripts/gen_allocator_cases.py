#!/usr/bin/env python3
"""Generate owned source recursion from the existing 50-constructor table.

Run with ``--check`` to detect drift without rewriting the Lean module.
"""

import argparse
import difflib
import sys
from pathlib import Path

from scripts import gen_ih_clause as source

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "Vsa/Sim/AllocatorCases.lean"
OWNED = {
    "EvalE": "EvalAllocatorSupply",
    "ExecS": "ExecAllocatorSupply",
    "ExecSeq": "∀ copy, ExecSeqAllocatorSupply copy",
}
LEAVES = {
    "hInt": "EvalAllocatorSupply.int",
    "hStr": "EvalAllocatorSupply.str",
    "hBool": "EvalAllocatorSupply.bool",
    "hNull": "EvalAllocatorSupply.null",
    "hVar": "fun _ _ _ _ _ found => EvalAllocatorSupply.var found",
    "hSExpr": "fun _ _ _ _ _ _ _ child => ExecAllocatorSupply.expr child",
    "hSBlock": "fun _ _ _ _ _ _ _ _ allocation _ body => ExecAllocatorSupply.block allocation (body .blockBody)",
    "hSeqNil": "fun st d env copy => ExecSeqAllocatorSupply.nil copy st d env",
}
SEQUENCE_CASES = {"hSeqConsNormal": "seqConsNormal", "hSeqConsAbrupt": "seqConsAbrupt"}


def motive(relation: str) -> str:
    """Return the owned motive or an explicit auxiliary contract."""
    return f"m{relation}" if relation in OWNED else f"aux.m{relation}"


def atom_text(atom: source.Atom) -> str:
    """Render one constructor premise against the selected contracts."""
    return f"{motive(atom.relation)} {atom.args}"


def field_type(case: source.Case, *, other_binary: bool = False) -> str:
    """Retain all source premises and child contracts in a residual field."""
    lines = [f"∀ {case.binder_text},"]
    if other_binary:
        lines += ["  op ≠ .eq → op ≠ .ne →"]
    lines += [f"  {atom_text(child)} →" for child in case.children]
    conclusion = atom_text(case.conclusion)
    lines += [f"  {conclusion}"]
    return "\n".join(lines)


def render() -> str:
    """Generate the residual record and all nine source induction roots."""
    cases, signatures = source.load_cases()
    lines = [
        "import Vsa.Sim.AllocatorSupplyLeaf",
        "import Vsa.Sim.EqAllocatorSupply",
        "import Vsa.Sim.ExecSeqAllocatorSupply",
        "import Vsa.Sim.BlockAllocatorSupply",
        "",
        "/-! Generated by `python3 -B -m scripts.gen_allocator_cases`.",
        "Constructor binders and order come from `term_sim_of_cases`.",
        "Evaluator, statement, and sequence motives retain allocator ownership.",
        "Six auxiliary contracts remain explicit parameters. -/",
        "",
        "open LeanRV64DExecutable Vsa Vsa.MemRepr Vsa.RuntimeRepr Vsa.While",
        "",
        "namespace Vsa.Sim.AllocatorCases",
        'local notation "SpecSt" => Vsa.While.St',
        "",
        "/-- Contracts for the six auxiliary source relations. -/",
        "structure AuxMotives where",
    ]
    for relation in source.RELATIONS:
        binders = signatures[relation]
        binder_text = " ".join(f"({' '.join(names)} : {ty})" for names, ty in binders)
        if relation not in OWNED:
            lines.append(f"  m{relation} : ∀ {binder_text}, Prop")
    for relation, contract in OWNED.items():
        binders = signatures[relation]
        binder_text = " ".join(f"({' '.join(names)} : {ty})" for names, ty in binders)
        args = " ".join(name for names, _ in binders[:-1] for name in names)
        lines += [
            "",
            f"/-- Owned source-induction contract for `{relation}`. -/",
            f"def m{relation} {binder_text} : Prop := {contract} {args}",
        ]
    lines += [
        "",
        "/-- Remaining source cases. Literal, lookup, expression-statement,",
        "equality, block statements, and all sequence constructors use checked owned proofs. -/",
        "structure Residuals (aux : AuxMotives) : Prop where",
    ]
    for case in cases:
        if case.name in LEAVES or case.name in SEQUENCE_CASES:
            continue
        partial = case.name == "hBinary"
        name = f"{case.name}Other" if partial else case.name
        lines += [
            f"  /-- `{case.constructor}` consumes its source premises and recursive contracts. -/",
            f"  {name} :",
            source.indent(
                field_type(case, other_binary=case.name == "hBinary"),
                4,
            ),
        ]
    binary = next(case for case in cases if case.name == "hBinary")
    binary_args = " ".join(binary.binder_names)
    lines += [
        "",
        "/-- Equality and inequality discharge their source binary branches. -/",
        "theorem Residuals.binary {aux : AuxMotives} (R : Residuals aux) :",
        source.indent(field_type(binary), 4) + " := by",
        f"  intro {binary_args} left right",
        "  by_cases heq : op = .eq",
        "  · subst op",
        "    exact EvalAllocatorSupply.binary_eqne .eq a a_1 a_2 left right",
        "  by_cases hne : op = .ne",
        "  · subst op",
        "    exact EvalAllocatorSupply.binary_eqne .ne a a_1 a_2 left right",
        f"  exact R.hBinaryOther {binary_args} heq hne left right",
    ]
    for case in cases:
        if case.name not in SEQUENCE_CASES:
            continue
        args = " ".join(case.binder_names)
        children = "head tail" if case.name == "hSeqConsNormal" else "head"
        supplier = (
            "ExecSeqAllocatorSupply.closure_consNormal a a_1 head (tail .closureBody)"
            if case.name == "hSeqConsNormal"
            else "ExecSeqAllocatorSupply.closure_consAbrupt a_1 head"
        )
        interp_supplier = (
            "ExecSeqAllocatorSupply.interp_consNormal a a_1 head (tail .interpRun)"
            if case.name == "hSeqConsNormal"
            else "ExecSeqAllocatorSupply.interp_consAbrupt a_1"
        )
        block_supplier = (
            "ExecSeqAllocatorSupply.block_consNormal a a_1 head (tail .blockBody)"
            if case.name == "hSeqConsNormal"
            else "ExecSeqAllocatorSupply.block_consAbrupt a_1 head"
        )
        lines += [
            "",
            "/-- Checked proofs supply the source constructor for every physical sequence copy. -/",
            f"theorem {SEQUENCE_CASES[case.name]} :",
            source.indent(field_type(case), 4) + " := by",
            f"  intro {args} {children} copy",
            "  cases copy with",
            f"  | closureBody => exact {supplier}",
            f"  | interpRun => exact {interp_supplier}",
            f"  | blockBody => exact {block_supplier}",
        ]
    for relation in source.RELATIONS:
        binders = signatures[relation]
        binder_text = " ".join(f"({' '.join(names)} : {ty})" for names, ty in binders)
        args = " ".join(name for names, _ in binders for name in names)
        lines += [
            "",
            f"/-- Assemble the `{relation}` contract by source induction. -/",
            f"theorem Residuals.on{relation} {{aux : AuxMotives}} (R : Residuals aux)",
            f"    {binder_text} :",
            f"    {motive(relation)} {args} :=",
            f"  @{relation}.rec",
            "    " + " ".join(motive(rel) for rel in source.RELATIONS),
        ]
        for case in cases:
            term = LEAVES.get(case.name, SEQUENCE_CASES.get(case.name))
            if term is None:
                method = "binary" if case.name == "hBinary" else case.name
                term = f"R.{method}"
            lines.append(f"    ({term})")
        lines.append(f"    {args}")
    lines += ["", "#print axioms Residuals.binary"]
    lines += [f"#print axioms {method}" for method in SEQUENCE_CASES.values()]
    lines += [f"#print axioms Residuals.on{relation}" for relation in source.RELATIONS]
    lines += ["", "end Vsa.Sim.AllocatorCases", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    """Write the generated module, or report drift without changing it."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args(argv)
    expected = render()
    if args.check:
        actual = args.output.read_text() if args.output.exists() else ""
        if actual != expected:
            sys.stderr.writelines(
                difflib.unified_diff(
                    actual.splitlines(True),
                    expected.splitlines(True),
                    fromfile=str(args.output),
                    tofile="generated",
                )
            )
            return 1
        print(f"{args.output}: up to date")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(expected)
        print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
