#!/usr/bin/env python3
"""Generate VsaIris/Vsa/MallocFastCode.lean: the code bytes of _malloc_r's
top-split fast paths (plus malloc's wrapper, the lock hooks, and the
_impure_ptr word the wrapper loads), as ONE list `pathText`, the predicate
`PathLoaded m` (every listed byte present with its value), and one
`path_at_<pc>` lemma per instruction in the shape `chain_facts` consumes.

Usage: python3 scripts/gen_malloc_path_code.py
"""
import re, pathlib
W = {}
for l in open('experiments/disasm.txt'):
    m = re.match(r'^\s+([0-9a-f]+):\t([0-9a-f]{8})\s+\t', l)
    if m: W[int(m.group(1), 16)] = int(m.group(2), 16)

def rng(a, b): return list(range(a, b + 1, 4))
PCS = (rng(0x80004790, 0x80004798) + rng(0x800047a8, 0x800047f0) + rng(0x8000485c, 0x80004880)
       + rng(0x80004830, 0x8000483c) + rng(0x800048ec, 0x800048f8) + rng(0x80004968, 0x80004974)
       + rng(0x80004a2c, 0x80004a44) + rng(0x80004be8, 0x80004bec) + rng(0x80004bf0, 0x80004c1c)
       + rng(0x80004c60, 0x80004c68) + rng(0x80004d64, 0x80004d74)
       + [0x80005068, 0x8000506c, 0x80005070, 0x80005074, 0x80006fe0, 0x80006ff8])
PCS = sorted(set(PCS))
IMPURE = (0x8001b970, [0x38, 0xb5, 0x01, 0x80, 0, 0, 0, 0])

text = []
for pc in PCS:
    w = W[pc]
    for i in range(4): text.append((pc + i, (w >> (8 * i)) & 0xff))
for i, b in enumerate(IMPURE[1]): text.append((IMPURE[0] + i, b))

CH = 16
chunks = [text[i:i + CH] for i in range(0, len(text), CH)]
where = {}
for j, c in enumerate(chunks):
    for (a, b) in c: where[a] = j

def mem_proof(a, b):
    j = where[a]
    pf = f'List.mem_append_left _ (by decide : ((0x{a:x} : Nat), (0x{b:02x}#8 : BitVec 8)) ∈ pathChunk{j})'
    if j == len(chunks) - 1:
        pf = f'(by decide : ((0x{a:x} : Nat), (0x{b:02x}#8 : BitVec 8)) ∈ pathChunk{j})'
    for i in range(j - 1, -1, -1):
        pf = f'List.mem_append_right pathChunk{i} ({pf})'
    return pf

L = []
L.append('import Vsa.Elf\nimport Vsa.MemRepr\n')
L.append('/-! Code bytes of `_malloc_r`\'s top-split fast paths, `malloc`\'s wrapper, the\n'
         'lock hooks, and the `_impure_ptr` word (generated by\n'
         '`scripts/gen_malloc_path_code.py`; do not hand-edit). -/\n')
L.append('namespace VsaIris.MallocFast\n')
for j, c in enumerate(chunks):
    L.append(f'def pathChunk{j} : List (Nat × BitVec 8) :=')
    L.append('  [' + ', '.join(f'(0x{a:x}, 0x{b:02x}#8)' for a, b in c) + ']\n')
L.append('/-- The allocator text the fast paths read: `(address, byte)`. -/')
body = f'pathChunk{len(chunks) - 1}'
for j in range(len(chunks) - 2, -1, -1):
    body = f'pathChunk{j} ++ ({body})'
L.append('def pathText : List (Nat × BitVec 8) :=\n  ' + body + '\n')
L.append('/-- Every listed byte is present with its value. -/')
L.append('def PathLoaded (mem : Std.ExtHashMap Nat (BitVec 8)) : Prop :=')
L.append('  ∀ p ∈ pathText, mem[p.1]? = some p.2\n')
for pc in PCS:
    w = W[pc]
    bs = [(w >> (8 * i)) & 0xff for i in range(4)]
    L.append(f'theorem path_at_{pc:08x} {{mem : Std.ExtHashMap Nat (BitVec 8)}} (h : PathLoaded mem) :')
    L.append('    ' + ' ∧\n    '.join(f'mem[(0x{pc + i:x} : Nat)]? = some (0x{bs[i]:02x} : BitVec 8)' for i in range(4)) + ' :=')
    L.append('  ⟨' + ',\n   '.join(f'h _ ({mem_proof(pc + i, bs[i])})' for i in range(4)) + '⟩\n')
L.append('/-- The `_impure_ptr` word (`0x8001b538`). -/')
L.append('theorem path_impure {mem : Std.ExtHashMap Nat (BitVec 8)} (h : PathLoaded mem) :')
a0, bs = IMPURE
L.append('    ' + ' ∧\n    '.join(f'mem[(0x{a0 + i:x} : Nat)]? = some (0x{bs[i]:02x} : BitVec 8)' for i in range(8)) + ' :=')
L.append('  ⟨' + ',\n   '.join(f'h _ ({mem_proof(a0 + i, bs[i])})' for i in range(8)) + '⟩\n')
for pc in (0x800047cc, 0x80004874, 0x80004c10):
    w = W[pc]
    bs = [(w >> (8 * i)) & 0xff for i in range(4)]
    L.append(f'/-- The bytes of the `jal` at `0x{pc:x}` are in the text. -/')
    L.append(f'theorem jal_bytes_{pc:08x} :')
    L.append('    ' + ' ∧\n    '.join(f'((0x{pc + i:x} : Nat), (0x{bs[i]:02x}#8 : BitVec 8)) ∈ pathText' for i in range(4)) + ' :=')
    L.append('  ⟨' + ',\n   '.join(mem_proof(pc + i, bs[i]) for i in range(4)) + '⟩\n')
L.append('end VsaIris.MallocFast\n')
pathlib.Path('VsaIris/Vsa/MallocFastCode.lean').write_text('\n'.join(L))
print(len(PCS), 'instructions,', len(text), 'bytes,', len(chunks), 'chunks')
