#!/usr/bin/env python3
"""Generate per-function code-region predicates + fetch-hypothesis lemmas
(PLAN-InterpSim §Tooling, disassembly ingestion).

For a function F in experiments/disasm.txt, emits Vsa/Sim/Code/<F>.lean:

- `def <f>Chunk<i> (mem) : Prop` — conjunction of the byte facts
  `mem[addr]? = some b` for a 16-instruction chunk (64 conjuncts), keeping
  projection depth bounded.
- `def <F>Loaded (mem) : Prop` — conjunction of the chunks.
- per instruction site: `theorem <f>_at_<addr> (h : <F>Loaded mem) :
  mem[a]? = some b0 ∧ mem[a+1]? = some b1 ∧ mem[a+2]? = some b2 ∧
  mem[a+3]? = some b3` proved by conjunction projections — exactly the four
  byte hypotheses the step-characterization lemmas consume (hb0..hb3, with
  the word reassembling as (((b3.append b2).append b1).append b0)).

The predicates enter the final `Loaded`/`Layout` as assumptions (M6); no
evaluation of the 138 KB image is ever needed at build time.

Usage: python3 experiments/gen_code_lemmas.py strlen [strcmp ...]
"""
import re, sys, pathlib

CHUNK = 16  # instructions per chunk (64 byte-conjuncts)

func_re = re.compile(r"^([0-9a-f]{16}) <(.+)>:$")
inst_re = re.compile(r"^\s+([0-9a-f]+):\t([0-9a-f]{8})\s+\t(\S+)(?:\s+(.*))?$")


def parse(path="experiments/disasm.txt"):
    funcs, cur = {}, None
    for line in open(path):
        m = func_re.match(line)
        if m:
            cur = m.group(2)
            funcs[cur] = []
            continue
        m = inst_re.match(line)
        if m and cur is not None:
            funcs[cur].append((int(m.group(1), 16), int(m.group(2), 16)))
    return funcs


def lean_ident(name):
    return re.sub(r"[^A-Za-z0-9_]", "_", name)


def emit(name, insts):
    f = lean_ident(name)
    F = f[0].upper() + f[1:]
    chunks = [insts[i:i + CHUNK] for i in range(0, len(insts), CHUNK)]
    L = []
    L.append("import Vsa.Elf\n")
    L.append(f"/-! Code-region predicate + fetch-hypothesis lemmas for `{name}`\n"
             f"(generated by experiments/gen_code_lemmas.py — do not hand-edit).\n"
             f"{len(insts)} instructions at "
             f"[0x{insts[0][0]:x}, 0x{insts[-1][0]+4:x}). -/\n")
    L.append("open Std (ExtHashMap)\n")
    L.append("namespace Vsa.Sim.Code\n")

    def byte_facts(addr, word):
        return [(addr + k, (word >> (8 * k)) & 0xFF) for k in range(4)]

    for ci, ch in enumerate(chunks):
        conj = " ∧\n  ".join(
            f"mem[(0x{a:x} : Nat)]? = some (0x{b:02x} : BitVec 8)"
            for addr, word in ch for a, b in byte_facts(addr, word))
        L.append(f"def {f}Chunk{ci} (mem : ExtHashMap Nat (BitVec 8)) : Prop :=\n  {conj}\n")

    top = " ∧ ".join(f"{f}Chunk{ci} mem" for ci in range(len(chunks)))
    L.append(f"/-- The whole `{name}` code region is loaded. -/\n"
             f"def {F}Loaded (mem : ExtHashMap Nat (BitVec 8)) : Prop :=\n  {top}\n")

    # chunk projections out of the top-level conjunction
    for ci in range(len(chunks)):
        proj = "h" if len(chunks) == 1 else (
            "h." + ".".join(["2"] * ci + (["1"] if ci < len(chunks) - 1 else [])))
        proj = proj.rstrip(".")
        L.append(f"theorem {f}_chunk{ci} {{mem : ExtHashMap Nat (BitVec 8)}}\n"
                 f"    (h : {F}Loaded mem) : {f}Chunk{ci} mem := {proj}\n")

    # per-site lemmas project 4 consecutive byte facts out of the chunk
    for ci, ch in enumerate(chunks):
        for ii, (addr, word) in enumerate(ch):
            bs = byte_facts(addr, word)
            concl = " ∧\n      ".join(
                f"mem[(0x{a:x} : Nat)]? = some (0x{b:02x} : BitVec 8)" for a, b in bs)
            nconj = 4 * len(ch)

            def proj(k):  # k-th conjunct (0-based) of an nconj-conjunction
                i = 4 * ii + k
                if i == nconj - 1:
                    return "hc" + "".join(".2" for _ in range(i))
                return "hc" + "".join(".2" for _ in range(i)) + ".1"

            parts = ", ".join(proj(k) for k in range(4))
            L.append(f"theorem {f}_at_{addr:x} {{mem : ExtHashMap Nat (BitVec 8)}}\n"
                     f"    (h : {F}Loaded mem) :\n      {concl} :=\n"
                     f"  have hc := {f}_chunk{ci} h\n  ⟨{parts}⟩\n")

    L.append("end Vsa.Sim.Code\n")
    out = pathlib.Path(f"Vsa/Sim/Code/{F}.lean")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L))
    print(f"wrote {out} ({len(insts)} sites, {len(chunks)} chunks)")


if __name__ == "__main__":
    funcs = parse()
    for name in sys.argv[1:]:
        if name not in funcs:
            sys.exit(f"function {name!r} not in disasm (have e.g. "
                     f"{list(funcs)[:5]})")
        emit(name, funcs[name])
