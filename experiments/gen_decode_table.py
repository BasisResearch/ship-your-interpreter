#!/usr/bin/env python3
"""Regenerate Vsa/Sim/DecodeTable/Batch*.lean from experiments/decode_ast_dump.txt.

Pipeline (PLAN-InterpSim.md §Tooling):
1. python3 experiments/disasm_census.py
2. python3 experiments/disasm_reachable.py
3. lake env lean --run experiments/M2_decode_ast_dump.lean > experiments/decode_ast_dump.txt
4. python3 experiments/gen_decode_table.py
5. lake build Vsa.Sim.DecodeTable

Template stabilized in Vsa/Sim/DecodePilot.lean (uniform across all 65
reachable mnemonics); statements' ASTs extracted by evaluation (discovery
only — every lemma is kernel-checked at build).
"""
import os

asts = {}
for line in open('experiments/decode_ast_dump.txt'):
    if ';OK;' not in line:
        continue
    w, st, ast = line.strip().split(';', 2)
    asts[w] = ' '.join(ast.split())
words = sorted(asts)
NB = 16
per = (len(words) + NB - 1) // NB
hdr = '''import Vsa.Elf
import Vsa.Sim.InitValues

/-! Decode table batch {nn}/16 (generated by experiments/gen_decode_table.py —
regenerate, do not hand-edit). One lemma per unique 32-bit instruction word
reachable from `interp_run` (PLAN-InterpSim.md Layer 0 item 4), uniform
template stabilized in Vsa/Sim/DecodePilot.lean. -/

open LeanRV64DExecutable LeanRV64DExecutable.Functions Sail ConcurrencyInterfaceV1 Vsa
open Register

set_option maxHeartbeats 16000000
set_option maxRecDepth 1000000
set_option linter.unusedSimpArgs false

namespace Vsa.Sim.DecodeTable

'''
TEMPLATE = '''theorem decode_{w}
    (σ : SequentialState RegisterType trivialChoiceSource)
    (_hmisa : σ.regs.get? Register.misa =
      some ((Vsa.Sim.initMisa) : RegisterType Register.misa))
    (hpriv : σ.regs.get? Register.cur_privilege =
      some (Privilege.Machine : RegisterType Register.cur_privilege))
    (hsec : σ.regs.get? Register.mseccfg =
      some ((0#64) : RegisterType Register.mseccfg)) :
    (ext_decode 0x{w}#32).run σ =
      .ok ({ast}) σ := by
  simp only [ext_decode, encdec_backwards]
  simp_all [simp_sail, bind, EStateM.bind, EStateM.run, pure, EStateM.pure,
    currentlyEnabled, hartSupports, get, getThe, MonadStateOf.get, EStateM.get,
    get_xLPE, readReg, Vsa.Sim.initMisa]
  simp +decide [encdec_reg_backwards_matches, encdec_iop_backwards_matches,
    encdec_bop_backwards_matches, encdec_uop_backwards_matches,
    encdec_csrop_backwards_matches, bool_bit_backwards_matches,
    width_enc_backwards_matches,
    encdec_reg_backwards, encdec_iop_backwards, encdec_bop_backwards,
    encdec_uop_backwards, encdec_csrop_backwards, encdec_cbop_backwards,
    encdec_sop_backwards, bool_bit_backwards, width_enc_backwards,
    EStateM.bind, pure, EStateM.pure]
  repeat' apply And.intro
  all_goals first
    | rfl
    | (apply BitVec.eq_of_toNat_eq; decide)
    | decide
    | omega
'''
os.makedirs('Vsa/Sim/DecodeTable', exist_ok=True)
for b in range(NB):
    chunk = words[b*per:(b+1)*per]
    if not chunk:
        break
    nn = f"{b+1:02d}"
    with open(f'Vsa/Sim/DecodeTable/Batch{nn}.lean', 'w') as f:
        f.write(hdr.format(nn=nn))
        f.write('\n'.join(TEMPLATE.format(w=w, ast=asts[w]) for w in chunk))
        f.write('\nend Vsa.Sim.DecodeTable\n')
with open('Vsa/Sim/DecodeTable.lean', 'w') as f:
    for b in range(NB):
        f.write(f'import Vsa.Sim.DecodeTable.Batch{b+1:02d}\n')
    f.write('\n/-! Full decode table for the reachable code (generated). -/\n')
print(f"generated {NB} batches, {per} words/batch, {len(words)} total")
