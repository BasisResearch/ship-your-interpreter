#!/usr/bin/env python3
"""Regenerate Vsa/Sim/DecodeTable/Batch*.lean from experiments/decode_ast_dump.txt.

Pipeline (PLAN-InterpSim.md §Tooling):
1. python3 experiments/disasm_census.py
2. python3 experiments/disasm_reachable.py
3. lake env lean --run experiments/M2_decode_ast_dump.lean > experiments/decode_ast_dump.txt
4. python3 experiments/gen_decode_table.py
5. lake build Vsa.Sim.DecodeTable

Template stabilized in Vsa/Sim/DecodePilot.lean (uniform across all 65
reachable mnemonics); statements' ASTs extracted by evaluation (discovery
only — every lemma is kernel-checked at build).
"""
import os
import sys

# --legacy emits the old (slow) simp_all/simp+decide template; default emits the
# fast "grounding simp only + rfl" template that reuses the splitters realized
# once in Vsa/Sim/DecodeTable/DecodeCommon.lean (7x faster per file; see
# experiments/decode-template-pilot.md).
LEGACY = '--legacy' in sys.argv[1:]


def write_if_changed(path, content):
    """Preserve build artifacts when generated source is unchanged."""
    try:
        with open(path) as existing:
            if existing.read() == content:
                return
    except FileNotFoundError:
        pass
    with open(path, 'w') as output:
        output.write(content)

asts = {}
for line in open('experiments/decode_ast_dump.txt'):
    if ';OK;' not in line:
        continue
    w, st, ast = line.strip().split(';', 2)
    asts[w] = ' '.join(ast.split())
words = sorted(asts)
NB = 16
PARTS_PER_BATCH = 32
per = (len(words) + NB - 1) // NB
hdr_common_import = '' if LEGACY else 'import Vsa.Sim.DecodeTable.DecodeCommon\n'
hdr = '''import Vsa.Elf
import Vsa.Sim.InitValues
''' + hdr_common_import + '''
/-! Decode table batch {nn}/16, part {pp}/{parts}
(generated by experiments/gen_decode_table.py —
regenerate, do not hand-edit). One lemma per unique 32-bit instruction word
reachable from `interp_run` (PLAN-InterpSim.md Layer 0 item 4), uniform
template stabilized in Vsa/Sim/DecodePilot.lean. -/

open LeanRV64DExecutable LeanRV64DExecutable.Functions Sail ConcurrencyInterfaceV1 Vsa
open Register

set_option maxHeartbeats 16000000
set_option maxRecDepth 1000000
set_option linter.unusedSimpArgs false

namespace Vsa.Sim.DecodeTable

'''
# Fast template: one grounding `simp only` (reads pinned to constants, whole
# monadic tower reduced to a ground term threaded on σ) then `rfl`. The
# `currentlyEnabled` / `hartSupports` match splitters this `simp only` needs are
# realized once in DecodeCommon (imported above), so per-lemma cost is ~0.4 s
# instead of ~2.5 s. `rfl` closes every reachable instruction class (verified:
# JAL/ITYPE/UTYPE/JALR/LOAD/STORE/BTYPE/ADDIW/SHIFTIOP/SHIFTIWOP/RTYPE/RTYPEW).
TEMPLATE_FAST = '''theorem decode_{w}
    (σ : SequentialState RegisterType trivialChoiceSource)
    (_hmisa : σ.regs.get? Register.misa =
      some ((Vsa.Sim.initMisa) : RegisterType Register.misa))
    (hpriv : σ.regs.get? Register.cur_privilege =
      some (Privilege.Machine : RegisterType Register.cur_privilege))
    (hsec : σ.regs.get? Register.mseccfg =
      some ((0#64) : RegisterType Register.mseccfg)) :
    (ext_decode 0x{w}#32).run σ =
      .ok ({ast}) σ := by
  simp only [ext_decode, encdec_backwards, EStateM.run, bind, EStateM.bind,
    pure, EStateM.pure, PreSail.readReg, get, getThe, MonadStateOf.get, EStateM.get,
    currentlyEnabled, hartSupports, get_xLPE, Vsa.Sim.initMisa,
    _hmisa, hpriv, hsec]
  rfl
'''

TEMPLATE_LEGACY = '''theorem decode_{w}
    (σ : SequentialState RegisterType trivialChoiceSource)
    (_hmisa : σ.regs.get? Register.misa =
      some ((Vsa.Sim.initMisa) : RegisterType Register.misa))
    (hpriv : σ.regs.get? Register.cur_privilege =
      some (Privilege.Machine : RegisterType Register.cur_privilege))
    (hsec : σ.regs.get? Register.mseccfg =
      some ((0#64) : RegisterType Register.mseccfg)) :
    (ext_decode 0x{w}#32).run σ =
      .ok ({ast}) σ := by
  simp only [ext_decode, encdec_backwards]
  simp_all [simp_sail, bind, EStateM.bind, EStateM.run, pure, EStateM.pure,
    currentlyEnabled, hartSupports, get, getThe, MonadStateOf.get, EStateM.get,
    get_xLPE, readReg, Vsa.Sim.initMisa]
  simp +decide [encdec_reg_backwards_matches, encdec_iop_backwards_matches,
    encdec_bop_backwards_matches, encdec_uop_backwards_matches,
    encdec_csrop_backwards_matches, bool_bit_backwards_matches,
    width_enc_backwards_matches,
    encdec_reg_backwards, encdec_iop_backwards, encdec_bop_backwards,
    encdec_uop_backwards, encdec_csrop_backwards, encdec_cbop_backwards,
    encdec_sop_backwards, bool_bit_backwards, width_enc_backwards,
    EStateM.bind, pure, EStateM.pure]
  repeat' apply And.intro
  all_goals first
    | rfl
    | (apply BitVec.eq_of_toNat_eq; decide)
    | decide
    | omega
'''

TEMPLATE = TEMPLATE_LEGACY if LEGACY else TEMPLATE_FAST
os.makedirs('Vsa/Sim/DecodeTable', exist_ok=True)
for b in range(NB):
    chunk = words[b*per:(b+1)*per]
    if not chunk:
        break
    nn = f"{b+1:02d}"
    part_size = (len(chunk) + PARTS_PER_BATCH - 1) // PARTS_PER_BATCH
    part_modules = []
    for p in range(PARTS_PER_BATCH):
        part = chunk[p*part_size:(p+1)*part_size]
        if not part:
            break
        pp = f"{p+1:02d}"
        module = f"Vsa.Sim.DecodeTable.Batch{nn}Part{pp}"
        part_modules.append(module)
        content = hdr.format(nn=nn, pp=pp, parts=PARTS_PER_BATCH)
        content += '\n'.join(TEMPLATE.format(w=w, ast=asts[w]) for w in part)
        content += '\nend Vsa.Sim.DecodeTable\n'
        write_if_changed(f'Vsa/Sim/DecodeTable/Batch{nn}Part{pp}.lean', content)
    content = ''.join(f'import {module}\n' for module in part_modules)
    content += f'\n/-! Generated umbrella for decode batch {nn}/16. -/\n'
    write_if_changed(f'Vsa/Sim/DecodeTable/Batch{nn}.lean', content)
content = ''.join(
    f'import Vsa.Sim.DecodeTable.Batch{b+1:02d}\n' for b in range(NB)
)
content += 'import Vsa.Sim.DecodeTable.Batch17\n'
content += '\n/-! Full decode table for the reachable code, plus the exit-path Batch17. -/\n'
write_if_changed('Vsa/Sim/DecodeTable.lean', content)
print(
    f"generated {NB} batches × {PARTS_PER_BATCH} parts, "
    f"at most {(per + PARTS_PER_BATCH - 1) // PARTS_PER_BATCH} words/part, "
    f"{len(words)} total"
)
