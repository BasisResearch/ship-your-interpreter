#!/usr/bin/env python3
"""gen_assembly_skeleton.py — t6: the RUN-1 assembly skeleton.

Parses `TermResidualsCore` (Vsa/Sim/TermAssembly.lean) and emits

  * `Vsa/Sim/rows/AssemblySkeleton.lean` — one named HOLE (`Skel<Field>`
    abbrev, type = the field's type verbatim) per field, plus the total
    assembler `termResidualsCore_of_skeleton` consuming all holes and
    building the record.  Elaborating the file PROVES every hole type
    matches its field TODAY; when RUN 1 swaps a hole for its supplier, any
    supplier↔field marshalling gap surfaces at THAT field, not at RUN-2
    assembly time.
  * `experiments/assembly_skeleton.tsv` — the visible work-list: one row per
    field (name, supplier note from the doc comment, status=hole).

Usage: python3 experiments/gen_assembly_skeleton.py [--no-verify]
"""
import re
import subprocess
import sys

SRC = "Vsa/Sim/TermAssembly.lean"
OUT = "Vsa/Sim/rows/AssemblySkeleton.lean"
TSV = "experiments/assembly_skeleton.tsv"


def parse():
    lines = open(SRC).read().splitlines()
    # structure extent
    start = next(i for i, l in enumerate(lines)
                 if l.startswith("structure TermResidualsCore"))
    end = next(i for i in range(start + 1, len(lines))
               if lines[i] and not lines[i].startswith(" ")
               and not lines[i].startswith("--"))
    # opens from the file header (verbatim)
    opens = [l for l in lines[:start]
             if l.startswith("open ") or l.startswith("local notation")]
    fields, doc, i = [], [], start + 1
    field_re = re.compile(r"^  (h\w+) :\s*(.*)$")
    while i < end:
        l = lines[i]
        if l.strip().startswith("/--"):
            doc = [l.strip()[3:].strip()]
            while not lines[i].rstrip().endswith("-/"):
                i += 1
                doc.append(lines[i].strip())
            doc[-1] = doc[-1][:-2].strip() if doc[-1].endswith("-/") else doc[-1]
            i += 1
            continue
        m = field_re.match(l)
        if m:
            name, ty = m.group(1), [m.group(2)]
            i += 1
            # continuation lines: deeper indentation, not a new field/doc
            while i < end and lines[i].startswith("    ") \
                    and not lines[i].strip().startswith("/--"):
                ty.append(lines[i].strip())
                i += 1
            fields.append((name, " ".join(t for t in ty if t).strip(),
                           " ".join(doc).replace("\t", " ")))
            doc = []
            continue
        i += 1
    return opens, fields


def emit(opens, fields):
    L = []
    A = L.append
    A("import Vsa.Sim.TermAssembly")
    A("")
    A("/-!")
    A("# t6 — the RUN-1 assembly skeleton for `TermResidualsCore`")
    A("")
    A(f"GENERATED by `experiments/gen_assembly_skeleton.py` from `{SRC}`")
    A("(regenerate after any field change; do not hand-edit).")
    A("")
    A(f"One named HOLE per field ({len(fields)} fields) + the total assembler.")
    A("Elaborating this file proves every hole type matches its field; RUN 1")
    A("replaces holes with suppliers ONE FIELD AT A TIME, so each")
    A("supplier↔field marshalling gap surfaces at its own field, visibly,")
    A("instead of at RUN-2 assembly.  Work-list: `experiments/assembly_skeleton.tsv`.")
    A("-/")
    A("")
    for o in opens:
        A(o)
    A("")
    A("set_option linter.unusedVariables false")
    A("")
    A("namespace Vsa.Sim.TermAssembly.Skel")
    A("")
    for name, ty, doc in fields:
        cap = name[0].upper() + name[1:]
        first = doc.split(".  ")[0] if doc else "(no supplier note)"
        A(f"/-- HOLE `{name}` — {first}. -/")
        A(f"abbrev Skel{cap} (L : Layout) : Prop :=")
        A(f"  {ty}")
        A("")
    A("/-- The total assembler: all holes ⟶ the record.  The one theorem RUN 1")
    A("keeps green while swapping holes for suppliers. -/")
    A("def termResidualsCore_of_skeleton (L : Layout)")
    for name, _, _ in fields:
        cap = name[0].upper() + name[1:]
        A(f"    ({name} : Skel{cap} L)")
    A("    : TermResidualsCore L :=")
    A("  { " + ", ".join(f"{n} := {n}" for n, _, _ in fields) + " }")
    A("")
    A("end Vsa.Sim.TermAssembly.Skel")
    open(OUT, "w").write("\n".join(L) + "\n")
    with open(TSV, "w") as f:
        f.write("field\tstatus\tsupplier_note\n")
        for name, _, doc in fields:
            f.write(f"{name}\thole\t{doc[:220]}\n")
    print(f"wrote {OUT} ({len(fields)} holes) + {TSV}")


def main():
    opens, fields = parse()
    emit(opens, fields)
    if "--no-verify" not in sys.argv:
        r = subprocess.run(["lake", "env", "lean", OUT],
                           capture_output=True, text=True)
        sys.stdout.write(r.stdout[-1500:])
        if r.returncode != 0:
            sys.stderr.write(r.stderr[-3000:])
            sys.exit(f"VERIFY FAILED: {OUT}")
        print("skeleton verified: lake env lean OK")


if __name__ == "__main__":
    main()
